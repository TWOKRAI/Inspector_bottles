# -*- coding: utf-8 -*-
"""Фикстура `declarations_snapshot` действительно ПОДКЛЮЧЕНА к тестам этого модуля.

**Почему отдельный тест на проводку, а не «и так видно».** Механизм снимка и
возврата стерегут hazard-тесты в ``modules/tests/test_declarations_registry_hazards.py``
— но они зовут ``restore(state)`` руками, с комментарием «то же, что делает
``declarations_snapshot`` в teardown». Это тест НА ФЕЙКЕ: он доказывает, что
механизм работает, если его позвать, и молчит о том, зовёт ли его кто-нибудь.

Измерено, а не предположено (матрица инъекций Ф0, строка B): снятие ``autouse``
у фикстуры в обоих conftest'ах даёт **ноль** красных на прогоне из 2852 тестов —
включая приёмку независимости порядка и стража сессии. Предохранитель существовал
без единого сторожа: сегодня его целиком прикрывают соседи (``TypeError`` на голый
вызов не даёт стереть реестр, а страж сессии ловит утечку объявлением), и его
собственная поломка была бы невидима до появления первого теста, который объявит
метрику и не приберёт.

``request.fixturenames`` содержит имя фикстуры ровно тогда, когда она подключена
к ЭТОМУ тесту — сам тест её не запрашивает, значит попасть туда она может только
как ``autouse``. Проверка дешёвая и поведенческая: она спрашивает у pytest, что он
реально собрал, а не читает conftest глазами.
"""

from __future__ import annotations


def test_declarations_snapshot_is_wired_as_autouse_here(request) -> None:
    """Фикстура снимка накрывает тесты `process_module`, а не просто существует."""
    assert "declarations_snapshot" in request.fixturenames, (
        "фикстура declarations_snapshot не подключена к тестам process_module: "
        "тест её не запрашивал, и попасть в fixturenames она могла только как autouse. "
        "Без неё объявление, оставленное любым тестом модуля, доедет до конца сессии — "
        f"собранные фикстуры: {sorted(request.fixturenames)!r}"
    )

# -*- coding: utf-8 -*-
"""Бюджет «в полёте» процесса-получателя кадров (Task 4.7c, переделка по вердикту CTO C1-C4).

**Зачем.** Кадр лежит в слоте SHM-кольца глубины D; по очереди идёт только ссылка на слот.
Писатель ходит по кольцу по кругу и через D кадров перезапишет тот же слот. Если у получателя
«в полёте» может сидеть больше D - 2 КАДРОВ, самый старый из них переживёт свой кадр: ссылка
есть, пикселей уже нет (разорванное чтение, пойманное seqlock'ом, — потеря кадра вместо
обработки). Два слота запаса — на кадр, который читается прямо сейчас, и на тот, который
пишется прямо сейчас: **B = D - 2**.

**Бюджет считает КАДРЫ, а не размер очереди** (C2/C3). IPC data-очередь — потолок памяти
(``data_queue_maxsize``, по умолчанию 50 при регистрации), в инвариант она не входит и из
топологии не выводится. В бюджет B входят: lag (``chain_max_lag_items`` — сколько КАДРОВЫХ
коллекций держит исполнитель; его принудительно держит DataReceiver) и транзитный запас
``B - lag`` — кадры в пути между очередью и приёмником. Транзит не навязывается размером
очереди, а ИЗМЕРЯЕТСЯ приёмником (``transit_over_budget``): глубина IPC-очереди > B - lag.

D — минимум глубин колец ВСЕХ писателей, чьи кадры получает процесс: самое мелкое кольцо
перезаписывается первым. Камеры друг на друга не влияют: бюджет считается только по
писателям этого получателя (вызывающий передаёт именно их).

**Границы.** ``chain_max_lag_items == 0`` в DataReceiver означает «без границы» — для процесса
за кольцом это ловушка, поэтому lag всегда >= 1. Кольцо мельче 4 — ошибка построения.
Явный lag допустим при ``1 <= lag <= B - 2`` (остаётся запас на транзит); на кольце 4 явного
lag нет вовсе, а выведенный по умолчанию — 1.

Чистые функции без зависимостей: их зовёт ``SystemBlueprint.build_configs()``, ошибка
поднимается при сборке рецепта, а не на живой системе.
"""

from __future__ import annotations

from collections.abc import Iterable

# Стандартный потолок отставания исполнителя; на малом бюджете (D = 4) урезается до B - 1.
_DEFAULT_LAG = 2
# Запас слотов кольца сверх «в полёте»: кадр читается + кадр пишется.
_RING_RESERVE = 2
# Минимальное кольцо: бюджет B = D - 2 >= 2 (lag >= 1 и транзит >= 1).
_MIN_RING_DEPTH = _RING_RESERVE + 2


def ring_budget(writer_depths: Iterable[int], *, process: str = "?") -> int:
    """Бюджет B = min(глубин колец писателей) - 2: сколько кадров получатель вправе держать «в полёте».

    Raises:
        ValueError: писателей нет; кольцо мельче 4.
    """
    depths = [int(d) for d in writer_depths]
    if not depths:
        raise ValueError(f"процесс '{process}': нет ни одного писателя кольца — бюджет считать не от чего")
    ring = min(depths)
    if ring < _MIN_RING_DEPTH:
        raise ValueError(
            f"процесс '{process}': кольцо {ring} слишком мелкое — на lag >= 1 (0 = «без границы») "
            f"и транзит >= 1 нужно кольцо не меньше {_MIN_RING_DEPTH}"
        )
    return ring - _RING_RESERVE


def inflight_budget(
    writer_depths: Iterable[int],
    *,
    queue: int | None = None,
    lag: int | None = None,
    process: str = "?",
) -> tuple[int, int]:
    """Вернуть ``(transit, chain_max_lag_items)`` для получателя кадров.

    ``transit`` — транзитный запас ``B - lag`` (читать как резерв, а не как maxsize очереди);
    явный ``queue`` возвращается как задан: это потолок памяти (cap), в бюджет не входит.

    Args:
        writer_depths: глубины колец всех писателей, чьи кадры получает процесс.
        queue: явный потолок памяти IPC-очереди из рецепта (None = вывести транзит).
        lag: явный потолок отставания из рецепта (None = вывести; 0 тут не «авто» —
            вызывающий переводит 0 в None).
        process: имя процесса — только для текста ошибки.

    Raises:
        ValueError: писателей нет; кольцо мельче 4; явный lag вне ``1..B-2``; явный queue < 1.
    """
    budget = ring_budget(writer_depths, process=process)

    if lag is None:
        # lag по умолчанию 2, но не больше B - 1: иначе на границе (D = 4) транзит остался бы 0.
        lag = min(_DEFAULT_LAG, budget - 1)
    elif not 1 <= lag <= budget - 2:
        raise ValueError(
            f"процесс '{process}': chain_max_lag_items {lag} вне 1..{budget - 2} при бюджете в полёте "
            f"{budget} (кольцо - {_RING_RESERVE}); 0 = «без границы» за кольцом недопустим, "
            f"а на транзит нужно оставить хотя бы 2 кадра"
        )

    if queue is None:
        return budget - lag, lag
    if queue < 1:
        raise ValueError(f"процесс '{process}': data_queue_maxsize {queue} < 1")
    return queue, lag

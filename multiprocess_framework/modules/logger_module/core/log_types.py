# -*- coding: utf-8 -*-
"""Типы данных для logger_module."""

from dataclasses import dataclass
from typing import Any, Dict

from .log_config import LogLevel, ScopeName


@dataclass
class LogRecord:
    """Запись лога — внутренний формат LoggerManager.

    Используется внутри процесса. При передаче через RouterManager
    конвертируется в Message(type=LOG) через to_dict().

    Соответствие словарю OpenTelemetry (Ф3.1/3.2, ADR-LOG-005)
    ==========================================================

    Фреймворк не зависит от OTel ни одной строкой; словарь взят как **имена
    понятий**, а SDK живёт отдельным сервисом (Ф8.6). Таблица ниже — контракт
    для того, кто будет писать экспортёр: гадать по именам полей нельзя, потому
    что одно из них называется так же, как чужое ДРУГОЕ понятие.

    ============== ======================== =====================================
    наше поле      OTel                     примечание
    ============== ======================== =====================================
    ``timestamp``  ``Timestamp``            момент эмиссии
    ``level``      ``SeverityText``         каноничное имя уровня
    (выводится)    ``SeverityNumber``       :func:`severity_of`, 5/9/13/17/21
    ``message``    ``Body``
    ``module``     ``InstrumentationScope`` **имя источника** — вот это и есть
                                            «scope» в терминах OTel
    ``extra``      ``Attributes``
    ``scope``      —                        **НЕ** ``InstrumentationScope``
    ``seq``        —                        пломба процесса (ADR-LOG-004)
    ============== ======================== =====================================

    **Коллизия имени, разрешённая явно.** Наш ``scope`` — это *группа*
    логирования (``SYSTEM``/``BUSINESS``/``PERFORMANCE``/``DEBUG``): ключ
    маршрутизации, по которому гейт решает, в какие каналы уходит запись.
    У OTel ``InstrumentationScope`` — идентификация *источника* (кто пишет), и
    у нас эту роль играет ``module``. Понятия разные, имя похожее; переименовано
    было **чужое** (то есть у нас оно никогда не появится под именем ``scope``),
    потому что переименование нашего стоило бы ~970 употреблений в коде, 485 в
    тестах и слом ключа конфига ``scopes``, только что сведённого к одному
    написанию в Ф2.4.

    У ``scope`` нет соответствия в спеке вовсе: полей «группа/facility» в модели
    OTel нет, такое кладут в ``Attributes``. Экспортёр обязан класть его туда, а
    не в ``InstrumentationScope``.
    """

    timestamp: float
    level: LogLevel
    scope: ScopeName
    message: str
    module: str
    extra: Dict[str, Any]
    seq: int = 0
    """Пломба (2.V1): номер записи в пределах процесса, ставится в точке эмиссии.

    Значение по умолчанию ``0`` означает «запись создана мимо
    :meth:`LoggerCore.log`» — то есть пломбы у неё нет и проверяющий обязан
    сказать об этом вслух, а не молча посчитать её отсутствие нормой.
    """

    def to_dict(self) -> Dict[str, Any]:
        """Сериализация для передачи через каналы / BatchBuffer."""
        return {
            "timestamp": self.timestamp,
            "level": self.level.value,  # str: "ERROR", "INFO", ...
            # Ф2.4: скоуп уже строка, и та же самая, что стоит ключом в конфиге.
            # До Ф2.4 здесь ехало `scope.value` — ВТОРОЕ написание того же имени
            # (`PERFORMANCE` в конфиге, `perf` в записи). Читателей у поля в
            # проде не было ни одного, поэтому сведение к одному написанию
            # обошлось без слоя совместимости (решение Р-2.4-А).
            #
            # Ф3.2: программного читателя у поля по-прежнему нет (ни канал, ни
            # tap, ни стор, ни GUI его не берут — проверено grep'ом), но читатель
            # ЕСТЬ и он человек: кольцо памяти хранит сырой словарь, и
            # `logger.sink.tail` отдаёт его оператору. Там `scope` отвечает на
            # «почему запись поехала именно в этот канал» — ровно то, ради чего
            # Ф2.4 свела его написание к ключу конфига. Поэтому поле оставлено;
            # удаление сэкономило бы байты и убило бы связь запись → правило.
            "scope": self.scope,
            "message": self.message,
            "module": self.module,
            "extra": self.extra,
            "seq": self.seq,
        }

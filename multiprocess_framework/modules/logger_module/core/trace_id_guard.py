# -*- coding: utf-8 -*-
"""Страж m2: сырой ``trace_id`` не имеет права стоять в ТЕКСТЕ записи.

Задача Ф1.4 плана ``observability-closure``, находка m2. Идентификатор
корреляции — структурное поле (``extra.context.trace_id``), а не часть
сообщения, и причина не косметическая:

* текст с вклеенным идентификатором **уникален на каждый вызов**, поэтому любой
  дроссель по тексту (``sampling_first_n``, Ф7.1) на нём слепнет — подавлять
  нечего, каждая запись «новая»;
* по той же причине ключ окна (:mod:`.windowed_voice`) расходится с событием:
  окно на ключ, собранный из текста, открывалось бы заново каждый раз;
* группировать такие записи в разборе нечем — они не совпадают ни с чем.

Страж переиспользуемый и НЕ привязан к плагину, ради которого заведён: это
свойство любой записи, а точек записи в дереве больше двухсот.
"""

from __future__ import annotations

import re
from typing import Any, Iterable, Optional

#: 32 hex-символа подряд — форма ``uuid4().hex`` этого проекта. Границы
#: (``(?<!...)``/``(?!...)``) обязательны: без них страж срабатывал бы на
#: подстроке внутри более длинного hex — например, внутри sha-256 дайджеста,
#: который идентификатором корреляции не является.
TRACE_ID_RE = re.compile(r"(?<![0-9a-fA-F])[0-9a-fA-F]{32}(?![0-9a-fA-F])")


def find_bare_trace_id(message: Any) -> Optional[str]:
    """Вернуть найденный сырой идентификатор или ``None``."""
    match = TRACE_ID_RE.search(str(message))
    return match.group(0) if match else None


def assert_no_bare_trace_id(message: Any, where: str = "") -> None:
    """Уронить ``AssertionError``, если в тексте стоит сырой 32-hex.

    Args:
        message: текст записи (или объект, чей ``str()`` — текст).
        where: адрес для сообщения об ошибке (файл, имя точки вызова).

    Raises:
        AssertionError: текст содержит идентификатор, которому место в поле.
    """
    found = find_bare_trace_id(message)
    if found is None:
        return
    address = f" ({where})" if where else ""
    raise AssertionError(
        f"сырой trace_id в ТЕКСТЕ записи{address}: {found!r}. "
        f"Идентификатор корреляции обязан ехать структурным полем "
        f"(extra.context.trace_id / kwarg), иначе текст уникален на каждый вызов: "
        f"дроссель по тексту слепнет, окно голоса открывается заново, "
        f"а сгруппировать записи в разборе нечем. Текст: {str(message)!r}"
    )


def assert_no_bare_trace_ids(messages: Iterable[Any], where: str = "") -> None:
    """То же для набора текстов — первый нарушитель роняет проверку.

    **Вызывающих на сегодня НОЛЬ — сверено грепом по всему дереву (ревью Task
    1.4), и это названо здесь, а не подразумевается.** Правило проекта
    «неиспользуемый путь — это контракт» запрещает молча заводить дверь, о
    которой нельзя сказать, кому она нужна; и оно же запрещает считать «нет
    вызывающих» доказательством ненужности.

    Кому нужна: проверке ПАЧКИ собранных строк (содержимое файла журнала,
    список записей из memory-канала, накопитель тестового приёмника) — там, где
    вызывающему нужен адрес первого нарушителя, а не ``any(...)``. Единичная
    :func:`assert_no_bare_trace_id` этого не даёт, а сама по себе форма
    ``for m in messages`` у вызывающего теряет ``where``.

    Если к закрытию Ф1 плана ``observability-closure`` вызывающий не появится —
    снять вместе с этим докстрингом: тогда это будет не контракт, а домысел.
    """
    for message in messages:
        assert_no_bare_trace_id(message, where)

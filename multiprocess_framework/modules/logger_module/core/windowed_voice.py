# -*- coding: utf-8 -*-
"""Окно голоса на ключ: **факт учитывается всегда, строка в журнал — не чаще окна**.

Задача Ф1.4 плана ``observability-closure`` (находки M17, m2). До неё окно
журнала переписывали вручную снова и снова — поимённый реестр копий и задач,
которые их сняли, лежит в :data:`REPLACED_MANUAL_WINDOWS` (по одному состоянию
``_last_log``/``_suppressed`` на файл), и каждая копия решала одну и ту же
задачу чуть-чуть по-своему: где-то троттлилась только запись, где-то вместе с
ней исчезал и учёт. Числом реестр здесь не пересказывается сознательно — см.
комментарий у него.

## Два обязательства, разделённые НАМЕРЕННО

Главное решение этого модуля — :meth:`WindowedVoices.take` возвращает
**решение**, а не совершает запись:

* **факт** — счётчик, запись в плоскость ошибок, инкремент статистики — остаётся
  на вызывающем и учитывается ВСЕГДА, окно его не касается;
* **голос** — строка в журнал — выпускается не чаще окна, и следующий голос
  называет, сколько событий было подавлено с прошлой записи.

Склеивать их в один вызов нельзя, и это не вкусовщина. Живой контрпример, ради
которого разделение и заводилось, — ``process_module/health/state.py``: там
``_safe_track`` (запись в плоскость ошибок с трассой и контекстом) стоял ВНУТРИ
``if should_log:``, потому что своего окна у плоскости ошибок не было и был взят
чужой — от журнала. Итог: повтор в окне 5 с не оставлял в плоскости ошибок
ничего, кроме числа (замер: 5 вхождений из пяти потоков → 1 запись). Task 1.3a
это место починила, и форма там теперь такая:

    self._safe_track(exc, ctx, fields)                    # ← факт: ВСЕГДА
    voiced, suppressed = self._voices.take(key, throttle)  # ← решение
    if voiced:
        self._safe_log(compose_voice_text(text, suppressed))

``_safe_track`` стоит ДО ``take()``, а не после: решение принимает чужой
механизм, и его отказ не имеет права стоить факта. :func:`log_windowed` —
удобство для частого случая «нужен только голос», а не единственная дверь.

## Слот списывается ДОСТАВКОЙ, а не решением (Task 4.13)

``take()`` возвращает решение — но само решение ещё не означает, что строка
доехала. До Task 4.13 слот считался съеденным фактом решения: приёмник мог не
иметь метода уровня или бросить исключение (а три боевых вызывающих гасят
исключение через ``except: pass``), и первая же потеря давала гарантированное
молчание на весь интервал — **неотличимое от штатного подавления**.

Форма починки — **резерв → откат**, и она выбрана прогоном, а не вкусом.
Наивное «сначала доставить, потом списать» замерено: 16 потоков на одном ключе,
200 раундов → двойной голос в 200 раундах из 200. Поэтому:

* ``take()`` списывает слот КАК ПРЕЖДЕ, под локом — конкуренты видят занятый
  слот и подавляются законно;
* если доставка не состоялась, вызывающий зовёт :meth:`WindowedVoices.release`,
  и тот под ТЕМ ЖЕ локом возвращает ключ в «пора говорить», сложив в него долг:
  прежний невысказанный счёт + сама несостоявшаяся запись + всё, что успели
  подавить конкуренты, пока запись была в полёте;
* **лок на время эмиссии не удерживается** — дисциплина ниже не нарушена.

**Граница «что считать доставкой» — «приёмник принял вызов без исключения»**
(метод есть и вернулся). Ниже этой границы лежит плоскость логгера со своими
счётчиками, и тянуть окно до файла значило бы сделать примитив зависимым от
проводки. Контракт поэтому говорит «передано приёмнику», а не «записано».

Отказ доставки виден двумя способами: числом — процессный счётчик
``windowed_delivery_failed`` рядом с ``windowed_suppressed`` (он растёт на
КАЖДУЮ несостоявшуюся доставку), и словами — самоотчёт через
:func:`~..._fallback.emergency_log` РАЗ НА КЛЮЧ. Аварийный выход здесь законен:
о поломке сообщает сам сломавшийся маршрут, и рассказывать о ней через ту же
плоскость означало бы рекурсию.

## Ключи и память

Состояние живёт по ключу, ключи разных источников независимы. **Обе** карты
держателя ограничены действующим потолком (:data:`MAX_TRACKED_KEYS` — L0-дефолт
512, ``observability.voices.max_tracked_keys`` — ручка, Task 2.7): ключ с именем
процесса, рода исключения или причины — величина неограниченного алфавита, и
карта без потолка стала бы утечкой на ключах, которых больше никогда не будет.
До Task 2.7 потолок и такт протухания были литералами без ручки и без readback
(ревью Ф1, нарушение правила 2 §1 плана) — механизм-сосед (дроссель-сэмплер,
:mod:`.sampling`) уже публиковал и текущее число ключей, и счётчик насыщения, а
здесь у ``WindowedVoices.tracked_keys()`` не было ни одного боевого вызывающего.

* карта ОКОН (``_state``) подметается сначала по протухшим — старше
  :data:`_STALE_WINDOWS` своих окон (L0-дефолт 10, ``observability.voices.stale_windows``,
  Task 2.7) и без накопленных подавлений, — потом, если и это не помогло, по
  старшинству среди бездолжников; выброс НЕ молчит — он растит
  ``windowed_keys_evicted`` (этот счётчик и есть насыщение — сампловый
  аналог ``sampler_keys_saturated``: растёт ровно тогда, когда протухшего
  для освобождения места не нашлось, и пришлось жертвовать живым ключом);
* карта СЕРИЙ (``_repeats``) растёт отдельно: :meth:`WindowedVoices.note_repeat`
  карты окон не касается, и до ревью Task 1.4 потолка у неё не было вовсе
  (замер ревью: 50 000 разных ключей → 50 000 записей при ``tracked_keys() == 0``).
  Жертвы здесь — САМЫЕ КОРОТКИЕ серии: серия длины 1 не отличима от «серии не
  было», а длинная — ровно тот симптом, ради которого ось заведена, и терять её
  первой значило бы слепнуть в худшем случае. Потолок — тот же самый
  действующий :data:`MAX_TRACKED_KEYS`, а не вторая копия числа.

**Только что созданный ключ жертвой не становится** — ни в одной из карт. Иначе
насыщенная должниками карта выбрасывала бы его сразу после вставки, и механизм
отключался бы ровно в том состоянии, ради которого существует: ревью Task 1.4
воспроизвело пять голосов из пяти подряд по одному ключу при окне 100 с.

## Дисциплина лока

Решение и обнуление счётчика подавленных берутся под ОДНИМ локом (иначе число
в тексте отстаёт от своего момента — урок ``RouterManager._report_send_error``,
комментарий «Ф6.х.7б»). Сама запись в журнал делается ВНЕ лока: обработчик
записи имеет право позвать ``log_windowed`` повторно, и удержание лока на время
эмиссии превратило бы реентрантность в дедлок.

**Порядка захвата двух локов здесь нет — и это утверждение проверяемое, а не
формальное.** Лок держателя (``self._lock``) и лок процессных счётчиков
(``_totals_lock``) НИГДЕ не удерживаются одновременно: ``_bump`` зовётся строго
после выхода из ``with self._lock``. Инверсии поэтому не бывает по построению, а
не по соглашению о порядке. Прежняя редакция объявляла здесь именно порядок
(«сначала лок держателя, потом лок счётчиков») — утверждение вакуумное: ревью
Task 1.4 не нашло в коде ни одной точки, где выполнялась бы его посылка.

**Третий лок (Task 2.7) подчиняется тому же правилу.** ``_policy_lock`` читает
действующий потолок/такт (:func:`max_tracked_keys`, :func:`stale_windows`) — оба
вызова стоят ДО ``with self._lock:``, как и уже существовавшее чтение
``default_window_sec()``. ``_sweep_locked``/``_sweep_repeats_locked`` получают
готовые числа параметрами и НЕ зовут политику сами — иначе ``_policy_lock``
захватывался бы изнутри ``self._lock``, и третий лок нарушил бы то же
инвариант, который у первых двух проверяется тестом.
"""

from __future__ import annotations

import logging
import threading
import time
from typing import Any, Dict, List, Optional, Set, Tuple

from ..._fallback import emergency_log

#: Реестр снятых ручных копий окна журнала: имя копии → задача, которая её сняла.
#:
#: **Число здесь не пишется словом НИГДЕ — оно считается длиной этого кортежа.**
#: Это правка ревью Task 1.3a, и она третья по счёту на одном и том же месте:
#: соседние докстринги независимо говорили «семь», «шесть» и «пять», перечисляя
#: при этом один и тот же набор. Слово и перечень — два хранилища одного факта,
#: и они расходятся молча; кортеж оставляет одно.
REPLACED_MANUAL_WINDOWS: tuple[tuple[str, str], ...] = (
    ("_SEND_ERROR_LOG_INTERVAL_SEC", "Task 1.4"),
    ("_NEVER_DROP_LOSS_LOG_INTERVAL_SEC", "Task 1.4"),
    ("_system_evict_log_window", "Task 1.4"),
    ("_data_evict_log_window", "Task 1.4"),
    ("_queue_missing_log_window", "Task 1.4"),
    # Здесь окно журнала держало заодно и запись в плоскость ошибок; разрезать
    # это было отдельной задачей.
    ("HealthState.DEFAULT_THROTTLE", "Task 1.3a"),
)

#: Дефолт окна, если политика процесса не задана конфигом.
#: Совпадает с величиной, до которой независимо сошлись все ручные копии,
#: перечисленные поимённо в :data:`REPLACED_MANUAL_WINDOWS`.
DEFAULT_WINDOW_SEC: float = 5.0

#: Сколько повторов ПОДРЯД по одному ключу терпится до эскалации INFO → WARNING.
#: Строго «больше порога»: N=3 означает, что четвёртый подряд говорит громко.
DEFAULT_ESCALATE_AFTER_REPEATS: int = 3

#: Потолок карты ключей на один держатель окон. L0-дефолт политики
#: (``observability.voices.max_tracked_keys``, Task 2.7) — действующее значение
#: читает :func:`max_tracked_keys`, а не этот символ напрямую (он остаётся
#: именем встроенного дефолта, как :data:`DEFAULT_WINDOW_SEC` у окна).
MAX_TRACKED_KEYS: int = 512

#: Во сколько окон молчания ключ считается протухшим и подметается. L0-дефолт
#: политики (``observability.voices.stale_windows``, Task 2.7) — действующее
#: значение читает :func:`stale_windows`.
_STALE_WINDOWS: int = 10

_policy_lock = threading.Lock()
_policy: Dict[str, Any] = {
    "window_sec": DEFAULT_WINDOW_SEC,
    "escalate_after_repeats": DEFAULT_ESCALATE_AFTER_REPEATS,
    "max_tracked_keys": MAX_TRACKED_KEYS,
    "stale_windows": _STALE_WINDOWS,
}

_totals_lock = threading.Lock()
_totals: Dict[str, int] = {
    "windowed_suppressed": 0,
    "windowed_keys_evicted": 0,
    # Task 4.13: сколько раз решение «голосить» было принято, а доставка до
    # приёмника не состоялась. Делает предыдущие два числа честными: без него
    # «подавлено N» одинаково означает и работающее окно, и сломанный приёмник.
    "windowed_delivery_failed": 0,
}

#: Метка «этот ключ обязан заговорить при следующем обращении», которую ставит
#: :meth:`WindowedVoices.release`. ``-inf`` выбран вместо «now минус окно»
#: сознательно: сравнение в :meth:`WindowedVoices.take` идёт с окном, пришедшим
#: в ТОТ вызов, а оно у следующего вызывающего может оказаться больше прежнего —
#: тогда откат «на одно окно назад» снова попал бы внутрь окна и промолчал.
#: ``now - (-inf)`` больше любого конечного окна, каким бы оно ни пришло.
_RELEASED_AT: float = float("-inf")


# ---------------------------------------------------------------------------
# Политика процесса (окно из конфига, а не из литерала)
# ---------------------------------------------------------------------------


def default_window_sec() -> float:
    """Действующее окно процесса, сек (``observability.voices.default_window_sec``)."""
    with _policy_lock:
        return float(_policy["window_sec"])


def escalate_after_repeats() -> int:
    """Порог эскалации повторов процесса (``observability.voices.escalate_after_repeats``)."""
    with _policy_lock:
        return int(_policy["escalate_after_repeats"])


def max_tracked_keys() -> int:
    """Действующий потолок карты ключей процесса (``observability.voices.max_tracked_keys``).

    Читается ДЕРЖАТЕЛЕМ на каждый вызов :meth:`WindowedVoices.take` /
    :meth:`WindowedVoices.note_repeat`, а не один раз в конструкторе — держатели
    создаются до применения политики (роутер, реестр очередей поднимаются раньше
    ``wire_voices_policy``), и захват значения в ``__init__`` заморозил бы
    встроенный дефолт (Task 2.7, тот же урок, что уже есть у ``clock`` в
    :meth:`WindowedVoices.__init__`).
    """
    with _policy_lock:
        return int(_policy["max_tracked_keys"])


def stale_windows() -> int:
    """Действующий такт протухания процесса (``observability.voices.stale_windows``)."""
    with _policy_lock:
        return int(_policy["stale_windows"])


def set_voices_policy(
    *,
    window_sec: Optional[float] = None,
    escalate_after: Optional[int] = None,
    max_tracked_keys: Optional[int] = None,
    stale_windows: Optional[int] = None,
) -> Dict[str, Any]:
    """Задать политику голосов процесса. Возвращает применённый снимок.

    Зовётся сшивкой процесса (``wire_voices_policy`` на старте,
    ``apply_voices_policy`` на пересборке) — по той же схеме трёх точек, по
    которой в секцию наблюдаемости заведены ``events``/``flight``/``observation``:
    это не параметр менеджера, а политика, которую читает живой механизм.

    **Возвращает ВНУТРЕННИЕ имена политики** (``window_sec``), а не имена полей
    схемы. Наружу их отдавать нельзя: readback с чужим именем ключа round-trip'ом
    не переживает (см. ``apply_voices_policy``, где перевод и делается).

    ``None`` означает «не трогать эту ось», а не «сбросить в дефолт»: молчание
    слоя не имеет права стирать заданное (правило Г3 этого проекта).
    """
    with _policy_lock:
        if window_sec is not None:
            _policy["window_sec"] = float(window_sec)
        if escalate_after is not None:
            _policy["escalate_after_repeats"] = int(escalate_after)
        if max_tracked_keys is not None:
            _policy["max_tracked_keys"] = int(max_tracked_keys)
        if stale_windows is not None:
            _policy["stale_windows"] = int(stale_windows)
        return dict(_policy)


def reset_voices_policy() -> None:
    """Вернуть политику к встроенным дефолтам (фикстуры тестов)."""
    with _policy_lock:
        _policy["window_sec"] = DEFAULT_WINDOW_SEC
        _policy["escalate_after_repeats"] = DEFAULT_ESCALATE_AFTER_REPEATS
        _policy["max_tracked_keys"] = MAX_TRACKED_KEYS
        _policy["stale_windows"] = _STALE_WINDOWS


# ---------------------------------------------------------------------------
# Процессные счётчики (readback наблюдаемости)
# ---------------------------------------------------------------------------


def voice_counters() -> Dict[str, int]:
    """Счётчики механизма для ``get_stats()`` плоскости логов.

    Величины ПРОЦЕССНЫЕ, а не пер-менеджерные, и это сознательно: держателей окон
    в процессе много (роутер, реестр очередей, менеджер процессов), а плоскостей
    наблюдаемости, чей ``get_stats()`` уезжает в readback, — три. Пер-менеджерное
    число не доехало бы наружу ни от одного из настоящих потребителей.
    """
    with _totals_lock:
        return dict(_totals)


def reset_voice_counters() -> None:
    """Обнулить процессные счётчики (фикстуры тестов)."""
    with _totals_lock:
        for key in _totals:
            _totals[key] = 0


def _bump(key: str, value: int = 1) -> None:
    if value <= 0:
        return
    with _totals_lock:
        _totals[key] = _totals.get(key, 0) + value


# ---------------------------------------------------------------------------
# Держатель окон
# ---------------------------------------------------------------------------


class WindowedVoices:
    """Состояние окон по ключу. Потокобезопасен, не пиклится (держит лок)."""

    __slots__ = ("_lock", "_state", "_repeats", "_clock", "_reported")

    def __init__(self, clock: Optional[Any] = None) -> None:
        """
        Args:
            clock: источник монотонного времени; ``None`` → ``time.monotonic``.
                Инъекция — ради тестов окна: без неё «окно истекло» проверяется
                настоящим ``sleep``, а на сетке ``time.monotonic`` Windows
                (15.6 мс) узкое окно требует кратного запаса.

                Дефолт — ``None``, а НЕ ``time.monotonic`` значением: захват
                функции в конструкторе пережил бы подмену
                ``monkeypatch.setattr(time, "monotonic", …)`` у держателя,
                созданного ДО подмены, и молча вернул бы настоящие часы.
                Измерено: 8 соседних тестов окна покраснели ровно на этом.
        """
        self._clock = clock
        self._lock = threading.Lock()
        # key -> [последний голос (monotonic), подавлено с него, окно этого ключа]
        self._state: Dict[str, List[float]] = {}
        # key -> сколько раз подряд событие повторилось (ось эскалации, без времени)
        self._repeats: Dict[str, int] = {}
        # ключи, о сломанной доставке которых самоотчёт уже прозвучал (Task 4.13).
        # Своей карты с потолком не заводит: сюда попадают ТОЛЬКО ключи, которые
        # в этот же момент лежат в ``_state``, и уходят они вместе с ним — в
        # подметании и в ``forget``. Потолок поэтому общий, а не второй.
        self._reported: Set[str] = set()

    # -- окно ---------------------------------------------------------------

    def take(self, key: str, interval: Optional[float] = None) -> Tuple[bool, int]:
        """Решение о голосе по ключу. **Ничего не пишет и ничего не считает за вызывающего.**

        Args:
            key: адрес события. Разные ключи независимы.
            interval: окно, сек. ``None`` → политика процесса.

        Returns:
            ``(голосить?, подавлено_с_прошлой_записи)``. Первый вызов с новым
            ключом всегда даёт ``(True, 0)``. Внутри окна — ``(False, N)``, где
            ``N`` — сколько уже накоплено (число возвращается и на подавлении:
            вызывающему бывает нужно решить, не пора ли сказать иначе).
        """
        window = default_window_sec() if interval is None else float(interval)
        # Потолок и такт протухания — тоже действующая политика процесса
        # (Task 2.7), и читаются здесь же, ДО входа в ``with self._lock``: тот
        # же довод, что уже у ``window`` — ``_policy_lock`` не имеет права
        # захватываться изнутри ``self._lock`` (см. «Дисциплина лока» в шапке
        # модуля), поэтому оба числа приходят в ``_sweep_locked`` параметрами.
        ceiling = max_tracked_keys()
        stale_factor = stale_windows()
        now = time.monotonic() if self._clock is None else self._clock()
        evicted = 0
        with self._lock:
            entry = self._state.get(key)
            if entry is not None and (now - entry[0]) < window:
                entry[1] += 1
                suppressed = int(entry[1])
                voiced = False
            else:
                suppressed = int(entry[1]) if entry is not None else 0
                self._state[key] = [now, 0, window]
                voiced = True
                if len(self._state) > ceiling:
                    # ``protect`` — ключ, ради которого сюда и зашли. Без него
                    # насыщенная должниками карта выбрасывала бы его немедленно
                    # (он бездолжник по построению, а бездолжники идут первыми),
                    # и следующий вызов снова видел бы НОВЫЙ ключ: голос звучал
                    # бы каждый раз. Воспроизведено ревью Task 1.4.
                    evicted = self._sweep_locked(now, ceiling, stale_factor, protect=key)
        # Инкременты процессных счётчиков — ВНЕ лока держателя, и это ЕДИНСТВЕННОЕ
        # место, где встречаются оба лока модуля. Порядка захвата у них нет, потому
        # что одновременно они не удерживаются нигде: ``_bump`` исполняется уже
        # после выхода из ``with self._lock``. Инверсия исключена построением, а не
        # соглашением (ревью Task 1.4 сняло здесь обратное утверждение).
        if not voiced:
            _bump("windowed_suppressed", 1)
        _bump("windowed_keys_evicted", evicted)
        return voiced, suppressed

    def release(self, key: str, suppressed: int = 0) -> int:
        """Доставка голоса не состоялась — вернуть слот и сложить в него долг (Task 4.13).

        Зовётся вызывающим, который получил от :meth:`take` разрешение говорить,
        но записи до приёмника не довёл: у приёмника нет метода уровня, либо он
        бросил исключение. Граница «доставка» именно здесь и проходит — «приёмник
        принял вызов и вернулся», а не «строка легла в файл».

        Что происходит под локом:

        * ключ получает метку :data:`_RELEASED_AT` — следующее обращение к нему
          выйдет в ветку «голосить», каким бы окном ни пришли;
        * в счёт подавленных складываются три слагаемых: ``suppressed``
          (невысказанный долг, который несла провалившаяся запись), единица за
          саму эту запись и всё, что конкуренты успели подавить, пока запись
          была в полёте. Ни одно вхождение из счёта не выпадает.

        Вне лока — процессный счётчик ``windowed_delivery_failed`` (на КАЖДУЮ
        неудачу) и самоотчёт через :func:`~..._fallback.emergency_log` РАЗ НА
        КЛЮЧ: сломанный маршрут говорит о себе сам, аварийным выходом, потому
        что своя плоскость у него сломана по условию задачи. Оба вызова стоят
        после ``with self._lock`` по той же дисциплине, что ``_bump`` в
        :meth:`take`.

        Args:
            key: тот же ключ, что отдавался в :meth:`take`.
            suppressed: число, которое :meth:`take` вернула вместе с решением.

        **Цена, названная ревью и оставленная сознательно: освобождённый ключ
        становится ПЕРВОЙ жертвой вытеснения по потолку.** ``_RELEASED_AT`` —
        минус бесконечность, то есть для сортировщика жертв такой ключ
        бесконечно стар. Воспроизведено: потолок 4, три обычных должника плюс
        один освобождённый — вылетает именно освобождённый, хотя он самый
        ценный из четырёх (у него сломан маршрут).

        Почему оставлено: альтернатива — завести признак «освобождён» с обратным
        весом в ключе сортировки, то есть второе правило вытеснения рядом с
        первым. Потеря при этом НЕ молчит — она считается в
        ``windowed_keys_evicted``, и это тот самый счётчик, который делает
        «подавлено N» честным. Менять правило вытеснения ради этого случая —
        отдельное решение с собственной приёмкой, а не довесок к откату слота.

        **Не идемпотентен:** два вызова на один :meth:`take` дадут долг 2 при
        одном событии. Боевого пути с двойным вызовом нет (шесть мест, каждое в
        одиночной ветке — сверено инвентарём), но контракт назван, чтобы
        следующий вызывающий не завёл его случайно.

        Returns:
            Накопленный долг ключа — то самое число, которое назовёт следующий
            состоявшийся голос.
        """
        # Окно читается ДО лока держателя (дисциплина лока, шапка модуля) и
        # нужно лишь на случай, когда ключа в карте уже нет: его могли вытеснить
        # по потолку или забыть через ``forget``, пока запись была в полёте.
        fallback_window = default_window_sec()
        first_report = False
        with self._lock:
            entry = self._state.get(key)
            in_flight = int(entry[1]) if entry is not None else 0
            window = float(entry[2]) if entry is not None else fallback_window
            debt = int(suppressed) + 1 + in_flight
            self._state[key] = [_RELEASED_AT, debt, window]
            if key not in self._reported:
                self._reported.add(key)
                first_report = True
        _bump("windowed_delivery_failed", 1)
        if first_report:
            emergency_log(
                __name__,
                "warning",
                "окно голоса: доставка не состоялась, слот возвращён (ключ %s, долг %d). "
                "Дальнейшие отказы этого ключа считаются в windowed_delivery_failed",
                key,
                debt,
            )
        return debt

    def _sweep_locked(self, now: float, ceiling: int, stale_factor: int, protect: Optional[str] = None) -> int:
        """Подмести карту окон. Вызывается под ``self._lock``. Возвращает выброшенные.

        Args:
            now: момент вызова (monotonic).
            ceiling: действующий потолок карты (:func:`max_tracked_keys` на
                момент вызова :meth:`take` — снят ДО лока, не пересчитывается
                здесь: см. «Дисциплина лока»).
            stale_factor: действующий такт протухания (:func:`stale_windows`,
                снят той же дорогой).
            protect: ключ, которому НЕЛЬЗЯ стать жертвой — тот, ради которого
                подметание и запущено.
        """
        for key in [k for k, e in self._state.items() if e[1] == 0 and (now - e[0]) > stale_factor * e[2]]:
            del self._state[key]
            self._repeats.pop(key, None)
            self._reported.discard(key)
        if len(self._state) <= ceiling:
            # Протухшие не считаются выброшенными: у них не было ни одного
            # неназванного подавления, терять было нечего.
            return 0
        # Потолок не взят подметанием — значит ключи горячие, и что-то придётся
        # выбросить. НЕ молчим об этом: иначе «подавлено 0» означало бы то же
        # самое, что «счёт выброшен вместе с ключом».
        #
        # Порядок жертв — сначала БЕЗДОЛЖНИКИ (нечего терять), внутри группы по
        # старшинству. Найдено собственным hazard-тестом: сортировка по одному
        # возрасту выбирает жертвой ровно тот ключ, который дольше всех копил
        # неназванный счёт, — то есть механизм терял в первую очередь самое
        # ценное, что у него было, и делал это тем охотнее, чем дольше жил.
        #
        # ``protect`` исключается из кандидатов ЦЕЛИКОМ, а не «жертвуется
        # последним»: только что вставленный ключ — бездолжник с самой свежей
        # меткой, то есть при карте из одних должников он единственный кандидат
        # своей группы. Замер ревью Task 1.4: 512 должников, пять ``take('hot')``
        # подряд в окне 100 с давали ПЯТЬ голосов и ``'hot' in map == False``.
        ordered = sorted(
            (item for item in self._state.items() if item[0] != protect),
            key=lambda kv: (kv[1][1] > 0, kv[1][0]),
        )
        evicted = 0
        for key, _entry in ordered[: len(self._state) - ceiling]:
            del self._state[key]
            self._repeats.pop(key, None)
            self._reported.discard(key)
            evicted += 1
        return evicted

    def forget(self, key: str) -> None:
        """Забыть ключ (событие кончилось — следующее заговорит немедленно)."""
        with self._lock:
            self._state.pop(key, None)
            self._repeats.pop(key, None)
            self._reported.discard(key)

    def tracked_keys(self) -> int:
        with self._lock:
            return len(self._state)

    # -- эскалация по повторам ПОДРЯД --------------------------------------

    def note_repeat(self, key: str) -> int:
        """Событие повторилось подряд. Возвращает длину серии (первое = 1).

        Карта серий ограничена тем же потолком, что карта окон: ``note_repeat``
        карты окон не касается вовсе, поэтому её собственный потолок — не
        дублирование, а единственный (см. шапку модуля).
        """
        # Потолок читается ДО лока — та же дисциплина, что у ``take()``
        # (Task 2.7): ``_policy_lock`` не захватывается изнутри ``self._lock``.
        ceiling = max_tracked_keys()
        with self._lock:
            self._repeats[key] = self._repeats.get(key, 0) + 1
            if len(self._repeats) > ceiling:
                self._sweep_repeats_locked(ceiling, protect=key)
            return self._repeats[key]

    def _sweep_repeats_locked(self, ceiling: int, protect: str) -> None:
        """Подмести карту серий. Под ``self._lock``. Жертвы — самые короткие серии.

        Длина серии здесь работает ценой записи: единица не отличима от «серии не
        было», а длинная серия — тот самый симптом, ради которого ось заведена.
        Возраста у серии нет по построению (ось повторов, а не времени), поэтому
        подметать по нему нечем.

        Молчит СОЗНАТЕЛЬНО: ``windowed_keys_evicted`` считает выброс ключа ОКНА
        вместе с его неназванным счётом подавлений, а здесь теряется другая
        величина. Слить их в одно число значило бы сделать существующий счётчик
        неинтерпретируемым; заводить второй ради карты, у которой сегодня
        единицы ключей (один вызывающий на всё дерево), — рано.
        """
        victims = sorted((k for k in self._repeats if k != protect), key=lambda k: self._repeats[k])
        for key in victims[: len(self._repeats) - ceiling]:
            del self._repeats[key]

    def reset_repeat(self, key: str) -> None:
        """Серия прервана (событие не случилось) — следующее начнёт счёт заново."""
        with self._lock:
            self._repeats.pop(key, None)

    def repeats(self, key: str) -> int:
        with self._lock:
            return self._repeats.get(key, 0)



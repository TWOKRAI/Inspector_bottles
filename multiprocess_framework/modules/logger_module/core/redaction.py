# -*- coding: utf-8 -*-
"""Редакция секретов в записи лога (Ф4.3→4.5) — процессор цепочки.

Зачем отдельный перехватчик, а не «не пишите секретов в логи»: секрет попадает
в лог не потому, что кто-то решил его записать, а **транзитом**. Трейсбек
(``ErrorManager.log_exception`` склеивает ``traceback.format_exc()`` прямо в
текст сообщения) несёт локальные переменные фрейма; ``repr`` конфига несёт
пароль подключения. Ни одна из этих строк не пишется руками, и запретить их
нельзя — можно только перехватить на единственной точке эмиссии.

Две поверхности, и обе обязательны
==================================

* **``extra``** — по ИМЕНАМ ключей, точным сравнением (не подстрокой): подстрока
  ``token`` съела бы ``tokenizer`` и ``token_count``, а ложная маскировка
  метрики хуже, чем отсутствие редакции, — ей верят.
* **``message``** — регуляркой ``ключ=значение`` / ``"ключ": "значение"``, потому
  что трейсбек едет именно туда. Без message-ветки задача не закрывает свою
  мотивацию: секреты вероятнее всего именно в ``errors.log`` и ``critical.log``.

Что этот модуль сознательно НЕ делает
=====================================

* **не угадывает секреты по виду значения** (энтропия, JWT, base64) — это работа
  офлайнового аудита (`/core:quality:secrets-audit`), а не горячего пути, и
  ложное срабатывание здесь стоит дороже пропуска: замаскированный `frame_id`
  ломает разбор инцидента;
* **не спускается в списки** (``extra={"items": [{"password": ...}]}``) —
  граница названа, а не забыта: спуск в списки удваивает обход ради формы,
  которой в проекте сегодня нет ни одной;
* **не имеет конфигурации.** Список имён — константа модуля. Ключ конфига
  добавил бы слой и, главное, выключатель: редакция, которую можно случайно
  выключить рецептом, не редакция.

Стоимость на чистой записи (а таких — все) — один проход по ключам ``extra``
без аллокаций плюс один поиск регуляркой по строке. Копия строится **только**
при находке, и только по ветке, где находка: сёстры едут по ссылке.
"""

from __future__ import annotations

import re
from typing import Any, Dict, Optional

from .log_config import LogLevel, ScopeName

#: Чем маскируем. Строка-маркер, а не пустое значение: пустое неотличимо от
#: «поля не было», и разбор инцидента упёрся бы в вопрос «редакция или баг».
MASK = "***"

#: Имена полей, значение которых не показывают никому. Сравнение — ТОЧНОЕ по
#: lowercase-имени (см. модульный докстринг про ``tokenizer``).
SECRET_FIELD_NAMES = frozenset(
    {
        "password",
        "passwd",
        "pwd",
        "secret",
        "token",
        "access_token",
        "refresh_token",
        "auth_token",
        "api_key",
        "apikey",
        "access_key",
        "secret_key",
        "private_key",
        "authorization",
        "credentials",
        "credential",
        "session_key",
        "passphrase",
    }
)

#: Корни имён — ДЕШЁВЫЙ предфильтр для текста сообщения.
#:
#: Замер (20 000 записей × 5 прогонов): полная регулярка из 18 альтернатив с
#: ``\b`` и ``IGNORECASE`` стоит 3.9 мкс на КАЖДОЙ записи, тогда как сама
#: эмиссия — 4.3 мкс. То есть редакция удваивала цену ``log()`` ради строк, в
#: которых секретов нет (а таких — все, кроме считанных). Семь подстрочных
#: поисков по lowercase-копии стоят 0.57 мкс и дают тот же ответ «тут может
#: быть»; полная регулярка запускается только после их согласия.
#:
#: **Связь с именами обязана держаться, и её сторожит тест.** Имя, ни один
#: корень которого сюда не попал, стало бы невидимым для message-ветки молча:
#: в ``extra`` маскируется, в тексте — нет.
SECRET_NAME_ROOTS = ("pass", "pwd", "secret", "token", "key", "auth", "credential")

#: Предфильтр URL-ветки: корней имён в ``postgres://u:пароль@h`` нет вовсе,
#: поэтому у неё свой — и он ещё дешевле (0.03 мкс).
_URL_MARK = "://"

#: Потолок спуска в ``extra``. Не оптимизация, а защита от самоссылочного
#: словаря: без него цикл дал бы ``RecursionError``, редактор бы «бросил», и
#: запись уехала бы НЕотредактированной — то есть цикл в чужих данных
#: превращался бы в утечку секрета.
MAX_DEPTH = 6

#: Обе формы «ключ → значение» в тексте сообщения. Строго линейный шаблон, без
#: вложенных квантификаторов: трейсбеки бывают длиной в килобайты, и
#: катастрофический бэктрекинг означал бы зависание внутри ``log()``.
#:
#: ``\b`` вокруг имени решает ту же задачу, что точное сравнение в ``extra``:
#: ``token_count`` не совпадёт, потому что ``_`` — словесный символ.
#:
#: Кавычка после имени входит во ВТОРУЮ группу, и это не косметика: без неё
#: форма ``"password": "x"`` не ловилась вовсе — ``\b`` заканчивал имя перед
#: закрывающей кавычкой, а разделитель требовался сразу. Докстринг обещал обе
#: формы, регулярка умела одну; поймано прогоном, а не чтением.
_MESSAGE_RE = re.compile(
    r"\b(" + "|".join(sorted(SECRET_FIELD_NAMES)) + r")\b([\"']?\s*[=:]\s*)(\"[^\"]*\"|'[^']*'|[^\s,;)\]}]+)",
    re.IGNORECASE,
)


#: Пароль внутри URL: ``postgres://user:пароль@host``. Отдельным шаблоном,
#: потому что формой «ключ=значение» он не ловится вовсе — найдено живым
#: прогоном редактора на трейсбеке подключения (``dsn=postgres://u:p@h/db``
#: уезжал целиком, хотя строка рядом уже маскировалась).
#:
#: Это НЕ угадывание секрета по виду значения (чего модуль сознательно не
#: делает): позиция между ``:`` и ``@`` в URL — точная, а не вероятностная.
_URL_CREDENTIALS_RE = re.compile(r"(://[^/\s:@]+:)([^@\s/]+)(@)")


def _mask_url_credentials(match: "re.Match[str]") -> str:
    return f"{match.group(1)}{MASK}{match.group(3)}"


def _mask_message_match(match: "re.Match[str]") -> str:
    """Заменить значение, сохранив форму: кавычки остаются кавычками.

    JSON-подобная строка обязана остаться разбираемой — иначе редакция ломала
    бы инструменты, читающие лог, и её первым делом отключили бы.
    """
    name, sep, value = match.group(1), match.group(2), match.group(3)
    if value[:1] in ('"', "'"):
        quote = value[0]
        return f"{name}{sep}{quote}{MASK}{quote}"
    return f"{name}{sep}{MASK}"


def _message_may_carry_secret(message: str) -> bool:
    """Дешёвый детект: стоит ли вообще запускать регулярки по этой строке.

    Цепочка ``or`` развёрнута руками, а не собрана генератором по
    :data:`SECRET_NAME_ROOTS`: генератор стоил вдвое дороже самих поисков
    (0.97 мкс против 0.57), а это путь КАЖДОЙ записи. Расхождение развёрнутого
    списка с константой сторожит тест — глазами такое не удерживают.
    """
    if _URL_MARK in message:
        return True
    low = message.lower()
    return (
        "pass" in low
        or "key" in low
        or "token" in low
        or "secret" in low
        or "auth" in low
        or "pwd" in low
        or "credential" in low
    )


def _has_secret_key(value: Any, depth: int = 0) -> bool:
    """Есть ли что маскировать. Ни одной аллокации — это путь чистой записи."""
    if depth > MAX_DEPTH or not isinstance(value, dict):
        return False
    for key, nested in value.items():
        if isinstance(key, str) and key.lower() in SECRET_FIELD_NAMES:
            return True
        if isinstance(nested, dict) and _has_secret_key(nested, depth + 1):
            return True
    return False


def _redact_mapping(source: Dict[Any, Any], depth: int = 0) -> Dict[Any, Any]:
    """Копия словаря с замаскированными значениями секретных ключей.

    **Копия, а не правка на месте, и это главное свойство модуля.** Словарь
    записи после Ф4.1 один на всех приёмников, а его ``extra`` вдобавок держит
    ссылки на объекты вызывающего (``to_dict`` отдаёт ``extra`` как есть).
    Маскировка на месте испортила бы и запись всем приёмникам сразу, и данные
    того, кто эту запись всего лишь залогировал.
    """
    result = dict(source)
    for key, value in source.items():
        if isinstance(key, str) and key.lower() in SECRET_FIELD_NAMES:
            result[key] = MASK
        elif isinstance(value, dict) and depth < MAX_DEPTH and _has_secret_key(value, depth + 1):
            result[key] = _redact_mapping(value, depth + 1)
    return result


class SecretRedactor:
    """Процессор цепочки: маскирует секреты в ``extra`` и в тексте сообщения.

    Счётчики — на экземпляре, потому что экземпляр свой у каждого менеджера
    (``LoggerManager`` и брат ``ErrorManager``), и складывать их «в среднем по
    процессу» значило бы потерять ответ на вопрос «а на пути ОШИБОК редакция
    работает?».

    **Отказ — fail-closed, и это отличие от общей политики цепочки.** Цепочка
    при броске процессора доставляет запись как есть (``processor_failures``) —
    правильная политика для сэмплинга, но для редакции она означает «сломались,
    поэтому показали секрет оператору». Поэтому свой ``try``: при любом сбое
    наружу уходит запись с маркером вместо ``message`` и ``extra``. Запись
    сохраняется (терять логи редактор не вправе), содержимое — нет.
    """

    __slots__ = ("records_redacted", "redaction_failures")

    def __init__(self) -> None:
        self.records_redacted = 0
        self.redaction_failures = 0

    def __call__(
        self,
        scope: ScopeName,
        level: LogLevel,
        record: Dict[str, Any],
    ) -> Optional[Dict[str, Any]]:
        try:
            extra = record.get("extra")
            message = record.get("message")

            dirty_extra = isinstance(extra, dict) and _has_secret_key(extra)

            # Предфильтр говорит «может быть», регулярка — «есть». Разница не
            # косметическая: слово ``keyboard`` проходит предфильтр, и без
            # сверки результата счётчик ``records_redacted`` считал бы такие
            # записи отредактированными, а копия строилась бы впустую.
            new_message = message
            if isinstance(message, str) and _message_may_carry_secret(message):
                new_message = _MESSAGE_RE.sub(
                    _mask_message_match, _URL_CREDENTIALS_RE.sub(_mask_url_credentials, message)
                )
            dirty_message = new_message is not message and new_message != message

            if not dirty_extra and not dirty_message:
                # Чистая запись едет ТЕМ ЖЕ словарём: контракт цепочки это
                # разрешает, а копия на каждой записи была бы аллокацией ради
                # ничего (записей без секретов — все, кроме считанных).
                return record

            redacted = dict(record)
            if dirty_extra:
                redacted["extra"] = _redact_mapping(extra)
            if dirty_message:
                # Порядок двух подстановок проверен, а не выведен: на четырёх
                # формах (``dsn=`` с URL, ``token=`` с URL, JSON-пара с URL
                # внутри, чистый URL рядом с ключом) оба порядка дают
                # посимвольно одно и то же. Зафиксирован URL-первым, потому что
                # так короче цепочка при вложении «ключ = URL с паролем».
                redacted["message"] = new_message
            self.records_redacted += 1
            return redacted
        except Exception as exc:  # noqa: BLE001 — см. докстринг класса: fail-closed
            self.redaction_failures += 1
            failed = dict(record)
            failed["message"] = f"<редакция секретов не отработала: {type(exc).__name__}>"
            failed["extra"] = {"redaction_failed": type(exc).__name__}
            return failed

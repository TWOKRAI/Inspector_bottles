# -*- coding: utf-8 -*-
"""Сэмплинг повторяющихся записей (Ф7.1) — процессор цепочки Ф4.1.

Зачем
=====

Двенадцать точек ``_log_debug`` в ``RouterManager`` сегодня «включить нельзя»:
каждая стоит на пути КАЖДОГО сообщения, и включённый DEBUG превращает
диагностику в шторм. Живой замер (Б-6, ``webcam_sketch``, ~25 мин): 97 066
повторов ОДНОГО текста, 21 903 потерянных записи, 88 313 вытеснений из
событийного кольца. Правило шапки Ф7 — «события чаще ~1K/с обязаны иметь
отдельный выключаемый ключ» — здесь исполняется не ключом на точку (их
рукописных реестров индустрия не делает, и план это запретил в Out of scope),
а дросселем по ПОВТОРЯЕМОСТИ: одинаковое дросселируется, редкое проходит всегда.

Модель
======

``first_n`` первых записей по ключу проходят всегда — начало всплеска видно
целиком; дальше проходит каждая ``every_mth``-я — темп остаётся наблюдаемым;
после тишины дольше ``burst_reset_sec`` состояние ключа сбрасывается, и новый
всплеск снова получает свои ``first_n``. Без сброса второй всплеск через час
попал бы в хвост счёта первого и был бы почти невидим — а именно всплеск и
есть событие.

Ключ — **уровень + текст сообщения**. Текст ГОТОВЫЙ (цепочка стоит после
форматирования), и это ровно то, что нужно шторму: он повторяет строку
дословно. Обратная сторона названа, а не забыта: точка, чей текст несёт
переменную на каждом событии (``… idx={idx}``), даёт новый ключ каждый раз и
дросселю не поддаётся. Это предел механизма, а не дефект: такую точку лечит не
сэмплинг, а счётчик (правило Ф7 «что нужно постоянно — считать, а не писать»).

Чего этот модуль НЕ делает
==========================

* **не трогает ошибки.** ERROR/CRITICAL проходят всегда, до всякого учёта:
  подавленная ошибка — это молчание там, где инвариант плана требует голоса.
  Верхняя граница уровня настраивается (``max_level``), но ниже ошибок она
  прибита в коде — конфиг не вправе её поднять.
* **не снимает цену call-site.** ``f``-строка собирается ДО входа в ``log()``, и
  подавленная запись всё равно стоит сборку + гейт + ``to_dict``. Сэмплинг
  снимает объём ПОСЛЕ гейта: tap'ы, IPC, батч, диск, ``system``-очередь — ту
  самую петлю, которая измерена в Б-6.
* **не берёт лок.** ``log()`` зовут из многих потоков; гонка на счётчике ключа
  стоит лишнего пропуска или лишнего подавления одной записи, лок на горячем
  пути стоил бы дороже. Тот же выбор, что у счётчиков редактора.

Потолок кардинальности и его политика (Ф7.х)
============================================

Первая редакция на переполнении карты **насыщалась навсегда**: новые ключи не
заводились и проходили без дросселя. Довод был такой — полная чистка вернула бы
``first_n`` сразу всем ключам, то есть шторм прорвался бы заново ровно в момент,
когда карту переполнил он же.

Ревью фазы показало, что цена этого выбора больше названной: после насыщения
дроссель умирает **именно для шторма**, ради которого заведён — 50 000 повторов
одного текста прошли целиком, подавлено 0. И насыщение достигается не в теории:
за 90 секунд живого прогона карта набрала 204 ключа, экстраполяция до потолка —
около получаса, то есть КОРОЧЕ шторма Б-6 (~25 минут наблюдения при живом росте).

Довод против чистки при этом остался верным — он просто был про НЕ ТУ операцию.
Поэтому политика теперь двухступенчатая, и обе ступени честные:

1. **Подмести протухшее.** Ключ, которого не видели дольше ``burst_reset_sec``,
   при следующей встрече и так получит свои ``first_n`` (правило всплеска) —
   значит его состояние уже ничего не значит, и удалить его **бесплатно по
   смыслу**. Проход по карте бывает только на переполнении, поэтому горячий путь
   не платит ни одной лишней операции: LRU-порядок здесь НЕ поддерживается
   намеренно, ``last_at`` и так пишется на каждой записи.
2. **Насытиться, если мести нечего.** Карта, целиком забитая ГОРЯЧИМИ ключами, —
   это честный шторм высокой кардинальности, и дроссель по повторяемости против
   него бессилен по построению (лечится счётчиком вместо записи, правило шапки
   Ф7). Тогда работает прежнее поведение: новый ключ не заводится, запись
   проходит, ``keys_saturated`` растёт — то есть «дроссель включён и НЕ работает»
   остаётся отдельно спрашиваемым фактом, а не сливается с «потерь нет».

Бесплодный проход не повторяется на каждой записи: если мести было нечего,
следующая попытка не раньше чем через ``burst_reset_sec`` — раньше протухнуть
физически некому.
"""

from __future__ import annotations

import time
from typing import Any, Callable, Dict, Optional, Tuple

from ...channel_routing_module.levels import (
    ERROR_SEVERITY,
    UNKNOWN_SEVERITY,
    record_severity,
    severity_of,
)
from .log_config import LogLevel, ScopeName

#: Потолок карты ключей — класс Н5, тот же, что у ``_DECISION_CACHE_CEILING``.
#: Ключ содержит ТЕКСТ записи, то есть по построению растёт без предела там, где
#: текст несёт переменную.
KEY_CEILING = 4096

#: Поле, которым пропущенная запись говорит, сколько её однокашников подавлено
#: с прошлого пропуска. Глобальный ``records_dropped_by_processor`` отвечает
#: «сколько всего», это поле — «чего именно»: без него оператор видит цифру
#: потерь без адреса.
SKIPPED_FIELD = "sampled_skipped"


class _KeyState:
    """Окно одного ключа: сколько видели, когда последний раз, сколько подавили."""

    __slots__ = ("seen", "last_at", "suppressed")

    def __init__(self, now: float) -> None:
        self.seen = 1
        self.last_at = now
        self.suppressed = 0


class RateSampler:
    """Процессор цепочки: дросселирует повторяющиеся записи.

    Экземпляр — на менеджера (как у редактора Ф4.5): у ``LoggerManager`` и
    брата-``ErrorManager`` свои счётчики, и «в среднем по процессу» скрыло бы
    ответ на вопрос «а на пути ошибок сэмплинг не съел ли лишнего».

    Выключенное состояние выражается **параметром** (``first_n <= 0``), а не
    отдельным булевым флагом: два способа сказать «выключено» рано или поздно
    разъезжаются, и «флаги не костыли» — правило этого плана.
    """

    __slots__ = (
        "_first_n",
        "_every_mth",
        "_burst_reset_sec",
        "_max_severity",
        "_time_fn",
        "_keys",
        "_next_sweep_at",
        "records_sampled_out",
        "keys_saturated",
        "keys_expired",
    )

    def __init__(
        self,
        first_n: int = 0,
        every_mth: int = 100,
        burst_reset_sec: float = 5.0,
        max_level: str = "DEBUG",
        time_fn: Optional[Callable[[], float]] = None,
    ) -> None:
        # Часы — ЗАВИСИМОСТЬ объекта, а не глобальный ``time.monotonic``:
        # тест на burst обязан двигать время сам, а глобальный патч часов уже
        # приносил в этот проект флейк (правило записано в памяти проекта).
        self._time_fn: Callable[[], float] = time_fn or time.monotonic
        self._keys: Dict[Tuple[int, Any], _KeyState] = {}
        # Момент, раньше которого подметать карту бессмысленно: прошлый проход
        # ничего не нашёл, а протухнуть новому нечему быстрее ``burst_reset_sec``.
        self._next_sweep_at = 0.0
        self.records_sampled_out = 0
        self.keys_saturated = 0
        self.keys_expired = 0
        self.configure(first_n, every_mth, burst_reset_sec, max_level)

    # -----------------------------------------------------------------
    # Конфигурация
    # -----------------------------------------------------------------

    def configure(
        self,
        first_n: int,
        every_mth: int,
        burst_reset_sec: float,
        max_level: str,
    ) -> None:
        """Применить параметры БЕЗ сброса окон.

        Окна переживают ``reload`` намеренно. Пересоздание сэмплера (или чистка
        карты здесь) означало бы: оператор, дёрнувший конфиг под штормом,
        получает шторм заново — «идемпотентность ≠ монотонность». Параметры
        меняются, состояние продолжается.
        """
        self._first_n = int(first_n)
        # Ноль и отрицательное как «каждая M-я» бессмысленны и дали бы деление
        # на ноль на горячем пути; 1 = «дальше проходит всё», это законный
        # способ сказать «дроссель только на первых N».
        self._every_mth = max(1, int(every_mth))
        self._burst_reset_sec = float(burst_reset_sec)
        # ``_next_sweep_at`` — не окно ключа, а КЭШ решения о расписании,
        # выведенный из ПРЕЖНЕГО значения окна. Оставить его — значит «оператор
        # сузил окно под штормом, а подметание заблокировано до конца старого»
        # (при окне в сутки — на сутки). Сброс бесплатен: лишний проход случится
        # не раньше следующего переполнения. Окна КЛЮЧЕЙ при этом не трогаются —
        # обещание докстринга держится.
        self._next_sweep_at = 0.0
        severity = severity_of(max_level)
        # Непонятое имя уровня → сэмплируем только DEBUG. Fail-quiet здесь
        # безопаснее fail-open: опечатка в конфиге не должна начать глушить
        # WARNING. Само имя отвергается валидатором конфига на границе.
        if severity == UNKNOWN_SEVERITY:
            severity = severity_of("DEBUG")
        # Ошибки не сэмплируются НИКОГДА: потолок из конфига обрезан кодом.
        self._max_severity = min(severity, ERROR_SEVERITY - 1)

    # ``enabled`` здесь БЫЛ и удалён (Ф7.х, minor ревью Ф7): свойство не читал
    # никто, а выключенность выражается параметром (``first_n <= 0``) — второй
    # способ спросить то же самое рано или поздно разъезжается с первым.

    # -----------------------------------------------------------------
    # Горячий путь
    # -----------------------------------------------------------------

    def __call__(
        self,
        scope: ScopeName,
        level: LogLevel,
        record: Dict[str, Any],
    ) -> Optional[Dict[str, Any]]:
        if self._first_n <= 0:
            return record

        severity = record_severity(level)
        if severity > self._max_severity:
            # Сюда попадают и ERROR/CRITICAL (потолок обрезан в configure), и
            # всё, что оператор объявил слишком важным для дросселя.
            return record

        key = (severity, record.get("message"))
        state = self._keys.get(key)
        now = self._time_fn()

        if state is None:
            if len(self._keys) >= KEY_CEILING and not self._make_room(now):
                # Мести было нечего: карта полна ГОРЯЧИМИ ключами — честный шторм
                # высокой кардинальности, против которого дроссель по
                # повторяемости бессилен по построению. Новый ключ не заводим,
                # запись проходит. Считаем КАЖДЫЙ такой случай, а не только
                # переход: «карта переполнилась однажды» и «мимо дросселя идёт
                # постоянный поток» — разные факты, и лечатся они разным.
                self.keys_saturated += 1
                return record
            self._keys[key] = _KeyState(now)
            return record

        if now - state.last_at > self._burst_reset_sec:
            # Новый всплеск: считаем с нуля. Подавленный хвост прошлого всплеска
            # уже учтён глобальным счётчиком, а его число теряется здесь
            # намеренно — оно относилось к событию, которое кончилось.
            state.seen = 1
            state.suppressed = 0
            state.last_at = now
            return record

        state.last_at = now
        state.seen += 1

        if state.seen <= self._first_n:
            return record

        if (state.seen - self._first_n) % self._every_mth != 0:
            state.suppressed += 1
            self.records_sampled_out += 1
            return None

        if not state.suppressed:
            return record

        # Копия, а не правка на месте: словарь записи после Ф4.1 один на всех
        # приёмников, а его ``extra`` держит ссылки на объекты вызывающего.
        # Правка на месте испортила бы и запись, и чужие данные.
        passed = dict(record)
        extra = passed.get("extra")
        merged = dict(extra) if isinstance(extra, dict) else {}
        merged[SKIPPED_FIELD] = state.suppressed
        passed["extra"] = merged
        state.suppressed = 0
        return passed

    # -----------------------------------------------------------------
    # Потолок кардинальности
    # -----------------------------------------------------------------

    def _make_room(self, now: float) -> bool:
        """Подмести протухшие ключи. ``True`` — место освободилось.

        Протухший = не встречался дольше ``burst_reset_sec``. Его состояние уже
        ничего не значит: при следующей встрече правило всплеска всё равно
        начнёт счёт с нуля, — поэтому удаление здесь **бесплатно по смыслу**, в
        отличие от полной чистки, которая вернула бы ``first_n`` и горячим тоже.

        Проход по всей карте — только на переполнении и не чаще, чем раз в
        ``burst_reset_sec``, если прошлый оказался бесплодным: раньше протухнуть
        физически некому, а повторять O(N) на каждой записи под штормом уникальных
        ключей значило бы вылечить объём ценой процессора.
        """
        if now < self._next_sweep_at:
            return False
        cutoff = now - self._burst_reset_sec
        # ``list(...)`` — снимок: класс безлоковый, и два потока, попавшие сюда
        # одновременно, иначе ловили бы ``dictionary changed size during
        # iteration``. ``pop(key, None)`` вместо ``del`` — идемпотентность по той
        # же причине: пересекающиеся списки протухших дают ``KeyError`` на
        # втором удалении. Оба отказа воспроизведены стендом ревью корзины
        # (8 потоков, шторм уникальных ключей — красный каждый прогон); исключение
        # отсюда выходит из процессора и ПИШЕТСЯ аварийным путём, то есть механизм
        # снижения объёма на отказе объём добавляет.
        stale = [key for key, state in list(self._keys.items()) if state.last_at < cutoff]
        if not stale:
            self._next_sweep_at = now + self._burst_reset_sec
            return False
        removed = 0
        for key in stale:
            if self._keys.pop(key, None) is not None:
                removed += 1
        if not removed:
            # Всё протухшее вымел параллельный поток — для НАШЕГО вызывающего
            # места так и не появилось, честный ответ «мести было нечего».
            self._next_sweep_at = now + self._burst_reset_sec
            return False
        self.keys_expired += removed
        self._next_sweep_at = 0.0
        return True

    # -----------------------------------------------------------------
    # Наблюдаемость
    # -----------------------------------------------------------------

    @property
    def keys_tracked(self) -> int:
        """Сколько ключей под учётом. Приближение к потолку видно заранее."""
        return len(self._keys)

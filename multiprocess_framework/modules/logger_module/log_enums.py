# -*- coding: utf-8 -*-
"""Уровни и области логирования — рантайм LoggerManager (без Pydantic).

Уровень (``LogLevel``) остаётся enum'ом: перечень уровней задан индустрией и
закрыт. Область (``LogScope``) с Ф2.4 — набор строковых констант: список групп
открыт, и новая заводится конфигом приложения, а не правкой этого файла.

Ранги уровней (``LEVEL_ORDER`` / ``level_rank`` / ``is_error_level``) здесь
БОЛЬШЕ НЕ ЖИВУТ: они общее хозяйство трёх плоскостей наблюдаемости и переехали
в ``channel_routing_module.levels`` (Ф0.6, резидуал R6). База не имеет права
зависеть от своего потомка, а tap-механика с порогом уровня поднята именно в
базу. Здесь остались только enum'ы формата лог-записи — статистике они не нужны.
"""

from enum import Enum

#: Хэш по identity вместо ``Enum.__hash__`` (2.2, измерено).
#:
#: ``Enum.__hash__`` — **Python-функция**, а не слот C-уровня: она делает
#: ``hash(self._name_)``, то есть на каждый хэш тратится вызов интерпретатора и
#: хэш строки. Замер: ``hash(LogLevel.DEBUG)`` — **91 нс** против **11 нс** у
#: ``hash(int)``. ``LogLevel`` стоит в ключе кэша решений гейта
#: (``LoggerCore.should_log``), и `dict.get` по такому ключу стоил **165 нс**
#: против **23 нс** после этой правки — семикратно, на КАЖДОЙ записи, включая
#: отклонённую гейтом (то есть на самом дешёвом исходе).
#:
#: Ф2.4: вторым enum'ом в том же ключе был ``LogScope``; он стал обычной строкой,
#: и своего ``__hash__`` ему не нужно — CPython держит хэш строки в самом объекте.
#:
#: Замена корректна, а не «оптимизация на глаз»: члены enum — синглтоны, а
#: ``Enum`` не определяет ``__eq__``, поэтому равенство здесь и так identity.
#: Хэш по identity ему ровно соответствует. Проверено: ``LogLevel.DEBUG == "DEBUG"``
#: остаётся ``False``, дедупликация в множестве работает.
#:
#: Отдельная константа, а не строчка в теле каждого класса: имя объясняет, что
#: это осознанная замена, а не забытый ``__hash__`` после переопределения
#: ``__eq__``. Закреплено тестом ``test_gate_cost_bench.py``.
_IDENTITY_HASH = object.__hash__


class LogLevel(Enum):
    """Уровни логирования."""

    DEBUG = "DEBUG"
    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"

    __hash__ = _IDENTITY_HASH


#: Тип имени группы логирования. Обычная строка (Ф2.4) — псевдоним заведён
#: ради читаемости сигнатур: ``scope: ScopeName`` говорит «сюда идёт имя
#: группы», чего голый ``str`` рядом с ``module: str`` не говорит.
ScopeName = str


class LogScope:
    """Преднастроенные имена групп логирования — **строки, а не enum** (Ф2.4).

    Значение константы совпадает с ключом конфига (``scopes.SYSTEM``) и с тем,
    что уезжает в записи. **Одно написание на всё** — решение Р-2.4-А.

    До Ф2.4 здесь был ``Enum``, и написаний было ДВА, расходившихся не регистром,
    а словом: ключ конфига брался из ``scope.name`` (``PERFORMANCE``), а в записи
    ехал ``scope.value`` (``perf``). Второй словарь имён — ровно то, что фаза
    сносит; заодно исчезла и причина, по которой новую группу нельзя было завести
    конфигом: ``log()`` требовал члена enum, то есть правки кода фреймворка.

    **Класс — набор дефолтов, а не закрытый перечень.** ``log()`` принимает любую
    строку; эти шесть имён живут здесь потому, что на них ссылаются удобные методы
    менеджера (``log_system``, ``log_business``, …), а не потому, что список чем-то
    ограничен. Прикладные группы объявляются в конфиге приложения и во фреймворк
    не попадают — то же разделение владения, что у имён приёмников (Р-2.6-Г).

    Скоуп, которого нет в конфиге, — законная ситуация (группа ещё не объявлена),
    но не молчаливая: ``LoggerCore`` говорит о нём вслух один раз на имя
    (Р-2.4-Б). Повод не теоретический: ``AUDIT`` и ``SECURITY`` в дефолтах не
    объявлены с самого начала и всё это время уходили на запасной маршрут молча.

    ``_IDENTITY_HASH`` здесь больше не нужен и **не является потерей**: хэш строки
    CPython кэширует в самом объекте, поэтому ключ кэша решений
    ``(scope, level, module)`` со строкой не дороже прежнего. Проверено замером
    (``test_gate_cost_bench.py``), а не выведено — прежняя редакция соседнего
    докстринга уверенно объясняла хэш enum'ов неправильно, и цена той ошибки
    была семикратной.
    """

    __slots__ = ()

    SYSTEM: ScopeName = "SYSTEM"
    BUSINESS: ScopeName = "BUSINESS"
    PERFORMANCE: ScopeName = "PERFORMANCE"
    AUDIT: ScopeName = "AUDIT"
    SECURITY: ScopeName = "SECURITY"
    DEBUG: ScopeName = "DEBUG"


#: Преднастроенные имена перечнем — для тех, кому нужно ПРОЙТИ по дефолтам
#: (сетки тестов, документация). До Ф2.4 это давала итерация по ``Enum``.
#:
#: **Это не перечень допустимых значений, и проверять по нему нельзя.**
#: ``log()`` принимает любую строку — в том и смысл задачи; группа, которой
#: здесь нет, законна ровно настолько же, насколько эти шесть. Валидация «скоуп
#: должен быть из списка» вернула бы правку кода фреймворка на заведение группы,
#: то есть отменила бы 2.4 целиком.
PRESET_SCOPES: tuple[ScopeName, ...] = (
    LogScope.SYSTEM,
    LogScope.BUSINESS,
    LogScope.PERFORMANCE,
    LogScope.AUDIT,
    LogScope.SECURITY,
    LogScope.DEBUG,
)

# -*- coding: utf-8 -*-
"""Уровни и области логирования — enum для рантайма LoggerManager (без Pydantic).

Ранги уровней (``LEVEL_ORDER`` / ``level_rank`` / ``is_error_level``) здесь
БОЛЬШЕ НЕ ЖИВУТ: они общее хозяйство трёх плоскостей наблюдаемости и переехали
в ``channel_routing_module.levels`` (Ф0.6, резидуал R6). База не имеет права
зависеть от своего потомка, а tap-механика с порогом уровня поднята именно в
базу. Здесь остались только enum'ы формата лог-записи — статистике они не нужны.
"""

from enum import Enum

#: Хэш по identity вместо ``Enum.__hash__`` (2.2, измерено).
#:
#: ``Enum.__hash__`` — **Python-функция**, а не слот C-уровня: она делает
#: ``hash(self._name_)``, то есть на каждый хэш тратится вызов интерпретатора и
#: хэш строки. Замер: ``hash(LogLevel.DEBUG)`` — **91 нс** против **11 нс** у
#: ``hash(int)``. Оба enum'а стоят в ключе кэша решений гейта
#: (``LoggerCore.should_log``), и `dict.get` по такому ключу стоил **165 нс**
#: против **23 нс** после этой правки — семикратно, на КАЖДОЙ записи, включая
#: отклонённую гейтом (то есть на самом дешёвом исходе).
#:
#: Замена корректна, а не «оптимизация на глаз»: члены enum — синглтоны, а
#: ``Enum`` не определяет ``__eq__``, поэтому равенство здесь и так identity.
#: Хэш по identity ему ровно соответствует. Проверено: ``LogLevel.DEBUG == "DEBUG"``
#: остаётся ``False``, дедупликация в множестве работает.
#:
#: Отдельная константа, а не строчка в теле каждого класса: имя объясняет, что
#: это осознанная замена, а не забытый ``__hash__`` после переопределения
#: ``__eq__``. Закреплено тестом ``test_gate_cost_bench.py``.
_IDENTITY_HASH = object.__hash__


class LogLevel(Enum):
    """Уровни логирования."""

    DEBUG = "DEBUG"
    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"

    __hash__ = _IDENTITY_HASH


class LogScope(Enum):
    """Области логирования (значение — строка для сериализации)."""

    SYSTEM = "system"
    BUSINESS = "business"
    PERFORMANCE = "perf"
    AUDIT = "audit"
    SECURITY = "security"
    DEBUG = "debug"

    __hash__ = _IDENTITY_HASH

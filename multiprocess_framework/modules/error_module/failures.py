# -*- coding: utf-8 -*-
"""Классы отказа для мест, где объекта исключения НЕТ (Task 1.3b).

Зачем вообще типы, а не общий ``RuntimeError``
----------------------------------------------

Ключ окна голоса — пара ``(класс отказа, context)`` (см.
``HealthState.report_error`` и ``ObservableMixin.report_error``). Если каждый
отказ, пришедший ВОЗВРАТОМ ЗНАЧЕНИЯ, фабриковать общим ``RuntimeError``, ключ
вырождается: «камера не открылась» и «воркер не создался» в одном контексте
получают ОДИН ключ и начинают глушить друг друга — первый отказ на всё окно
делает второй немым. Разные имена классов разводят ключи без единой строчки
дополнительной логики.

Граница применения — узкая, и она здесь не пожелание
-----------------------------------------------------

Эти классы — **только** для сайтов, где отказ сообщён кодом возврата
(``isOpened() -> False``, ``create_worker(...) -> False``, ``ok is False``) и
исключение приходится ФАБРИКОВАТЬ. Сервис или плагин со своим доменом отказов
заводит СВОЮ иерархию и пользуется ей: ``Services/device_hub/errors.py``,
``Services/modbus/sdk/errors.py``, ``Services/hikvision_camera/sdk/errors.py``
уже дают различимые имена типов, и переводить их на общефреймворковую
таксономию не нужно — это был бы второй словарь поверх работающего первого.

Без этой границы, записанной здесь, вариант «маленький набор для фабрикации»
через пару лет дрейфует в «единая таксономия всего»: автор нового плагина
видит фреймворковые классы и сливает в них домен, у которого были свои имена.

Как пользоваться
----------------

    from multiprocess_framework.modules.error_module.interfaces import DeviceOpenFailed

    if not cap.isOpened():
        ctx.health.report_error(
            DeviceOpenFailed(f"камера {device_id} не открылась"),
            context="capture.start",
            camera_id=camera_id,
            device_id=device_id,
        )

Деталь снятого лог-сообщения уезжает в ``**fields`` СТРУКТУРНО, а не в текст:
по тексту фильтр по полю не ищет.
"""

from __future__ import annotations

__all__ = [
    "FrameworkFailure",
    "ResourceUnavailable",
    "SubsystemStartFailed",
    "DeviceOpenFailed",
    "ObservabilityMisuse",
]


class FrameworkFailure(Exception):
    """База классов отказа фреймворка.

    Ловить её осмысленно только в самом общем обработчике: ветки ``except``
    прикладного кода должны называть конкретный класс, иначе тип перестаёт
    нести информацию, ради которой заведён.
    """


class ResourceUnavailable(FrameworkFailure):
    """Ресурс, на который рассчитывали, недоступен: файл, БД, сокет, порт.

    Отличие от :class:`SubsystemStartFailed` — здесь наша сторона исправна, а
    внешнее не отвечает; это состояние обычно временное и повторяемое.
    """


class SubsystemStartFailed(FrameworkFailure):
    """Подсистема не встала или не убралась: ``create_worker``/``initialize``/
    регистрация/подтверждение cleanup вернули отказ.

    Отличие от :class:`ResourceUnavailable` — отказ внутри нашего периметра
    (имя занято, слот отсутствует, конфигурация не сошлась), и сам по себе он
    не рассосётся.

    **Незавершённый teardown — тоже сюда, и это названо намеренно.** Сайт
    ``process_manager_process.py`` «cleanup не подтверждён» лёг под этот класс
    при миграции Task 1.3b, и исполнитель честно назвал выбор натяжкой: имя
    говорит «не поднялась». Разбор ревью: заводить четвёртый класс дороже
    пользы — ключ окна не вырождается (три сайта PM несут три разных
    ``context``), потребителей, читающих ТИП отказа, нет (греп по дереву даёт
    только тесты), а контракт-тест намеренно пинит размер набора, чтобы рост
    был осознанным. Поэтому расширена ГРАНИЦА КЛАССА, а не набор: иначе класс и
    его единственный нетривиальный сайт расходились бы молча.
    """


class DeviceOpenFailed(FrameworkFailure):
    """Устройство не открылось: камера, привод, драйвер шины.

    Отдельно от :class:`ResourceUnavailable` намеренно: это самый частый отказ
    прикладного слоя, у него свой ритм повторов и свой адресат на пульте, и
    сливать его с «файл не найден» в один ключ окна значит терять оба.
    """


class ObservabilityMisuse(FrameworkFailure):
    """Саму дорогу наблюдаемости позвали неправильно.

    Заводится ``ObservableMixin._as_incident``, когда в ``_track_error``
    приехало не исключение. Отдельный класс, а не ``TypeError``: бросок внутри
    ``except``-ветки подменил бы исходную ошибку своей, поэтому отказ дороги
    становится ФАКТОМ на той же дороге. Ненулевая книга ``_track_error_misuse``
    в readback означает, что где-то в дереве живёт кривой вызов — и это
    сообщение обязано быть прочитано, а не полежать счётчиком.
    """

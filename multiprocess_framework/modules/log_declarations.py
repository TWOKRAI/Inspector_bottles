# -*- coding: utf-8 -*-
"""Объявление источника рядом с модулем: имя и правило-дефолт (Ф2.7).

**Зачем.** Ф2.6 положила имя источника константой `LOG_SOURCE` в `interfaces.py`
модуля — там же, где публичный API. Этого хватило, чтобы штамп и правило перестали
печататься дважды, но объявление осталось **пассивным**: узнать «какие имена вообще
объявлены» можно было только грепом, а правило-дефолт модуля пришлось бы писать в
центральный конфиг — то есть при добавлении модуля трогать общий файл.

Здесь объявление становится активным. Модуль зовёт :func:`declare_log_source` рядом
со своей константой, и дальше:

* имя попадает в :func:`declared_sources` — ответ на «что бывает» ДО первой записи
  (``seen_sources`` отвечает только про тех, кто уже писал);
* правило-дефолт, если оно есть, уезжает в слой L0 — под конфиг приложения, а не
  поверх него: модуль знает про себя, но последнее слово за тем, кто систему
  собирает.

**Центральных правок ноль.** Реестр наполняется импортом самого модуля, а не списком
в общем файле: список пришлось бы править при каждом добавлении — ровно та работа,
ради устранения которой задача и делается.

**Конфликт двух объявлений на одно имя — отказ, а не выбор.** Тихое разрешение
(«побеждает последний импортированный») сделало бы поведение зависимым от порядка
импортов, то есть от того, что никто не считает настройкой. Повторное объявление
ТЕМ ЖЕ владельцем — не конфликт: модуль переимпортируют (reload в тестах, spawn
дочернего процесса), и падать на этом нельзя.

Реестр процессный, как и всё остальное состояние наблюдаемости: дочерний процесс
импортирует свои модули сам и собирает свой набор.

**Лежит рядом с `_fallback.py`, а не внутри `logger_module`, и это не вкусовщина.**
Объявление зовут из `interfaces.py` модулей, которые сам логгер и импортирует
(`dispatch_module` → `channel_routing_manager` → …); импорт через пакет логгера
замкнул бы кольцо — воспроизведено на первой редакции: `ImportError: cannot import
name 'ChannelRoutingConfig' from partially initialized module`. Здесь лист без
зависимостей, тот же приём, что у аварийного выхода.
"""

from __future__ import annotations

import threading
from typing import Dict, Optional, Tuple

__all__ = [
    "declare_log_source",
    "declared_sources",
    "declared_rules",
    "forget_declarations",
]

#: имя источника → (владелец, правило-дефолт или None)
_DECLARED: Dict[str, Tuple[str, Optional[object]]] = {}
_LOCK = threading.Lock()

#: Ф2.х (Н2): правила уже читались сборкой конфига хотя бы раз. Снимок в сборку
#: попадает на момент чтения; правило, объявленное ПОЗЖЕ, в уже собранные
#: конфиги не попало — и молчать об этом нельзя: симптом «правило написано, а
#: не действует» иначе ищется в конфиге, где всё верно.
_RULES_CONSUMED: bool = False


def declare_log_source(name: str, *, owner: str, rule: Optional[object] = None) -> str:
    """Объявить имя источника (и, опционально, его правило-дефолт).

    Args:
        name: точечное имя источника — то же, что уезжает в ``module`` записи.
        owner: кто объявляет, обычно ``__name__`` объявляющего файла. Нужен, чтобы
            отличить повторный импорт того же модуля от ДВУХ модулей, назвавшихся
            одинаково: первое законно, второе — ошибка конфигурации.
        rule: правило-дефолт (``LoggerRuleSchema``) либо ``None``. Уезжает в слой
            L0, то есть под конфиг приложения.

    Returns:
        То же ``name`` — чтобы объявление писалось одной строкой рядом с константой.

    Raises:
        ValueError: имя уже объявлено ДРУГИМ владельцем либо тем же владельцем с
            другим правилом. Отказ, а не предупреждение: у такого состояния нет
            правильного прочтения, и любой молчаливый выбор зависел бы от порядка
            импортов. Тот же отказ — правило не той формы (см. ниже): словарь
            вместо схемы упал бы позже в сборке конфига, далеко от виновника и
            без его имени (класс «model_copy не валидирует», уже стрелявший
            в этой фазе дважды).
    """
    # Ф2.х (Н3): форма правила проверяется ЗДЕСЬ, на границе реестра, а не там,
    # где сборка позовёт .model_dump(). Утиная проверка, а не isinstance: лист
    # не может импортировать схему логгера — кольцо воспроизведено в шапке.
    if rule is not None and not callable(getattr(rule, "model_dump", None)):
        raise ValueError(
            f"правило-дефолт источника '{name}' от '{owner}' — {type(rule).__name__}, "
            f"а нужна схема правила (LoggerRuleSchema). Словарь здесь молча доехал бы "
            f"до сборки конфига и упал там без имени виновника"
        )
    with _LOCK:
        previous = _DECLARED.get(name)
        if previous is not None:
            prev_owner, prev_rule = previous
            if prev_owner == owner and _same_rule(prev_rule, rule):
                return name  # повторный импорт того же модуля — не конфликт
            raise ValueError(
                f"источник '{name}' уже объявлен модулем '{prev_owner}', "
                f"повторное объявление от '{owner}' с другим содержимым отклонено. "
                f"Два объявления на одно имя означают, что действующее правило зависит "
                f"от порядка импортов"
            )
        _DECLARED[name] = (owner, rule)
        consumed = _RULES_CONSUMED
    # Ф2.х (Н2): boot-конфиг детям собирает ассемблер в РОДИТЕЛЕ, пересборку —
    # сам ребёнок; оба берут снимок реестра на момент чтения. Правило, объявленное
    # после первого чтения (ленивый импорт, плагин), в уже собранные конфиги не
    # попало — говорим об этом аварийным выходом, потому что предмет жалобы —
    # ровно та раскладка, которой запись поехала бы.
    if consumed and rule is not None:
        from ._fallback import emergency_log

        emergency_log(
            __name__,
            "WARNING",
            f"правило-дефолт источника '{name}' ({owner}) объявлено ПОСЛЕ сборки "
            f"конфига наблюдаемости: в уже собранные конфиги оно не попало и начнёт "
            f"действовать со следующей сборки (reload либо новый процесс)",
        )
    return name


def declared_sources() -> Dict[str, str]:
    """Объявленные имена: ``имя → владелец``.

    Отличается от ``LoggerCore.seen_sources`` тем же, чем каталог от журнала:
    здесь то, что МОЖЕТ писать, там — то, что уже писало. Источник, у которого всё
    гасится порогом, в журнале не появится вовсе, а в каталоге он есть.
    """
    with _LOCK:
        return {name: owner for name, (owner, _rule) in _DECLARED.items()}


def declared_rules() -> Dict[str, object]:
    """Правила-дефолты объявивших модулей — вклад в слой L0.

    Пусто, пока ни один модуль правила не объявил, и это нормальное состояние:
    имя объявляют почти все, а собственный порог — только тот, кому есть что
    сказать про себя.

    Чтение помечает реестр «снимок взят» (Ф2.х, Н2): сборка конфига берёт
    правила ровно этим вызовом, и всё, что объявится позже, в неё уже не
    попало. Позднее объявление правила с этого момента слышно аварийным
    выходом — см. :func:`declare_log_source`.
    """
    global _RULES_CONSUMED
    with _LOCK:
        _RULES_CONSUMED = True
        return {name: rule for name, (_owner, rule) in _DECLARED.items() if rule is not None}


def forget_declarations() -> None:
    """Очистить реестр. **Только для тестов.**

    Прод-вызовов нет и быть не должно: реестр наполняется импортом, а импорт в
    живом процессе не отменяют. Функция существует, чтобы тест конфликта не
    оставлял след соседям — иначе порядок тестов начал бы значить.

    Сбрасывает и отметку «снимок взят» — по той же причине: иначе первый тест,
    прочитавший правила, включал бы поздние предупреждения всем соседям.
    """
    global _RULES_CONSUMED
    with _LOCK:
        _DECLARED.clear()
        _RULES_CONSUMED = False


def _same_rule(left: Optional[object], right: Optional[object]) -> bool:
    """Равны ли два правила по СОДЕРЖИМОМУ, а не по identity.

    Повторный импорт создаёт новый объект схемы с теми же полями, и сравнение по
    identity объявило бы конфликт там, где его нет, — то есть уронило бы процесс
    на совершенно законном reload.

    **Обычное ``==`` этого достаточно, и проверено это слом-инъекцией, а не
    предположением.** Первая редакция сравнивала ``model_dump()``, считая, что
    иначе сработает identity. Инъекция «сравнивать по identity» дала **ноль**
    красных — потому что `BaseModel.__eq__` Pydantic сравнивает поля сам, и ветка
    с ``model_dump`` не добавляла ничего, кроме двух словарей на каждый вызов.
    Убрана; свойство сторожит тест ``test_an_equal_rule_re_declared_passes``.
    """
    if left is None or right is None:
        return left is None and right is None
    return bool(left == right)

"""Опасности самого помощника дорог — писано АВТОРОМ, а не приёмкой.

Слепая приёмка (``test_road_cost_contract.py``) сверяет контракт, который ей
назвали. Здесь — то, что видно только изнутри механизма, и появилось оно не из
головы: инъекция I5 матрицы Ф2 (``plans/observability-closure/injections-phase-2.md``)
сделала :func:`~._road_cost.timed_pair` последовательным вместо «вперемежку»,
сняв ровно ту защиту, ради которой функция написана, — и дала **НОЛЬ красных из
51**. Заявленное свойство не сторожил никто.

**Почему сторож БЕЗ ПОРОГА.** Первая моя редакция мерила отношение при
искусственном дрейфе и требовала «0.90 < x < 1.10». Это абсолютный порог на
шумной величине — та самая болезнь, которую фаза вычищала в Н-7, и вдобавок
порог был взят с потолка. Здесь вместо него — те же СОБЫТИЯ, которыми меряет
:func:`~._road_cost.count_calls`: порядок блоков и арифметика на подставных
часах. Оба литерала точны и от машины не зависят.

**Разовый замер, ради которого всё это существует** (стенд с дрейфом по стенным
часам, обе стороны делают ОДНО И ТО ЖЕ, верный ответ 1.000):

===========================  ==================  ====================
модель фона                  вперемежку          последовательно
===========================  ==================  ====================
ровный (контроль)            0.995 / 1.002       1.011 / 1.007
рампа по часам               0.919 / 0.903       **0.452 / 0.440**
ступенька ×2                 1.002 / 0.978       **0.376 / 0.380**
живая горелка-поток          0.983 / 1.002       **0.506 / 0.589**
===========================  ==================  ====================

Это ЗАМЕР, а не тест: воспроизводить его в прогоне значило бы вернуть порог на
шумной величине. Модель дрейфа обязана идти по СТЕННЫМ ЧАСАМ и быть общей для
обеих сторон — при счётчике «на сторону» обе формы замера тождественны по
построению, и такой стенд показывает ноль независимо от того, сломан помощник
или нет (на этом я и ошибся первым стендом).
"""

from __future__ import annotations

import threading
import time
from typing import Any, List, Tuple

import pytest

from . import _road_cost
from ._road_cost import timed_pair


class TestTheMeasurementInterleavesTheTwoSides:
    """Литерал А — ПОРЯДОК блоков и их число."""

    def test_the_two_sides_alternate_across_ten_blocks(self) -> None:
        """Пять окон, и в каждом сначала одна сторона, потом другая.

        Последовательная форма («сначала все окна одной стороны») даёт ДВА
        блока вместо десяти — литерал ловит её на порядке, не на времени.
        Число вызовов каждой стороны — ``5 * repeats``: оно ловит форму, где
        окон стало не пять.
        """
        order: List[str] = []
        repeats = 2
        timed_pair(lambda: order.append("n"), lambda: order.append("o"), repeats=repeats)

        blocks: List[str] = [side for i, side in enumerate(order) if i == 0 or order[i - 1] != side]
        assert blocks == ["n", "o"] * 5, (
            f"стороны перестали чередоваться: блоки {blocks} вместо десяти n/o вперемежку — "
            "замер сравнивает уже не реализации, а два разных окна загрузки машины"
        )
        assert (order.count("n"), order.count("o")) == (5 * repeats, 5 * repeats), (
            f"число вызовов сторон изменилось: {(order.count('n'), order.count('o'))} "
            f"вместо {(5 * repeats, 5 * repeats)} — окон стало не пять"
        )


class TestTheMeasurementTakesTheMinimumOfItsWindows:
    """Литерал Б — арифметика на ПОДСТАВНЫХ часах, без единой настоящей секунды."""

    #: Длительности десяти окон в порядке их снятия: n, o, n, o, …
    #: Окна стороны «n» — 9, 5, 7, 6, 8 (минимум 5, ВТОРОЕ окно);
    #: окна стороны «o» — 4, 2, 3, 10, 6 (минимум 2, ВТОРОЕ окно).
    #: Оба минимума ВНУТРЕННИЕ — ни первое окно, ни последнее, — поэтому литерал
    #: отличает «минимум» от «первое» (дало бы 9.0, 4.0), от «последнее» (8.0, 6.0)
    #: и от «среднее». Первая редакция скрипта этого свойства НЕ имела: минимум
    #: стороны «n» стоял последним, и подмена min на «последнее» проходила молча —
    #: поймано ручной проверкой сторожа заплатой, а не рассуждением.
    _SCRIPT: Tuple[float, ...] = (9, 4, 5, 2, 7, 3, 6, 10, 8, 6)

    def test_each_side_reports_the_minimum_of_its_own_five_windows(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """При ``repeats=1`` ответ обязан быть ровно ``(5.0, 2.0)``.

        **Две хрупкости названы вслух.** Первая: подмена идёт НА МОДУЛЕ ``time``,
        потому что помощник зовёт часы как ``time.perf_counter()``; рефакторинг
        на ``from time import perf_counter`` сделает тест ЛОЖНО КРАСНЫМ, а не
        тихо зелёным — направление безопасное, но чинить придётся здесь.
        Вторая (находка ревью): подмена процессная, и без привязки к потоку
        соседний демон съедал бы тики из общего списка — см. ``scripted``.
        """
        ticks: List[float] = []
        moment = 0.0
        for window in self._SCRIPT:
            ticks.append(moment)
            moment += window
            ticks.append(moment)

        real_perf_counter = time.perf_counter
        mine = threading.get_ident()

        def scripted() -> Any:
            """Подставные часы — ТОЛЬКО своему потоку.

            Подмена процессная (``time.perf_counter`` — один объект на весь
            интерпретатор), а ``ticks`` — общий расходуемый список. Соседний
            поток, зовущий часы в фоне, съел бы тики, и литерал получил бы
            ЧУЖИЕ числа: воспроизведено ревью — ``(2.0e-07, 3.0e-07)`` вместо
            ``(5.0, 2.0)``. Отказ ложно-красный, а не тихо-зелёный, но в общем
            гейте живут чужие демоны-потоки, а мигающий красный учит не
            смотреть на красное.
            """
            if threading.get_ident() != mine or not ticks:
                return real_perf_counter()
            return ticks.pop(0)

        monkeypatch.setattr(_road_cost.time, "perf_counter", scripted)
        result = timed_pair(lambda: None, lambda: None, repeats=1)

        assert result == (5.0, 2.0), (
            f"помощник вернул {result} вместо (5.0, 2.0) на подставных часах "
            f"{self._SCRIPT}: он больше не берёт МИНИМУМ из пяти окон своей стороны "
            "(или перестал делить на repeats)"
        )

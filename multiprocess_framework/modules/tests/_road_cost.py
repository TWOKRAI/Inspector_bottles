"""Общий помощник дорог для перф-бенчей плоскости чисел (Ф2, добор к Task 2.10, Р-12).

Не тест (подчёркивание в имени — pytest его не собирает), а два инструмента,
которыми пользуются бенчи ``process_module/tests/test_plugin_stats_road.py::
TestTheCostOfTheHotPath`` и ``process_module/tests/
test_f2_numbers_disabled_cost_bench.py``: :func:`timed_pair` (секунды на вызов
у двух реализаций, замеренные вперемежку) и :func:`count_calls` (число
python-уровневых и C-уровневых вызовов внутри одного ``fn()``).

Место — по образцу :mod:`._declarations_catalogue_guard`: подчёркивание в
имени файла, лежит рядом с тестами модуля, но тестовым модулем не считается.

**Почему инструмент вынесен, а не переписан заново.** ``timed_pair`` —
буквальный перенос ``_timed_pair`` (Task 1.1, ``test_plugin_stats_road.py``):
поведение не менялось ни на строку, только адрес. Числа, которым уже
доверяют потолки Task 2.1/2.4/Р-12, остаются числами ТОЙ ЖЕ функции.

**Почему потолку мало тайминга (Р-12, решение владельца 2026-09-02).**
Тайминг-гейт любой ширины слеп к классу регрессии, ради которого он заявлен:
+0.2 мкс на базе 6.3 мкс сдвигает отношение facade/direct всего с 1.80 до
1.86 — недостаточно, чтобы отличить «появилась лишняя работа» от дрожи
машины. Число вызовов Python-уровня ОТ МАШИНЫ И НАГРУЗКИ НЕ ЗАВИСИТ вовсе:
:func:`count_calls` даёт второй, узкий сторож той же мелочи (копия словаря на
вызов, лишний лок, разбор имени) рядом с широким тайминг-гейтом.
"""

from __future__ import annotations

import gc
import sys
import time
import tracemalloc
from typing import Any, Callable, Tuple

__all__ = ["count_calls", "peak_alloc", "report", "timed_pair"]


def report(capsys: Any, line: str) -> None:
    """Печать замера МИМО capture — и безопасная для консоли в cp1251.

    Бенч обязан печатать свои числа даже при зелёном прогоне: замер, который
    никто не видит, нельзя ни сверить с прошлым, ни принести в отчёт. Кодировка
    правится с запасом, потому что консоль на этой машине не UTF-8, а падение
    на печати выглядело бы как падение теста.

    **Инвентарь снят грепом, а не памятью** (первая редакция этого абзаца назвала
    три копии по памяти; их было четыре — поймано ревью, и это ровно тот класс,
    который задача чинила). На 2026-09-02 в дереве:

    * ``report``-подобных тел бенча — четыре: здесь, ``test_plugin_stats_road.py``
      и ``test_f2_numbers_disabled_cost_bench.py`` (обе переведены сюда добором
      Р-12), плюс ДВЕ оставшиеся копии — ``logger_module/tests/test_gate_cost_bench.py:101``
      и ``base_manager/tests/test_source_stamping.py:408``;
    * ``timed_pair``-подобных — три: здесь, ``test_gate_cost_bench.py:141`` и
      ``test_source_stamping.py:420``.

    **Обе оставшиеся копии ``timed_pair`` УЖЕ разошлись с этим телом:** у них
    ``range(3)`` вместо пяти окон и **нет** ``gc.disable()`` — то есть они мерят
    по трём окнам и вместе со сборкой мусора. Разошлись молча, как и положено
    дублю. Их перевод назван follow-up'ом в «Out of scope» добора и НЕ сделан
    заодно: это чужие зелёные тесты, а правка чужого зелёного требует своей
    инъекции.
    """
    with capsys.disabled():
        encoding = getattr(sys.stdout, "encoding", None) or "ascii"
        print(line.encode(encoding, errors="replace").decode(encoding, errors="replace"))


def timed_pair(new_fn: Callable[[], Any], old_fn: Callable[[], Any], repeats: int) -> Tuple[float, float]:
    """Секунд на вызов у ДВУХ реализаций, замеренных вперемежку.

    Перенесено буквально из ``test_plugin_stats_road.py::_timed_pair``
    (Task 1.1) — поведение не менялось, только адрес функции.

    Вперемежку, а не «сначала три прогона одного»: последовательный замер
    сравнивает не реализации, а два разных окна загрузки машины. ``gc``
    выключен на окно замера — сборка, попавшая в одну половину, дала бы
    дельту, которой нет (порог по часам иначе меряет кучу, а не код).

    Args:
        new_fn: первая измеряемая реализация (без аргументов).
        old_fn: вторая измеряемая реализация (без аргументов).
        repeats: сколько раз позвать каждую внутри ОДНОГО окна замера.

    Returns:
        ``(секунд_на_вызов_new, секунд_на_вызов_old)`` — лучшее (минимальное)
        из пяти окон для каждой стороны, делённое на ``repeats``.
    """
    best_new = best_old = None
    gc.disable()
    try:
        for _ in range(5):
            start = time.perf_counter()
            for _ in range(repeats):
                new_fn()
            new_elapsed = time.perf_counter() - start

            start = time.perf_counter()
            for _ in range(repeats):
                old_fn()
            old_elapsed = time.perf_counter() - start

            best_new = new_elapsed if best_new is None else min(best_new, new_elapsed)
            best_old = old_elapsed if best_old is None else min(best_old, old_elapsed)
    finally:
        gc.enable()
    return best_new / repeats, best_old / repeats


def peak_alloc(fn: Callable[[], Any], warm: int = 50, repeats: int = 200) -> int:
    """Пик выделенной памяти за ``repeats`` вызовов ``fn()``, в байтах.

    **Третий объектив, и он нужен потому, что первые два слепы.** ``tracemalloc``
    видит то, чего не видит ни :func:`count_calls`, ни :func:`timed_pair`:
    КОНСТРУИРОВАНИЕ объектов. Замер (CPython 3.12): ``dict(d)`` и ``{**d}`` дают
    у счётчика вызовов ровно ``(1, 1)`` — столько же, сколько ``lambda: None``,
    потому что конструктор типа не порождает события ``c_call``; а по пику
    памяти те же формы дают 248 и 184 байта против 112 у пустой.

    Из-за этой слепоты приёмочный критерий Task 2.10 («сборка записи перенесена
    ПЕРЕД гейтом → бенч красный») не выполнялся: заплата проходила мимо обеих
    половин пары и укладывалась в тайминг-потолок (дельта отношения 0.048).
    Найдено ревью, а не автором.

    **Прогрев обязателен.** Первый замер ``tracemalloc`` включает разовые
    аллокации самого инструмента (наблюдалось 158 против устойчивых 342 и 2402
    против устойчивых 738). ``gc`` выключен на окно замера по той же причине,
    что и у :func:`timed_pair`.

    Args:
        fn: измеряемый вызов без аргументов.
        warm: сколько раз позвать ДО замера — чтобы не мерить разовое.
        repeats: сколько раз позвать под наблюдением.

    Returns:
        Пик ``tracemalloc`` минус базовая линия, в байтах. Величина
        детерминирована для данной версии CPython и данных, но НЕ переносится
        между версиями — сверять замером, а не переписыванием.
    """
    for _ in range(warm):
        fn()
    gc.disable()
    tracemalloc.start()
    try:
        baseline = tracemalloc.get_traced_memory()[0]
        top = 0
        for _ in range(repeats):
            fn()
            peak = tracemalloc.get_traced_memory()[1]
            if peak > top:
                top = peak
        return top - baseline
    finally:
        tracemalloc.stop()
        gc.enable()


def count_calls(fn: Callable[[], Any]) -> Tuple[int, int]:
    """Число вызовов (python-уровня, C-уровня) внутри ОДНОГО ``fn()``, на любой глубине.

    Канал — ``sys.setprofile``, НЕ ``sys.settrace``: под ``pytest --cov``
    (боевой режим ``make test`` в проекте) построчный трассировщик
    ``coverage.CTracer`` уже занимает ``sys.gettrace()``, а ``sys.getprofile()``
    при этом свободен — coverage.py трогает только settrace-канал. Наблюдение
    снято прогоном (не предположение), см. критерий 7/8
    ``test_road_cost_contract.py`` и докстринг ниже.

    **Восстановление — по СНИМКУ, а не по ``None``.** Базовая линия — то, что
    было установлено ДО вызова (:func:`sys.getprofile`); если снаружи уже стоит
    чужой хук (в бою — редкий, но легитимный случай: сторонний профайлер), этот
    помощник обязан вернуть систему в ТО состояние, а не затереть чужой хук
    ``None``. Восстановление происходит и при исключении внутри ``fn`` —
    ``finally``, а не ``except``: исключение обязано пробрасываться наружу
    нетронутым.

    Args:
        fn: измеряемый вызов без аргументов. Исключение из него пробрасывается
            вызывающему — эта функция не место для решения «считать ли отказ».

    Returns:
        ``(py_calls, c_calls)`` — число событий ``"call"`` и ``"c_call"``,
        увиденных профайлером за время исполнения ``fn()``, включая вызовы на
        любой глубине вложенности. Вызов самого ``fn()`` считается наравне с
        остальными (профайлер уже активен к моменту этого вызова) — это не
        искажает сравнение ДВУХ вызовов между собой: одинаковая для обеих
        сторон единица сокращается вычитанием (см. критерии 3/5 контракта).

    Детерминизм — в границах одного процесса и одного потока: два подряд
    вызова с одним и тем же ``fn`` дают одну и ту же пару чисел, потому что
    считаются СОБЫТИЯ ВЫЗОВА байткода, а не время — они не зависят от
    загрузки машины (см. критерий 4 контракта).
    """
    py_calls = 0
    c_calls = 0

    def _profiler(frame: Any, event: str, arg: Any) -> None:
        nonlocal py_calls, c_calls
        if event == "call":
            py_calls += 1
        elif event == "c_call":
            c_calls += 1

    prior_profile = sys.getprofile()
    sys.setprofile(_profiler)
    try:
        fn()
    finally:
        sys.setprofile(prior_profile)
    return py_calls, c_calls

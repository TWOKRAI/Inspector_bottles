# -*- coding: utf-8 -*-
"""Ранги уровней — общее хозяйство трёх плоскостей наблюдаемости.

Почему здесь, а не в ``logger_module`` (Ф0.6, резидуал R6): предикат «эта
запись важнее порога» нужен всем троим — логам (гейт scope/level), ошибкам
(severity-маршрут и floor) и tap-механике в общей базе. Пока он жил в
``logger_module.log_enums``, ``error_manager`` тянул его кросс-модульным
импортом вглубь чужого модуля, а поднять tap'ы в ``ChannelRoutingManager``
было нельзя вовсе: база не имеет права зависеть от своего потомка.

Здесь ТОЛЬКО ранги и предикат. Сами enum'ы ``LogLevel`` / ``LogScope``
остаются в ``logger_module`` — они про формат лог-записи, а не про
сравнение важности, и статистике не нужны.

Функции принимают и ``LogLevel``, и строку: сравнение уровней не должно
требовать импорта лог-специфичного enum'а.
"""

#: Каноничный порядок уровней (растёт по важности). Единый источник для сравнения
#: «level ≥ порог» (log tail, should_log, severity-маршрут). Строки — как в
#: ``LogRecord.to_dict()``.
LEVEL_ORDER = ("DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL")

#: Ранг, начиная с которого запись считается аварийной: её нельзя ни буферизовать,
#: ни потерять при выключенных приёмниках (инвариант 1 плана observability-unified-routing).
ERROR_RANK = LEVEL_ORDER.index("ERROR")


def level_rank(level) -> int:
    """Числовой ранг уровня (DEBUG=0 … CRITICAL=4). Принимает ``LogLevel`` или строку.

    Неизвестный уровень → 0 (не фильтруем — безопасный дефолт «пропустить»).
    """
    val = getattr(level, "value", level)
    try:
        return LEVEL_ORDER.index(str(val).upper())
    except ValueError:
        return 0


def is_error_level(level) -> bool:
    """ERROR/CRITICAL? Принимает ``LogLevel`` или строку.

    Единственный предикат «эта запись — аварийная» на весь слой наблюдаемости.
    По нему ``LoggerCore.log()`` и severity-путь ``ErrorManager.log()`` решают
    писать синхронно, мимо ``BatchBuffer``, и подстилать floor (Ф0.9, вариант B).

    Заменил ``buffer_priority()`` из временной меры Ф0.1: та выталкивала запись
    из пачки приоритетом (сбрасывая заодно всю пачку), теперь запись просто не
    попадает в пачку.
    """
    return level_rank(level) >= ERROR_RANK

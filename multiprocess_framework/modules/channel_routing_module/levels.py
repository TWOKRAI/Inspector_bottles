# -*- coding: utf-8 -*-
"""Числа важности — общее хозяйство трёх плоскостей наблюдаемости.

Почему здесь, а не в ``logger_module`` (Ф0.6, резидуал R6): предикат «эта
запись важнее порога» нужен всем троим — логам (гейт scope/level), ошибкам
(severity-маршрут и floor) и tap-механике в общей базе. Пока он жил в
``logger_module.log_enums``, ``error_manager`` тянул его кросс-модульным
импортом вглубь чужого модуля, а поднять tap'ы в ``ChannelRoutingManager``
было нельзя вовсе: база не имеет права зависеть от своего потомка.

Здесь ТОЛЬКО числа и предикаты. Сами enum'ы ``LogLevel`` / ``LogScope``
остаются в ``logger_module`` — они про формат лог-записи, а не про сравнение
важности, и статистике не нужны.

Функции принимают и ``LogLevel``, и строку: сравнение уровней не должно
требовать импорта лог-специфичного enum'а.

Ф3.1 — числа стали словарём OTel (``SeverityNumber`` 1–24)
==========================================================

До Ф3.1 здесь жили СВОИ ранги 0…4 (``enumerate(LEVEL_ORDER)``). Они заменены,
а не дополнены: второй порядок при живом первом — ровно тот дефект, который
Ф2.4 убирала на оси скоупа (два написания одного имени). Как только появился бы
уровень вне пятёрки, гейт и запись сравнивали бы разное.

Что даёт чужая нумерация, кроме совместимости:

* **у «неизвестно» есть своё число.** В спеке ``0 = UNSPECIFIED``, а уровни
  начинаются с 1. Наш ``UNKNOWN_RANK = -1`` был заведён вручную ровно потому,
  что 0 был занят DEBUG; теперь дырка под «уровня нет» стоит в самой шкале;
* **расширение без миграции.** ``TRACE`` = 1–4 и ``DEBUG2..DEBUG4`` = 6–8
  вставляются между существующими числами, не сдвигая их. Имена не заводятся,
  пока нет call-site'а (verbosity внутри DEBUG — задел, а не фича);
* **число выводится из текста, а не едет в записи.** В ``LogRecord`` ничего не
  добавлено: ``severity_number`` — чистая функция от имени уровня, и
  материализуется только там, где нужен внешнему потребителю (колонка стора —
  Ф3.6, экспортёр OTLP — Ф8.6). Цена в байтах на записи и в IPC — ноль.

**Алиасов в :data:`SEVERITY_NUMBERS` нет намеренно.** По этому словарю бьют
прямые лукапы горячего пути; ключ ``WARN`` в нём легализовал бы неканоничное
имя мимо валидации границы и сломал бы производные (перебор ключей дал бы семь
имён вместо пяти). Алиасы живут отдельно и раскрываются один раз — в
:func:`normalize_level_name`.
"""

from typing import Dict, Optional

#: Каноничный порядок уровней (растёт по важности). **Индекс-стабилен:** значения
#: по индексу берут дефолты конфига, поэтому вставлять сюда ``TRACE`` нельзя —
#: расширение шкалы идёт в :data:`SEVERITY_NUMBERS`, а имена сюда добавляются
#: только в конец. Строки — как в ``LogRecord.to_dict()``.
LEVEL_ORDER = ("DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL")

#: Имя уровня → ``SeverityNumber`` словаря OpenTelemetry. Числа — литералы, а не
#: производная от порядка: ``enumerate`` согласился бы с любой нумерацией, включая
#: сломанную, и тест на смену чисел перестал бы существовать.
#:
#: Ф1.1: гейт спрашивают на КАЖДОЙ записи, а линейный поиск по кортежу плюс
#: ``.upper()`` аллоцировал новую строку. Словарь убирает и то, и другое: на пути
#: решения остаются два хэш-лукапа и сравнение int.
SEVERITY_NUMBERS: Dict[str, int] = {
    "DEBUG": 5,
    "INFO": 9,
    "WARNING": 13,
    "ERROR": 17,
    "CRITICAL": 21,  # OTel зовёт этот диапазон FATAL; имя уровня у нас своё
}

#: Чужие написания тех же уровней. Раскрываются ТОЛЬКО на границе
#: (:func:`normalize_level_name`), в горячий словарь не попадают.
#: ``WARN`` и ``FATAL`` — каноничные имена OTel и большинства чужих логгеров,
#: то есть не опечатка, а законный синоним.
LEVEL_ALIASES: Dict[str, str] = {"WARN": "WARNING", "FATAL": "CRITICAL"}

#: «Оси важности у этой записи нет» (OTel ``SEVERITY_NUMBER_UNSPECIFIED``).
#: Число плоскости статистики: у метрики уровня не бывает. Ставится по ВИДУ
#: записи (``kind``), а не по неудаче ранжирования — иначе метрика и опечатка в
#: имени уровня стали бы неразличимы.
UNSPECIFIED = 0

#: Ответ «такого имени уровня нет». Ниже :data:`UNSPECIFIED` намеренно: «уровня
#: нет вовсе» и «уровень назван, но не опознан» — разные состояния, и путать их
#: нельзя. Потребители, которым нужен мягкий дефолт, выбирают его сами —
#: см. :func:`record_severity` и :func:`threshold_severity`.
UNKNOWN_SEVERITY = -1

#: Число самого низкого уровня. Дефолт позиции «уровень записи» (см. ниже).
DEBUG_SEVERITY = SEVERITY_NUMBERS["DEBUG"]

#: Число, начиная с которого запись считается аварийной: её нельзя ни
#: буферизовать, ни потерять при выключенных приёмниках (инвариант 1 плана
#: observability-unified-routing). В словаре OTel ровно эта граница — 17.
ERROR_SEVERITY = SEVERITY_NUMBERS["ERROR"]


def normalize_level_name(value) -> Optional[str]:
    """Имя уровня → каноничное имя, либо ``None``, если такого уровня нет.

    Единственное место, где раскрываются алиасы и регистр. Стоит на ГРАНИЦЕ
    (валидатор конфига, разбор аргумента команды), а не на горячем пути: цена
    ``.upper()`` платится один раз за смену конфига, а не на каждой записи.

    Возврат ``None`` — сигнал вызывающему отказать или сказать вслух. Что
    именно делать, решает он: у файла рецепта и у ручки оператора ответы
    разные (то же различение, что в Task 5.5).
    """
    val = getattr(value, "value", value)
    if not isinstance(val, str):
        val = str(val)
    name = val.upper()
    if name in SEVERITY_NUMBERS:
        return name
    return LEVEL_ALIASES.get(name)


def severity_of(level) -> int:
    """``SeverityNumber`` уровня или :data:`UNKNOWN_SEVERITY`. Принимает ``LogLevel`` или строку.

    НЕ маскирует незнакомый уровень: гейту ``LoggerScopeSchema.should_log``
    разница важна — на незнакомом уровне он обязан пропустить запись, а не
    сравнивать её число с порогом (иначе любой уровень с опечаткой стал бы тише
    DEBUG). Алиасы здесь НЕ раскрываются: горячий путь их не видит, их
    раскрывает граница (:func:`normalize_level_name`).

    Быстрый путь — прямой лукап без ``.upper()``: имена ``LogLevel.value`` уже
    в верхнем регистре, и на горячем пути лишняя строка не аллоцируется.
    """
    val = getattr(level, "value", level)
    if isinstance(val, str):
        number = SEVERITY_NUMBERS.get(val)
        if number is not None:
            return number
        return SEVERITY_NUMBERS.get(val.upper(), UNKNOWN_SEVERITY)
    # Нестроковый уровень мог прийти только из чужого кода; приводим, как раньше.
    return SEVERITY_NUMBERS.get(str(val).upper(), UNKNOWN_SEVERITY)


def record_severity(level) -> int:
    """Число ЗАПИСИ для сравнения с порогом. Непонятый уровень → :data:`DEBUG_SEVERITY`.

    Позиция «уровень записи» и позиция «порог» требуют ПРОТИВОПОЛОЖНЫХ дефолтов,
    и до Ф3.1 обе обслуживала одна функция (``level_rank``, «неизвестное → 0»).
    Годилось это только потому, что 0 был числом DEBUG: запись без уровня
    случайно оказывалась «самой низкой», а порог без уровня — «самым низким
    порогом», то есть всепропускающим. После переномерации DEBUG=5 совпадение
    исчезает, и одна из двух позиций сломалась бы молча — поэтому функций две.

    Здесь дефолт — самый низкий УРОВЕНЬ (не ноль): запись без уровня (метрика)
    и запись с непонятым именем уровня по-прежнему доходят до tap'а «дай всё»
    (порог DEBUG) и по-прежнему не доходят до tap'а порога ERROR. Оба факта
    несущие и характеризованы: первый — чтобы плоскость статистики могла
    пользоваться tap'ами вообще, второй — чтобы хвост ошибок не засорялся.

    :data:`UNSPECIFIED` здесь НЕ используется: он про то, что записать в поле
    ``severity_number`` у плоскости без оси важности, а не про то, кому её
    доставить.
    """
    number = severity_of(level)
    return DEBUG_SEVERITY if number == UNKNOWN_SEVERITY else number


def threshold_severity(min_level) -> int:
    """Число ПОРОГА. Непонятый порог → :data:`UNSPECIFIED`, то есть «пропускать всё».

    Fail-open, а не fail-closed: противоположный дефолт означал бы тишину от
    опечатки — невидимую потерю, запрещённую инвариантом 2 плана. Шумная выдача
    хотя бы видна.

    Это последний рубеж, а не первый: с Ф3.1 непонятый порог отвергается на
    границах — в валидаторе конфига (``LoggerScopeSchema.min_level``) и в
    аргументе команд подписки. Сюда он может прийти только из программного
    вызова в обход обеих.
    """
    number = severity_of(min_level)
    return UNSPECIFIED if number == UNKNOWN_SEVERITY else number


def is_error_level(level) -> bool:
    """ERROR/CRITICAL? Принимает ``LogLevel`` или строку.

    Единственный предикат «эта запись — аварийная» на весь слой наблюдаемости.
    По нему ``LoggerCore.log()`` и severity-путь ``ErrorManager.log()`` решают
    писать синхронно и подстилать floor (Ф0.9, вариант B; с Ф7.4 синхронны все).

    Заменил ``buffer_priority()`` из временной меры Ф0.1: та выталкивала запись
    из пачки приоритетом (сбрасывая заодно всю пачку), теперь запись просто не
    попадает в пачку.
    """
    return record_severity(level) >= ERROR_SEVERITY

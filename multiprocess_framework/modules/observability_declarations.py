# -*- coding: utf-8 -*-
"""Объявление наблюдаемой сущности рядом с её владельцем (Ф2.7, расширено Ф8.1).

**Зачем.** Ф2.6 положила имя источника константой `LOG_SOURCE` в `interfaces.py`
модуля — там же, где публичный API. Этого хватило, чтобы штамп и правило перестали
печататься дважды, но объявление осталось **пассивным**: узнать «какие имена вообще
объявлены» можно было только грепом, а правило-дефолт модуля пришлось бы писать в
центральный конфиг — то есть при добавлении модуля трогать общий файл.

Здесь объявление становится активным. Модуль зовёт :func:`declare_log_source` рядом
со своей константой, и дальше:

* имя попадает в :func:`declared_sources` — ответ на «что бывает» ДО первой записи
  (``seen_sources`` отвечает только про тех, кто уже писал);
* правило-дефолт, если оно есть, уезжает в слой L0 — под конфиг приложения, а не
  поверх него: модуль знает про себя, но последнее слово за тем, кто систему
  собирает.

**Центральных правок ноль.** Реестр наполняется импортом самого модуля, а не списком
в общем файле: список пришлось бы править при каждом добавлении — ровно та работа,
ради устранения которой задача и делается.

**Конфликт двух объявлений на одно имя — отказ у лог-источников, no-op у метрик
(с Ф1 порта наблюдений).** У ЛОГ-ИСТОЧНИКА имя — адрес правила, и два владельца на
один адрес означают, что правило применится не к тому: тихое разрешение («побеждает
последний импортированный») сделало бы поведение зависимым от порядка импортов, то
есть от того, что никто не считает настройкой, — поэтому там отказ. У МЕТРИКИ имя
адресом быть перестало: адрес — путь ``state.plugins.<писатель>.<имя>``, и два
плагина с одинаковым именем листа получают два РАЗНЫХ листа. Спорить не о чем,
отказ снят, повторное объявление любым владельцем — идемпотентный no-op.
Повторное объявление ТЕМ ЖЕ владельцем — не конфликт нигде: модуль переимпортируют (reload в тестах, spawn
дочернего процесса), и падать на этом нельзя.

Реестр процессный, как и всё остальное состояние наблюдаемости: дочерний процесс
импортирует свои модули сам и собирает свой набор.

**Лежит рядом с `_fallback.py`, а не внутри `logger_module`, и это не вкусовщина.**
Объявление зовут из `interfaces.py` модулей, которые сам логгер и импортирует
(`dispatch_module` → `channel_routing_manager` → …); импорт через пакет логгера
замкнул бы кольцо — воспроизведено на первой редакции: `ImportError: cannot import
name 'ChannelRoutingConfig' from partially initialized module`. Здесь лист без
зависимостей, тот же приём, что у аварийного выхода.

Ф8.1 — то же объявление обслуживает ВТОРУЮ плоскость
==================================================

Метрики телеметрии перечислялись кортежем-литералом ``GATED_METRICS`` в коде
фреймворка: завести метрику значило править фреймворк, чего конструктор делать не
обязан. Теперь метрика объявляется там же, где считается, тем же механизмом —
меняется только **пространство имён** (``kind``), а не устройство реестра.

Пространства разделены ключом, а не тремя словарями: одинаковое имя в разных
плоскостях законно (``shm`` — и метрика, и требование плагина), а вот два владельца
на одно имя в ОДНОЙ плоскости — отказ у лог-источников и no-op у метрик (см. шапку:
плоскости расходятся здесь НАМЕРЕННО, потому что у метрик имя перестало быть
адресом). Один словарь с составным ключом
даёт оба свойства сразу; три словаря пришлось бы держать согласованными руками —
ровно тот класс, который Ф8.1 и схлопывает.

Значения у плоскостей разные и общей формы им не навязано: у лог-источника это
правило-дефолт (``LoggerRuleSchema``), у метрики — ничего, кроме факта
существования. Общий здесь **механизм объявления**, а не тип значения; сведение
трёх разных значений к одной схеме было бы унификацией по букве.
"""

from __future__ import annotations

import threading
from typing import Dict, Iterable, Mapping, NamedTuple, Optional, Tuple

__all__ = [
    "declare_log_source",
    "declared_sources",
    "declared_rules",
    "declare_metric",
    "declared_metrics",
    "forget_declarations",
    "snapshot",
    "restore",
    "RegistrySnapshot",
]

#: Пространство имён лог-источников (``module`` записи).
KIND_LOG_SOURCE = "log_source"
#: Пространство имён метрик телеметрии (суффикс пути публикации).
KIND_METRIC = "metric"

#: (плоскость, имя) → (владелец, правило-дефолт или None)
_DECLARED: Dict[Tuple[str, str], Tuple[str, Optional[object]]] = {}
_LOCK = threading.Lock()

#: Ф2.х (Н2): правила уже читались сборкой конфига хотя бы раз. Снимок в сборку
#: попадает на момент чтения; правило, объявленное ПОЗЖЕ, в уже собранные
#: конфиги не попало — и молчать об этом нельзя: симптом «правило написано, а
#: не действует» иначе ищется в конфиге, где всё верно.
_RULES_CONSUMED: bool = False


def _declare(kind: str, name: str, *, owner: str, rule: Optional[object] = None) -> str:
    """Общее тело объявления. Плоскости различаются ``kind`` и — с Ф1 — реакцией
    на второго владельца.

    Вынесено из :func:`declare_log_source` при Ф8.1 без изменения поведения: вторая
    копия правил конфликта разошлась бы с первой молча. С Ф1 порта наблюдений
    расхождение появилось, и оно НАМЕРЕННОЕ, а не дрейф: лог-источник на второго
    владельца отвечает ``ValueError`` (имя = адрес правила), метрика — идемпотентным
    no-op (адрес метрики — путь поддерева писателя, а не имя). Поэтому «расхождение
    здесь = дефект» больше не читать: дефектом было бы РАВНОЕ поведение.
    """
    with _LOCK:
        key = (kind, name)
        previous = _DECLARED.get(key)
        if previous is not None:
            prev_owner, prev_rule = previous
            if prev_owner == owner and _same_rule(prev_rule, rule):
                return name  # повторный импорт того же модуля — не конфликт
            if kind == KIND_METRIC:
                # Ф1 «порт наблюдений»: у МЕТРИКИ владения именем больше нет.
                # Публикация едет в поддерево своего писателя
                # (``state.plugins.<писатель>.<имя>``), и два плагина с именем
                # ``fps`` дают два РАЗНЫХ листа — спорить за имя синтаксически не
                # о чем. Отказ здесь был половиной арбитра (вторая половина —
                # сверка публикатора с владельцем в сборщике), и оставить его
                # значило бы уронить процесс за столкновение, которого больше нет.
                # Каталог имён при этом ЖИВ: им резолвит правила publisher-гейт и
                # по нему строит авто-строки GUI. Первое объявление остаётся —
                # каталогу нужно имя, а не владелец.
                return name
            raise ValueError(
                f"{_KIND_NOUN[kind]} '{name}' уже объявлен{_KIND_SUFFIX[kind]} модулем "
                f"'{prev_owner}', повторное объявление от '{owner}' с другим содержимым "
                f"отклонено. Два объявления на одно имя означают, что действующее правило "
                f"зависит от порядка импортов"
            )
        _DECLARED[key] = (owner, rule)
        consumed = _RULES_CONSUMED
    # Ф2.х (Н2): boot-конфиг детям собирает ассемблер в РОДИТЕЛЕ, пересборку —
    # сам ребёнок; оба берут снимок реестра на момент чтения. Правило, объявленное
    # после первого чтения (ленивый импорт, плагин), в уже собранные конфиги не
    # попало — и об этом говорим модулю, объявившему правило слишком поздно, а
    # не аварийным выходом. Задача 4.11 сняла прежний довод («предмет жалобы —
    # ровно та раскладка, которой запись поехала бы») как ложный: адресат этой
    # строки — тот, кто пишет конфиг/модуль, то есть ОПЕРАТОР в широком смысле,
    # а не самоотчёт сломавшегося маршрута наблюдаемости. ``emergency_log`` —
    # дверь именно для второго класса (см. его контракт в ``_fallback.py``).
    if consumed and rule is not None:
        from ._fallback import FallbackLogger

        FallbackLogger(__name__).warning(
            f"правило-дефолт источника '{name}' ({owner}) объявлено ПОСЛЕ сборки "
            f"конфига наблюдаемости: в уже собранные конфиги оно не попало и начнёт "
            f"действовать со следующей сборки (reload либо новый процесс)"
        )
    return name


#: Как называть сущность в тексте отказа. Своя строка на плоскость, а не общее
#: «объявление»: сообщение читает человек, у которого сломался импорт, и слово
#: «метрика» отправляет его в другое место конфига, чем слово «источник».
_KIND_NOUN = {KIND_LOG_SOURCE: "источник", KIND_METRIC: "метрика"}
_KIND_SUFFIX = {KIND_LOG_SOURCE: "", KIND_METRIC: "а"}


def declare_log_source(name: str, *, owner: str, rule: Optional[object] = None) -> str:
    """Объявить имя источника (и, опционально, его правило-дефолт).

    Args:
        name: точечное имя источника — то же, что уезжает в ``module`` записи.
        owner: кто объявляет, обычно ``__name__`` объявляющего файла. Нужен, чтобы
            отличить повторный импорт того же модуля от ДВУХ модулей, назвавшихся
            одинаково: первое законно, второе — ошибка конфигурации.
        rule: правило-дефолт (``LoggerRuleSchema``) либо ``None``. Уезжает в слой
            L0, то есть под конфиг приложения.

    Returns:
        То же ``name`` — чтобы объявление писалось одной строкой рядом с константой.

    Raises:
        ValueError: имя уже объявлено ДРУГИМ владельцем либо тем же владельцем с
            другим правилом. Отказ, а не предупреждение: у такого состояния нет
            правильного прочтения, и любой молчаливый выбор зависел бы от порядка
            импортов. Тот же отказ — правило не той формы (см. ниже): словарь
            вместо схемы упал бы позже в сборке конфига, далеко от виновника и
            без его имени (класс «model_copy не валидирует», уже стрелявший
            в этой фазе дважды).
    """
    # Ф2.х (Н3): форма правила проверяется ЗДЕСЬ, на границе реестра, а не там,
    # где сборка позовёт .model_dump(). Утиная проверка, а не isinstance: лист
    # не может импортировать схему логгера — кольцо воспроизведено в шапке.
    if rule is not None and not callable(getattr(rule, "model_dump", None)):
        raise ValueError(
            f"правило-дефолт источника '{name}' от '{owner}' — {type(rule).__name__}, "
            f"а нужна схема правила (LoggerRuleSchema). Словарь здесь молча доехал бы "
            f"до сборки конфига и упал там без имени виновника"
        )
    return _declare(KIND_LOG_SOURCE, name, owner=owner, rule=rule)


def declared_sources() -> Dict[str, str]:
    """Объявленные имена: ``имя → владелец``.

    Отличается от ``LoggerCore.seen_sources`` тем же, чем каталог от журнала:
    здесь то, что МОЖЕТ писать, там — то, что уже писало. Источник, у которого всё
    гасится порогом, в журнале не появится вовсе, а в каталоге он есть.
    """
    with _LOCK:
        return {name: owner for (kind, name), (owner, _rule) in _DECLARED.items() if kind == KIND_LOG_SOURCE}


def declared_rules() -> Dict[str, object]:
    """Правила-дефолты объявивших модулей — вклад в слой L0.

    Пусто, пока ни один модуль правила не объявил, и это нормальное состояние:
    имя объявляют почти все, а собственный порог — только тот, кому есть что
    сказать про себя.

    Чтение помечает реестр «снимок взят» (Ф2.х, Н2): сборка конфига берёт
    правила ровно этим вызовом, и всё, что объявится позже, в неё уже не
    попало. Позднее объявление правила с этого момента слышно аварийным
    выходом — см. :func:`declare_log_source`.
    """
    global _RULES_CONSUMED
    with _LOCK:
        _RULES_CONSUMED = True
        return {
            name: rule
            for (kind, name), (_owner, rule) in _DECLARED.items()
            if kind == KIND_LOG_SOURCE and rule is not None
        }


def declare_metric(name: str, *, owner: str) -> str:
    """Объявить метрику телеметрии — Ф8.1, замена кортежу-литералу ``GATED_METRICS``.

    Зовётся рядом с кодом, который метрику СЧИТАЕТ. Владение здесь не формальность:
    прежний кортеж жил в ``configs/``, то есть на два слоя ниже вычисления, и связь
    «эта строка каталога — вот эта величина» держалась только именем.

    **Владения именем у метрики НЕТ** (Ф1 «порт наблюдений»). Это КАТАЛОГ имён, а
    не реестр прав: по нему publisher-гейт резолвит правила конфига и по нему GUI
    строит авто-строки. Уровень плагина едет в поддерево своего писателя
    (``processes.<p>.state.plugins.<писатель>.<имя>``), поэтому одинаковое имя у
    двух плагинов — два разных листа, а не спор. Повторное объявление того же
    имени — идемпотентный no-op: первое объявление остаётся, отказа нет.
    Публиковать МОЖНО и без объявления — незнакомое гейту имя решается дефолтным
    правилом конфига (``TelemetryPublishConfig.resolve`` тотальна).

    Args:
        name: суффикс пути публикации (``fps``, ``latency_ms``, ``shm``) — тот же
            ключ, каким метрику адресует ``TelemetryPublishConfig.metrics``.
        owner: ``__name__`` объявляющего файла. Хранится как пометка «кто завёл
            имя» и наружу не отдаётся: спрашивать «чьё это имя» больше не у кого
            и незачем.

    Returns:
        То же ``name`` — объявление пишется одной строкой рядом с вычислением.

    **Правила-дефолта у метрики нет намеренно.** У лог-источника он есть, потому
    что модуль может знать про себя «я болтливый, мне WARNING». Метрика такого
    знания про себя не несёт: как часто её публиковать — решение того, кто собирает
    систему, и оно живёт в ``telemetry.publish`` рецепта. Завести здесь пустое поле
    «на будущее» значило бы построить ручку, которую никто не крутит.
    """
    return _declare(KIND_METRIC, name, owner=owner)


def declared_metrics() -> Tuple[str, ...]:
    """Объявленные метрики — каталог publisher-gate (Ф8.1).

    Порядок — **сортированный**, а не порядок импортов. Кортеж уезжает в readback
    пульта (``introspect.telemetry.gated_metrics``) и в шаблон строк GUI, и порядок,
    зависящий от того, какой модуль импортировался первым, переставлял бы строки
    в интерфейсе от запуска к запуску.

    Пустой кортеж — законное состояние процесса, который телеметрию не считает
    (ни один производитель не импортирован). Читатели обязаны отличать его от
    «каталог полон, а метрики в нём нет» — см. ``TelemetryPublishConfig.unknown_metrics``.
    """
    with _LOCK:
        return tuple(sorted(name for (kind, name) in _DECLARED if kind == KIND_METRIC))


def forget_declarations(kind: Optional[str] = None, *, names: Optional[Iterable[str]] = None) -> None:
    """Очистить реестр (целиком, одну плоскость либо перечисленные имена). **Только для тестов.**

    Args:
        names: забыть ТОЛЬКО эти имена (в плоскости ``kind``, либо во всех, если
            ``kind`` не задан). Это единственная форма очистки, которая НЕ теряет
            чужие объявления, и потому предпочтительная: сплошная очистка ниже
            восстановлению не поддаётся (см. предупреждение про ``kind``), а
            «восстановить руками, объявив заново» подменяет ВЛАДЕЛЬЦА — после
            такого восстановления настоящий владелец, объявившись повторно
            (reload, spawn), получил бы ``ValueError`` на ровном месте.
            Отсутствующее имя — не ошибка: тест не обязан знать, добрался ли он
            до объявления.
        kind: какую плоскость забыть; ``None`` — все. **Указывать плоскость почти
            всегда обязательно, и вот почему.** Реестр стал общим на три плоскости
            (Ф8.1), а наполняется он ИМПОРТОМ. Лог-источники тест восстанавливает
            сам, а метрики после сплошной очистки не вернутся никогда: их
            производители уже импортированы, и повторно объявлять некому.
            Воспроизведено на прогоне: очистка в одном тесте оставляла соседний
            каталог метрик пустым, и семь телеметрийных тестов краснели ТОЛЬКО
            в полном прогоне — поодиночке все зелёные. Класс «второй потребитель
            вскрывает дефект общего состояния».

    Прод-вызовов нет и быть не должно: реестр наполняется импортом, а импорт в
    живом процессе не отменяют. Функция существует, чтобы тест конфликта не
    оставлял след соседям — иначе порядок тестов начал бы значить.

    Сбрасывает и отметку «снимок взят» — по той же причине: иначе первый тест,
    прочитавший правила, включал бы поздние предупреждения всем соседям.

    Raises:
        TypeError: вызов БЕЗ ``names`` и БЕЗ ``kind``. Ф0.1 «trust gate»: такой
            вызов чистил реестр целиком, и гейт фреймворка держался порядком
            сборки — `statistics_module` перед `process_module` давал 20 красных,
            обратный порядок ноль. Отказ, а не предупреждение: предупреждение
            в тестовом прогоне никто не читает, а следствие видно за три модуля
            от виновника. Замена — :func:`snapshot` / :func:`restore` либо
            autouse-фикстура ``declarations_snapshot`` в conftest'ах обоих модулей.
    """
    global _RULES_CONSUMED
    if kind is None and names is None:
        raise TypeError(
            "forget_declarations() без names и без kind чистит реестр объявлений "
            "ЦЕЛИКОМ, а метрики после сплошной очистки не возвращаются никогда: их "
            "производители уже импортированы (sys.modules), объявлять заново некому — "
            "соседние тесты краснеют пачкой в зависимости от порядка сборки. "
            "Вместо голого вызова: forget_declarations(names=[...]) — забыть СВОЙ мусор, "
            "либо autouse-фикстура declarations_snapshot "
            "(multiprocess_framework/modules/statistics_module/tests/conftest.py, "
            "multiprocess_framework/modules/process_module/tests/conftest.py), которая "
            "снимает snapshot() до теста и делает restore() после."
        )
    with _LOCK:
        # Сплошной очистки (``_DECLARED.clear()``) здесь больше нет: единственная
        # форма, которая её звала, — голый вызов, а он теперь отказ. Возврат к
        # чистому состоянию делается снимком (:func:`restore`), и это не то же
        # самое: снимок ЗНАЕТ, что было, а сплошная очистка знает только, что
        # стало пусто.
        if names is not None:
            wanted = set(names)
            for ключ in [k for k in _DECLARED if k[1] in wanted and (kind is None or k[0] == kind)]:
                del _DECLARED[ключ]
        else:
            for ключ in [k for k in _DECLARED if k[0] == kind]:
                del _DECLARED[ключ]
        _RULES_CONSUMED = False


class RegistrySnapshot(NamedTuple):
    """Состояние реестра целиком — то, что :func:`restore` кладёт обратно.

    Полей два, потому что состояний тоже два: словарь объявлений и отметка
    «правила уже читались». Снимок без второго поля молча включал бы соседям
    предупреждения о «правило объявлено после сборки конфига» — тест, прочитавший
    правила, взводит ``_RULES_CONSUMED``, и без возврата отметка едет дальше по
    сессии.
    """

    #: Копия ``_DECLARED`` на момент снятия — именно копия, не вид.
    declared: Mapping[Tuple[str, str], Tuple[str, Optional[object]]]
    #: Значение ``_RULES_CONSUMED`` на момент снятия.
    rules_consumed: bool


def snapshot() -> RegistrySnapshot:
    """Снять состояние реестра. **Для тестов**, как и :func:`forget_declarations`.

    **Копия, а не вид, и это существенно.** Вид менялся бы вместе с реестром, и
    возврат по нему вернул бы ровно то состояние, от которого снимок защищал, —
    то есть не сделал бы ничего, оставаясь при этом зелёным.

    **Копия МЕЛКАЯ, и вот её честная граница** (ревью Ф0.5, находка 6). Прежняя
    редакция этой докстроки утверждала «значения словаря неизменяемы (кортеж
    „владелец, правило“), поэтому мелкой копии достаточно». Кортеж-обёртка
    действительно неизменяема, а вот ПРАВИЛО внутри неё — нет: ``LoggerRuleSchema``
    не ``frozen``, и ревьюер это воспроизвёл — мутация поля прошла, объект в снимке
    оказался тем же самым. Значит правило, изменённое тестом НА МЕСТЕ, ``restore()``
    не отменит: снимок держит ссылку, а не значение.

    Так и оставлено сознательно: правила приезжают импортом и на месте их никто не
    правит, а ``deepcopy`` схемы Pydantic на каждый снимок (а снимок берётся
    autouse-фикстурой перед КАЖДЫМ тестом двух модулей) — цена за защиту от того,
    чего не делают. Но граница названа, а не подразумевается: понадобится правка
    правила на месте — понадобится и глубокая копия.

    Прод-вызовов нет и быть не должно: реестр наполняется импортом, а импорт в
    живом процессе не отменяют.
    """
    with _LOCK:
        return RegistrySnapshot(declared=dict(_DECLARED), rules_consumed=_RULES_CONSUMED)


def restore(state: RegistrySnapshot) -> None:
    """Вернуть реестр К СОСТОЯНИЮ СНИМКА — тотально, а не «убрать лишнее».

    **Тотальность выбрана намеренно, и у неё есть цена.** «Убрать то, что
    появилось после» звучит мягче, но делает результат зависимым от истории
    вызовов: при двух живых снимках (session-scope фикстура плюс function-scope)
    возврат внешнего после внутреннего дал бы разное в зависимости от порядка.
    Тотальный возврат кладёт ровно содержимое снимка, и результат читается по
    одному аргументу.

    **Обратная сторона, которую нельзя забыть.** Объявление, приехавшее в реестр
    ИМПОРТОМ во время теста, возврат уносит навсегда: повторный ``import`` его не
    вернёт (модуль уже в ``sys.modules``, тело не исполняется). Поэтому фикстуры и
    сторож греют производителей ДО снятия снимка — иначе они сами становятся тем
    самым дефектом, который стерегут. Свойство проверено, а не объяснено:
    ``modules/tests/test_declarations_registry_hazards.py::TestRestoreCannotResurrectImports``.
    """
    global _RULES_CONSUMED
    with _LOCK:
        _DECLARED.clear()
        _DECLARED.update(state.declared)
        _RULES_CONSUMED = state.rules_consumed


def _same_rule(left: Optional[object], right: Optional[object]) -> bool:
    """Равны ли два правила по СОДЕРЖИМОМУ, а не по identity.

    Повторный импорт создаёт новый объект схемы с теми же полями, и сравнение по
    identity объявило бы конфликт там, где его нет, — то есть уронило бы процесс
    на совершенно законном reload.

    **Обычное ``==`` этого достаточно, и проверено это слом-инъекцией, а не
    предположением.** Первая редакция сравнивала ``model_dump()``, считая, что
    иначе сработает identity. Инъекция «сравнивать по identity» дала **ноль**
    красных — потому что `BaseModel.__eq__` Pydantic сравнивает поля сам, и ветка
    с ``model_dump`` не добавляла ничего, кроме двух словарей на каждый вызов.
    Убрана; свойство сторожит тест ``test_an_equal_rule_re_declared_passes``.
    """
    if left is None or right is None:
        return left is None and right is None
    return bool(left == right)

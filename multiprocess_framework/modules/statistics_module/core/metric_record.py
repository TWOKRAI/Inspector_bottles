# -*- coding: utf-8 -*-
"""
MetricRecord — dataclass для хранения и агрегации метрик.

Типы: counter, gauge, timing, histogram.

**Задача 2.2: timing и histogram живут на бакетах, а не на списке значений.**
Прежде обе дороги копили ``List[float]`` целиком (O(n) памяти в окне) и считали
p95 сортировкой сырого списка — число, которое математически не сливается: из
двух окон нельзя получить общий перцентиль, имея только их перцентили. Теперь
обе дороги — ОДНА механика (``count``/``sum``/``min``/``max``/``bucket_counts``):
память O(1) от числа наблюдений, ``count/min/max/avg`` остаются точными,
перцентиль становится оценкой по бакету, а слияние окон и процессов —
покомпонентным сложением (см. :meth:`MetricRecord.merged_with`).
"""

import math
from bisect import bisect_left
from dataclasses import dataclass, field, replace
from enum import Enum
from typing import Any, Dict, List, Optional, Tuple

#: Границы бакетов длительностей, **В СЕКУНДАХ**, плюс неявный ``+Inf`` справа.
#: Семантика границы — ``le`` (значение попадает в первый бакет, чья граница
#: ``>=`` значения), как в Prometheus-гистограммах.
#:
#: **Единица — секунды, потому что секунды принимает** ``StatsManager.record_timing``
#: (§2-П7 плана). Миллисекундные границы поверх секундных значений сложили бы
#: ВСЕ кадровые тайминги в первый бакет, и p95 стал бы константой при полностью
#: зелёном тесте памяти.
#:
#: **Почему 0.017 и 0.034, а не круглые 0.016 и 0.033.** Сетка рассчитана на
#: кадровые периоды: 1/60 = 0.0166666… и 1/30 = 0.0333333… — оба ЧУТЬ БОЛЬШЕ
#: круглых значений. При ``le`` граница 0.016 отправила бы штатный 60-fps кадр
#: (0.016667 > 0.016) в следующий бакет, а 0.033 — штатный 30-fps кадр
#: (0.033333 > 0.033) в бакет 0.050. Обе типовые частоты легли бы «на ступеньку
#: выше», и распределение читалось бы как систематическое опоздание, которого
#: нет. Границы 0.017 / 0.034 накрывают настоящий период с запасом ~2 %.
#:
#: **Три под-миллисекундные границы стоят первыми, и это не запас на будущее.**
#: Замер ревью по восьми живым процессам: у `command_manager.command.execution.
#: duration` (n=8671) и `dispatcher.dispatch.duration` (n=15389) **99.28 % из
#: 24 060 наблюдений лежали в первом бакете** прежней сетки (≤ 1 мс), и
#: перцентиль вырождался — `p95 == max` у 63.6 % агрегатов против 0 % у модели
#: со списком. Сетка, начинавшаяся с 1 мс, была слепа к диапазону, в котором
#: живут ВСЕ сегодняшние боевые тайминги: они микросекундные, а не кадровые.
#: Кадровый эмитент, под который подбирались 0.017/0.034, пока не существует —
#: приёмочный «контроль вырождения» проверял именно его и потому ничего не
#: поймал.
#:
#: Менять сетку дёшево сейчас и дорого потом: записи живут в сторе ~93 ч,
#: `bucket_bounds` едут вместе с ними, и после смены пришлось бы различать
#: две сетки по самим границам.
#:
#: Ручкой НЕ делается сознательно (решение спеки Р2.2-1): второго потребителя
#: с другой сеткой сегодня нет, а настраиваемые границы означают, что запись в
#: сторе живёт дольше своей константы. Границы едут в снапшоте ОДИН раз
#: (``bucket_bounds``), чтобы прочитанная через сутки запись оставалась читаемой.
DEFAULT_DURATION_BUCKETS_SEC: Tuple[float, ...] = (
    0.0001,
    0.00025,
    0.0005,
    0.001,
    0.002,
    0.005,
    0.010,
    0.017,
    0.034,
    0.050,
    0.100,
    0.250,
    1.0,
)

#: Число счётчиков: по одному на границу + один на ``+Inf``.
_BUCKET_SLOTS = len(DEFAULT_DURATION_BUCKETS_SEC) + 1


class MetricType(str, Enum):
    """Тип метрики."""

    COUNTER = "counter"
    GAUGE = "gauge"
    TIMING = "timing"
    HISTOGRAM = "histogram"


#: Типы, живущие на бакетах. Перечислены ОДИН раз: пока проверка стояла бы в
#: каждом месте своим сравнением, «починить timing и забыть histogram» было бы
#: делом одной невнимательной правки — ровно та развилка, из-за которой задача
#: 2.2 переводит обе дороги сразу (§2-П5).
DISTRIBUTION_TYPES = (MetricType.TIMING, MetricType.HISTOGRAM)


@dataclass
class MetricRecord:
    """Запись метрики с поддержкой агрегации.

    counter   — суммирует значения
    gauge     — хранит последнее значение
    timing    — count/sum/min/max + бакеты длительностей (секунды)
    histogram — то же самое, той же механикой

    ``count`` — СУММА значений счётчика (``add_counter(5)`` даёт 5).
    ``obs_count`` — ЧИСЛО наблюдений распределения. Поля РАЗНЫЕ, хотя наружу оба
    едут под ключом ``count`` (по своему типу): ключ записи не включает тип, и
    одно общее поле означало бы, что ``record_timing`` под именем счётчика
    накручивает его значение. Найдено прогоном золотого пути — счётчик показывал
    3.0 после одного ``record_metric`` и двух наблюдений.
    """

    name: str
    metric_type: MetricType
    tags: Dict[str, str] = field(default_factory=dict)

    # counter: сумма значений
    count: float = 0.0
    # timing/histogram: число наблюдений. Отдельно от ``count`` — см. докстринг.
    obs_count: int = 0

    # gauge
    value: Optional[float] = None

    # timing/histogram — одна механика на обе дороги
    sum_value: float = 0.0
    #: Границы наблюдавшегося диапазона. У распределений инициализируются
    #: ``+inf``/``-inf``, а не ``None``: сравнение с бесконечностью работает
    #: сразу, и на КАЖДОМ наблюдении экономятся две проверки ``is None`` — а
    #: наблюдение здесь и есть горячий путь. Наружу (:meth:`aggregate`) при
    #: пустой серии по-прежнему едет ``None``: «наблюдений не было» и
    #: «наблюдался ±inf» — разные вещи, и различает их ``count``.
    min_value: float = math.inf
    max_value: float = -math.inf
    bucket_counts: List[int] = field(default_factory=list)
    #: Наблюдения, отброшенные как NaN. Считаются отдельно и НЕ входят в
    #: ``count``: NaN не сравним ни с чем, поэтому одно такое значение навсегда
    #: отравило бы ``sum``/``min``/``max`` этой серии (``nan < x`` — False при
    #: любом x, и минимум больше никогда не обновится). Молча ронять наблюдение
    #: тоже нельзя — «следствие без причины»; поэтому счётчик, и он виден в
    #: агрегате, когда ненулевой.
    nan_dropped: int = 0

    def __post_init__(self) -> None:
        # Счётчики бакетов заводятся у ЛЮБОГО типа, а не только у распределений.
        # Довод — воспроизведённый прогоном золотого пути ОТКАЗ, а не симметрия:
        # ключ записи (`_metric_key`) состоит из имени и тегов и НЕ включает тип,
        # поэтому `record_metric("x")` с последующим `record_timing("x", …)`
        # достаёт из словаря запись типа COUNTER — и `observe` падал на ней
        # `IndexError: list index out of range`, роняя горячий путь эмитента.
        # Прежняя модель на том же месте молча дописывала значение в список.
        #
        # Аллокация здесь, а не ленивая проверка внутри `observe`: наблюдение —
        # горячий путь, и лишнее сравнение на КАЖДОМ вызове дороже 14 нулей на
        # запись (при потолке 1000 серий это ~0.1 МБ на процесс против
        # измеренной экономии в ~3100 раз).
        #
        # Само по себе это НЕ чинит столкновение типов: агрегат по-прежнему
        # ветвится по `metric_type`, поэтому тайминги, записанные под именем
        # счётчика, в снапшот не попадут. Дефект старше задачи 2.2 (у
        # `_ensure_record` тип не участвует в ключе), он назван и не тронут —
        # правка меняла бы форму ключа, а с ней и всю адресацию метрик.
        if not self.bucket_counts:
            self.bucket_counts = [0] * _BUCKET_SLOTS

    def add_counter(self, value: float = 1.0) -> None:
        """Добавить к счётчику."""
        self.count += value

    def set_gauge(self, value: float) -> None:
        """Установить gauge."""
        self.value = value

    def observe(self, value: float) -> None:
        """Учесть одно наблюдение длительности/величины — О(1) по памяти.

        Единственная точка учёта для timing И histogram: разные написания для
        двух дорог разошлись бы молча, а болеют они одним и тем же.

        Крайние значения названы, а не оставлены на «как получится»:

        * **NaN** — отбрасывается со счётом (:attr:`nan_dropped`). Довод узкий и
          именно про NaN: он не равен даже самому себе, поэтому попади он в
          ``min``/``max``, эти поля больше никогда не обновились бы (``nan < x``
          ложно при любом ``x``) — то есть испортился бы не только сам NaN, но и
          все последующие наблюдения серии. Проверка ``v != v`` истинна только
          для NaN и стоит одно сравнение — дешевле вызова ``math.isnan`` на
          горячем пути.
        * **Отрицательное и −Inf** — попадают в первый бакет. Отрицательная
          длительность бывает только у часов, шагнувших назад; выбрасывать
          наблюдение из-за этого дороже, чем показать его на дне шкалы.
        * **±Inf — ИЗВЕСТНОЕ поведение, не защищённое** (замечание ревью).
          Значение едет как есть: ``sum`` и ``avg`` серии становятся
          бесконечными, а вместе ``+inf`` и ``−inf`` дают ``nan``; в стор такая
          запись уезжает как ``Infinity``/``NaN``, то есть невалидным JSON.
          Прежняя модель со списком вела себя ровно так же — это не регресс, и
          собственной защиты здесь не заводится: воспроизведённой жалобы нет, а
          отсев бесконечности на горячем пути стоил бы ещё одного сравнения на
          каждое наблюдение. Названо, чтобы не выглядеть незамеченным.
        """
        # ``type(...) is float`` вместо безусловного ``float(value)``: штатный
        # эмитент присылает float, и вызов конструктора на горячем пути стоил
        # заметной доли всей операции. Нештатный вход (int, Decimal, строка с
        # числом) по-прежнему приводится — правило то же, цена платится только
        # тем, кто его нарушает.
        v = value if type(value) is float else float(value)
        if v != v:  # NaN — единственное значение, не равное самому себе
            self.nan_dropped += 1
            return
        self.obs_count += 1
        self.sum_value += v
        if v < self.min_value:
            self.min_value = v
        if v > self.max_value:
            self.max_value = v
        self.bucket_counts[bisect_left(DEFAULT_DURATION_BUCKETS_SEC, v)] += 1

    #: Прежние имена дорог. Оставлены тонкими псевдонимами ``observe``, потому
    #: что зовущий код (``AggregationWindow``, ``StatsManager``) говорит на
    #: языке типа метрики, а механика у них одна.
    def add_timing(self, duration: float) -> None:
        """Добавить наблюдение timing (секунды)."""
        self.observe(duration)

    def add_histogram(self, value: float) -> None:
        """Добавить наблюдение в гистограмму."""
        self.observe(value)

    def percentile(self, q: float = 0.95) -> Optional[float]:
        """Перцентиль ПО БАКЕТАМ — оценка, и это сказано вслух.

        ``rank = ceil(q · count)``; идём по накопленной сумме бакетов и берём
        ВЕРХНЮЮ границу первого бакета, где накоплено ``>= rank``. Результат
        зажимается сверху настоящим ``max``: на малых ``count`` граница бакета
        одна на всех, и без зажима серия из трёх наблюдений по 0.002 с
        отдавала бы p95 = 0.002 (граница), что случайно совпадает, но серия из
        трёх по 0.0011 отдала бы 0.002 при максимуме 0.0011 — число выше всего,
        что вообще наблюдалось.

        Попадание в бакет ``+Inf`` границы не имеет — отдаётся ``max``.

        Инвариант ``min <= p95 <= max`` держится по построению: в бакете, где
        сработал ранг, есть хотя бы одно наблюдение ``<= границы``, значит
        ``min <= граница``; сверху зажато ``max``.
        """
        n = self.obs_count
        if n <= 0:
            return None
        rank = math.ceil(q * n)
        cumulative = 0
        for index, bucket in enumerate(self.bucket_counts):
            cumulative += bucket
            if cumulative >= rank:
                if index >= len(DEFAULT_DURATION_BUCKETS_SEC):
                    return self.max_value
                bound = DEFAULT_DURATION_BUCKETS_SEC[index]
                return bound if bound < self.max_value else self.max_value
        return self.max_value

    def merged_with(self, other: "MetricRecord") -> "MetricRecord":
        """Слить две записи одной серии в НОВУЮ запись (окна, процессы).

        Чистая функция: ни одна из сторон не меняется. Слияние вызывается не на
        горячем пути (окно закрывается раз в 5–10 с), а цена одной лишней записи
        меньше, чем цена теста, который не может проверить ассоциативность,
        потому что операция мутирует свои аргументы.

        **Ассоциативность есть у counter, timing и histogram** —
        ``(a ⊕ b) ⊕ c == a ⊕ (b ⊕ c)``, потому что все составляющие
        (сумма, счётчик, поэлементная сумма бакетов, минимум, максимум)
        ассоциативны сами.

        **У gauge ассоциативности НЕТ, и это не дефект, а природа типа.**
        Gauge — «последнее известное значение», у слияния тут единственный
        осмысленный ответ «побеждает правый», и он зависит от порядка:
        ``(a ⊕ b) ⊕ c`` и ``a ⊕ (b ⊕ c)`` дают одно и то же значение c только
        потому, что правый всегда c; переставь аргументы — ответ другой.
        Названо здесь прямо, чтобы следующий читатель не написал тест
        ассоциативности на gauge и не «починил» его сведением к сумме.

        Raises:
            ValueError: у записей разные типы. Молча выбрать один из двух
                значило бы отдать наружу число, у которого нет смысла.
        """
        if self.metric_type != other.metric_type:
            raise ValueError(
                f"слияние записей разных типов: {self.metric_type.value} и {other.metric_type.value} "
                f"(метрика {self.name!r})"
            )

        # ``replace`` копирует поля ССЫЛКАМИ, поэтому ``tags`` (а у counter и
        # gauge ещё и ``bucket_counts``) достались бы результату общими с
        # ``self`` — правка одного меняла бы второй. Обещание «чистая функция»
        # было бы неверным ровно в том месте, где его читают. Копии здесь, а не
        # оговорка в докстринге: находка ревью, боевых вызывающих у слияния
        # пока нет, поэтому цена нулевая.
        if self.metric_type == MetricType.COUNTER:
            return replace(self, count=self.count + other.count, tags=dict(self.tags), bucket_counts=[])

        if self.metric_type == MetricType.GAUGE:
            # Побеждает ПРАВЫЙ: слияние читается как «поверх старого легло новое».
            return replace(
                self,
                value=other.value if other.value is not None else self.value,
                tags=dict(self.tags),
                bucket_counts=[],
            )

        # ``min``/``max`` без спецслучая «пусто»: у пустой стороны там ``+inf``
        # и ``-inf``, то есть нейтральные элементы обеих операций. Ровно ради
        # этого границы и инициализируются бесконечностями, а не ``None``.
        return replace(
            self,
            obs_count=self.obs_count + other.obs_count,
            sum_value=self.sum_value + other.sum_value,
            min_value=min(self.min_value, other.min_value),
            max_value=max(self.max_value, other.max_value),
            bucket_counts=[a + b for a, b in zip(self.bucket_counts, other.bucket_counts)],
            nan_dropped=self.nan_dropped + other.nan_dropped,
            tags=dict(self.tags),
        )

    def aggregate(self) -> Dict[str, Any]:
        """Вычислить агрегированный снапшот для flush.

        **Форма сохранена ключ-в-ключ** (решение Р2.2-3): у timing и histogram
        как были, так и остались ``count``/``min``/``max``/``avg``/``p95``, и
        первые четыре по-прежнему ТОЧНЫЕ — их считают не по бакетам. Изменился
        только способ получения ``p95`` (оценка по бакету, см.
        :meth:`percentile`). Читатели агрегата — команды ``get_metrics`` /
        ``get_metric``, консоль и строка ``performance.log`` — правки не
        требуют.

        **Добавлены** ``sum`` и ``buckets`` (только счётчики, без границ).
        Границы едут ОДИН раз на весь снапшот
        (``AggregationWindow._build_snapshot`` → ``bucket_bounds``): в каждой
        записи они стоили бы ~90 байт на метрику на дороге, у которой предел
        строки 2048 байт, — то есть прямо уменьшали бы число метрик в такте.
        """
        result: Dict[str, Any] = {
            "name": self.name,
            "type": self.metric_type.value,
            "tags": dict(self.tags),
        }

        if self.metric_type == MetricType.COUNTER:
            result["count"] = self.count

        elif self.metric_type == MetricType.GAUGE:
            result["value"] = self.value

        else:
            n = self.obs_count
            result["count"] = n
            if n:
                result["min"] = self.min_value
                result["max"] = self.max_value
                result["avg"] = self.sum_value / n
                result["p95"] = self.percentile(0.95)
            else:
                result["min"] = result["max"] = result["avg"] = result["p95"] = None
            result["sum"] = self.sum_value
            result["buckets"] = list(self.bucket_counts)
            if self.nan_dropped:
                # Ключ появляется ТОЛЬКО при ненулевом счётчике: постоянный ноль
                # весил бы в каждой записи на дороге с пределом строки и читался
                # бы как «эту проверку кто-то делает», а не «здесь что-то было».
                result["nan_dropped"] = self.nan_dropped

        return result

    def to_dict(self) -> Dict[str, Any]:
        """Сериализация для get_metric / get_all_metrics."""
        return self.aggregate()

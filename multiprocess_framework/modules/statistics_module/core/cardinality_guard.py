# -*- coding: utf-8 -*-
"""
CardinalityGuard — потолок числа уникальных серий (задача 2.2, решения Р2.2-5…9).

**Что такое серия.** Единица учёта метрик — не имя, а пара «имя × набор тегов»
(ключ ``_metric_key``). Живой замер стенда ``webcam_sketch`` 2026-08-13 показал,
что взрыв даёт именно теги, а не имена: у процесса ``devices`` **384 серии на 4
имени**, у ``ProcessManager`` — 288 на 10, у ``camera_0`` — 206 на 6. Тег
``command``/``key``, куда кладут имя команды, — главный источник. Потолок «на
имя» такого не поймал бы вовсе.

**Две позиции, один страж** (Р2.2-5). Серии копятся в ДВУХ местах:

1. ``AggregationWindow._metrics`` — чистится каждым сбросом окна;
2. ``StatsManager._metrics`` — живой справочник для ``get_metric`` /
   ``get_all_metrics``, не чистится ВОВСЕ (``reset_metrics`` зовут вручную) и
   растёт весь срок процесса: 226 серий за две минуты на ``camera_0``.

Позиции разные, поведение — одно, поэтому реализация здесь одна, а экземпляров
два. Два написания одного правила разошлись бы молча — оплаченный урок «одна
функция — две позиции».

**Стражи независимы** (Р2.2-7). Отказ ЖИВОГО слоя не мешает доставке: серия всё
равно едет в окно, в tap'ы и в стор — он ограничивает только поверхность
запроса ``get_metric``/``get_all_metrics``. Потерять доставку ради ограничения
справочника было бы дороже самой болезни.
"""

import threading
from typing import Any, Callable, Dict, List, Mapping, Optional

#: Дефолта потолка здесь НЕТ сознательно: его единственная позиция —
#: ``StatsManagerConfig.max_series`` (схема). Механизму дефолт не нужен — страж
#: без потолка не поднимают вовсе, — а вторая копия числа рядом с механизмом
#: разошлась бы со схемой молча. Заодно это снимает цикл импорта: схема
#: конфига не может импортировать ничего из пакета ``core``, потому что его
#: ``__init__`` тянет ``StatsManager``, который тянет саму схему (проверено —
#: ``ImportError: partially initialized module``).
#:
#: Сколько имён отказанных серий запоминается для голоса и для машинных чисел.
#: Константа, а не вторая ручка: «порог-сумма прячет слепоту» — судить надо
#: поимённо, но полный список отказанных имён на взрыве кардинальности сам стал
#: бы взрывом.
VOICE_NAME_LIMIT = 5

#: Адрес ручки в тексте предупреждения. WARNING без адреса не говорит, ЧТО
#: править, — находка Ф8.5, оплаченная дважды.
MAX_SERIES_KNOB = "observability.stats.max_series"


class CardinalityGuard:
    """Решает, пускать ли НОВУЮ серию, и считает отказы.

    Страж ничего не хранит из чужого: множество известных ключей ему передают
    на каждый вызов — это словарь владельца, единственная копия. Своей копии
    нет сознательно: она разошлась бы с владельцем при любой чистке (окно
    чистится каждым сбросом), и потолок начал бы считать несуществующие серии.
    """

    def __init__(
        self,
        limit: int,
        *,
        position: str = "",
        warn: Optional[Callable[[str], None]] = None,
    ) -> None:
        """
        Args:
            limit: потолок числа серий; ``0`` и меньше — без предела.
            position: имя позиции для текста предупреждения («окно агрегации»,
                «живой слой»). Без него два одинаковых WARNING было бы не
                различить, а лечатся они разным.
            warn: куда сказать вслух. ``None`` — молча (страж, поднятый без
                логгера, например в тесте окна отдельно от менеджера).
        """
        self._limit = max(0, int(limit))
        self._position = position
        self._warn = warn
        #: Свой лок — потому что позиции ДВЕ и локи у владельцев РАЗНЫЕ
        #: (``AggregationWindow._lock`` и ``StatsManager._metrics_lock``).
        #: Штатно ``allow`` зовётся уже под локом владельца, и этот лок тогда
        #: не оспаривается ни разу; но ручку ``set_limit`` дёргает поток
        #: ``config.reload``, который лока владельца НЕ держит, а ``report``
        #: читают из диагностики. Отсутствие своего лока сделало бы
        #: рассогласование счётчика и списка имён вопросом времени.
        self._lock = threading.Lock()
        #: Отказанные ЭМИССИИ с последнего :meth:`take_report` — период ОКНА.
        #: Это НЕ число серий: одну и ту же отказанную серию эмитент шлёт снова
        #: и снова, и каждая попытка считается здесь.
        self._dropped = 0
        #: Отказанные эмиссии за весь срок стража. Два счётчика, а не один,
        #: потому что и вопросов два: «сколько в ЭТОМ окне» (едет в записи
        #: снапшота и обнуляется вместе с окном) и «сколько всего» (диагностика
        #: процесса). Один счётчик на оба ответа врал бы на любом из них.
        self._dropped_total = 0
        #: РАЗЛИЧНЫЕ отказанные ключи. Отдельная величина от счётчика эмиссий,
        #: и различие несущее: ``total_count`` снапшота означает «сколько СЕРИЙ
        #: было в окне», а не «сколько эмиссий отвергнуто». Пока здесь стоял
        #: счётчик эмиссий, запись противоречила сама себе — «опущено 9» рядом
        #: с тремя именами (находка ревью, воспроизведена: 6 эмиссий трёх
        #: отказанных серий давали ``total_count=12`` при шести настоящих).
        #:
        #: Множество ОГРАНИЧЕНО тем же ``max_series``: наивный ``set`` взорвался
        #: бы ровно на том сценарии, который потолок и лечит — на потоке
        #: уникальных ключей. Второй ручки для его размера не заводится: память
        #: остаётся ограниченной одной величиной, и оператору не надо
        #: согласовывать две.
        self._refused_keys: set = set()
        #: Множество насытилось — значит ``series`` стало ОЦЕНКОЙ СНИЗУ. Признак
        #: отдельный, а не подразумеваемый: молчаливая оценка, выглядящая точным
        #: числом, — тот самый класс, который этот этап и вычищает.
        self._refused_saturated = False
        #: Первые ``K`` РАЗЛИЧНЫХ имён текущего периода (забираются вместе с
        #: отчётом окна) и за весь срок (для голоса). Два списка по той же
        #: причине, что два счётчика: у записи снапшота период — окно, у
        #: предупреждения оператору — процесс.
        self._names: List[str] = []
        self._names_total: List[str] = []
        #: Мы СЕЙЧАС упёрты в потолок? Голос звучит на переходе
        #: «под потолком → уперлись», а не на каждой эмиссии: путь горячий, и
        #: WARNING на каждый отказанный кадр сам стал бы штормом.
        self._at_ceiling = False
        #: Голос задолжали, но ещё не произнесли. Подробности — в :meth:`speak`.
        self._voice_owed = False

    @property
    def limit(self) -> int:
        """Действующий потолок — читается у ЖИВОГО стража.

        Readback обязан спрашивать это, а не пересчитывать из конфига:
        пересчёт дал бы то же число и при полностью несработавшей пересборке
        («effective = эхо запроса», major-13 соседней задачи).
        """
        return self._limit

    def set_limit(self, limit: int) -> None:
        """Сменить потолок на лету (``config.reload``).

        Смена потолка — смена УСЛОВИЯ, поэтому право на голос возвращается:
        оператор, поднявший потолок и снова упёршийся, обязан услышать об этом
        второй раз.
        """
        with self._lock:
            new = max(0, int(limit))
            if new == self._limit:
                return
            self._limit = new
            self._at_ceiling = False

    def allow(self, key: str, known: Mapping[str, Any], name: str) -> bool:
        """Пустить ли серию ``key`` в ``known``.

        **Известный ключ проходит ВСЕГДА**, даже при заполненном потолке. Иначе
        живая метрика, уже стоящая в словаре, замолчала бы в тот момент, когда
        справочник переполнился чужими сериями, — то есть потолок лечил бы рост
        ценой слепоты по тому, что уже наблюдают.

        **Но держат это свойство в бою НЕ здесь, и это надо знать.** Оба
        владельца (``AggregationWindow._ensure_record`` и
        ``StatsManager._ensure_record``) сперва берут запись из своего словаря и
        зовут ``allow`` ТОЛЬКО когда её там нет, — значит на обеих боевых
        дорогах ``key in known`` ложно всегда, и ветка ниже до них не достаёт.
        Проверено инъекцией: снятие этой ветки убивает ровно один тест — юнит
        самого стража, — а «известная серия не замолкает при переполнении» на
        уровне владельцев остаётся зелёным.

        Ветка оставлена намеренно как страховка для ТРЕТЬЕГО владельца, который
        мембершип не проверит; но выдавать её за причину, по которой свойство
        держится сегодня, нельзя: два предохранителя на одном свойстве прячут,
        который из них работает, и уверенное неверное объяснение переживает баг.

        Args:
            key: ключ серии (имя + отсортированные теги).
            known: словарь владельца — единственный источник «сколько уже есть».
            name: ИМЯ метрики (без тегов) для голоса. Имя, а не ключ: оператору
                нужно знать, какую метрику чинить, а ключ с сотней тегов в
                WARNING нечитаем.

        Returns:
            ``True`` — серию заводить; ``False`` — отказ, отказ уже посчитан.
        """
        if key in known:
            return True
        if self._limit and len(known) >= self._limit:
            self._refuse(key, name)
            return False
        # Новая серия прошла — значит мы под потолком. Право на голос
        # возвращается само, без отдельного вызова со стороны владельца:
        # окно чистится сбросом, и «условие снялось» иначе пришлось бы
        # сообщать стражу вручную из двух разных мест.
        if self._at_ceiling:
            with self._lock:
                self._at_ceiling = False
        return True

    def _refuse(self, key: str, name: str) -> None:
        """Учесть отказ и, если это переход в упор, ЗАДОЛЖАТЬ голос.

        Считаются ДВЕ разные величины: эмиссии (каждая попытка) и различные
        ключи (сколько серий не пущено). Смешивать их нельзя — на них отвечают
        разные вопросы, и именно смешение дало запись, противоречащую самой
        себе.
        """
        with self._lock:
            self._dropped += 1
            self._dropped_total += 1
            if key not in self._refused_keys:
                # Потолок множества — не меньше числа имён, которые мы всё равно
                # запоминаем. Иначе при крошечном ``max_series`` запись говорила
                # бы «опущено серий 3» рядом с ЧЕТЫРЬМЯ именами (поймано
                # прогоном золотого пути) — ровно то самопротиворечие, из-за
                # которого счёт эмиссий и признали дефектом. Инвариант:
                # ``series_dropped >= len(dropped_series)`` всегда.
                cap = max(self._limit, VOICE_NAME_LIMIT)
                if self._limit and len(self._refused_keys) >= cap:
                    # Множество упёрлось в тот же потолок. Дальше считать
                    # различные ключи не на что — говорим об этом вслух
                    # признаком, а не занижаем число молча.
                    self._refused_saturated = True
                else:
                    self._refused_keys.add(key)
            for bucket in (self._names, self._names_total):
                if name and name not in bucket and len(bucket) < VOICE_NAME_LIMIT:
                    bucket.append(name)
            if not self._at_ceiling:
                self._at_ceiling = True
                self._voice_owed = True

    def speak(self) -> None:
        """Произнести долг — на такте окна, а не на каждой эмиссии.

        **Два довода, и оба несущие.**

        *Первый — лок.* ``allow`` зовётся под локом владельца
        (``AggregationWindow._lock`` — обычный ``threading.Lock``, не
        реентерабельный), а запись предупреждения уходит в ``LoggerManager``,
        у которого свои каналы и свои tap'ы. Сегодня ни один из них метрик не
        эмитит — проверено; но tap, который начнёт это делать, замкнул бы
        цепочку ``allow → warning → record_metric → enqueue → тот же лок`` и
        повесил бы поток намертво. Шов разорван заранее.

        *Второй — содержание голоса.* Первая редакция звала ``speak`` сразу
        после отказа, и это давало бесполезное предупреждение: переход в упор
        случается на ПЕРВОМ отказе, поэтому текст всегда сообщал «опущено 1
        (первые имена: одно)». Число и имена набираются позже — значит и
        говорить надо позже. Такт окна (5–10 с) даёт голосу полную картину и
        заодно убирает с горячего пути даже сравнение.

        Текст строится ЗДЕСЬ, а не замораживается в момент отказа, — по той же
        причине: замороженная строка снова несла бы числа первой секунды.
        """
        with self._lock:
            if not self._voice_owed:
                return
            self._voice_owed = False
            where = f" ({self._position})" if self._position else ""
            about = "не меньше чем" if self._refused_saturated else ""
            series = f"{about} {len(self._refused_keys)}".strip()
            text = (
                f"потолок серий метрик{where} достигнут: {self._limit} — "
                f"новые серии не заводятся, опущено серий {series} "
                f"({self._dropped_total} эмиссий; первые имена: "
                f"{', '.join(self._names_total) or '—'}). "
                f"Потолок задаётся ключом {MAX_SERIES_KNOB} (0 — без предела)."
            )
        if self._warn is not None:
            self._warn(text)

    def report(self) -> Dict[str, Any]:
        """Машинные числа отказа для диагностики — НЕ сбрасывает.

        Ключи отчёта названы так, чтобы их нельзя было перепутать:

        * ``series`` — сколько РАЗЛИЧНЫХ серий не пущено. Это число едет в
          ``total_count`` снапшота и отвечает на вопрос «сколько метрик было в
          окне»;
        * ``observations`` — сколько ЭМИССИЙ отвергнуто. Одна отказанная серия
          даёт столько, сколько раз её прислали. Величина законная, но другая;
        * ``series_is_lower_bound`` — множество различных ключей упёрлось в
          потолок, и ``series`` занижено. Признак отдельный, потому что оценка,
          выглядящая точным числом, хуже честного «не меньше чем»;
        * ``names`` — первые ``K`` различных ИМЁН (без тегов), чтобы судить
          поимённо, а не по одной сумме.

        Все поля — за весь срок стража. Периодные (за окно) забирает
        :meth:`take_report`.
        """
        with self._lock:
            return {
                "series": len(self._refused_keys),
                "observations": self._dropped_total,
                "series_is_lower_bound": self._refused_saturated,
                "names": list(self._names_total),
            }

    def take_report(self) -> Dict[str, Any]:
        """То же, но со сбросом — для окна, где числа принадлежат ОКНУ.

        Окно живёт от сброса до сброса, и «сколько серий опущено» в его
        снапшоте обязано означать «в этом окне», а не «за всю смену»: иначе
        одно переполнение подсвечивало бы каждую следующую запись в сторе
        вплоть до перезапуска процесса.

        Сбрасывается и множество ключей — вместе со счётчиком эмиссий и
        именами. Иначе серия, отказанная однажды, продолжала бы считаться
        «опущенной в этом окне» до конца смены, и ``total_count`` завышался бы
        ровно так же, как он завышался эмиссиями до правки.
        """
        with self._lock:
            report = {
                "series": len(self._refused_keys),
                "observations": self._dropped,
                "series_is_lower_bound": self._refused_saturated,
                "names": list(self._names),
            }
            self._dropped = 0
            self._names = []
            self._refused_keys = set()
            self._refused_saturated = False
            return report

# -*- coding: utf-8 -*-
"""Версия кода фреймворка — то, что попадает в ``Resource`` каждой записи.

Отдельный модуль, а не строка в ``__init__.py``, по одной причине: вычисление
идентичности кода не должно происходить на импорте пакета — ``code_version()``
зовётся лениво, на сборке ``Resource``.

**Чем этот модуль НЕ является — проверено запуском (ревью Fable, 2026-08-05).**
``import multiprocess_framework.version`` не «лёгкий»: Python всегда исполняет
``__init__`` родительского пакета, и вместе с ним приезжают **440** модулей,
включая ``state_store``. Первая редакция докстринга утверждала обратное — это
был бы ровно запрещённый проектом класс «уверенное неверное объяснение».
Вреда в рантайме нет (к моменту вызова пакет давно загружен), но полагаться на
дешевизну этого импорта нельзя.

**Почему не хватало ручного ``__version__`` (решение владельца, ревью Ф3, Н-5).**
Константа ``"2.0.0"`` не менялась с 2026-04-25 — сквозь ``state_store``,
``chain`` и всю переделку наблюдаемости. То есть поле ``fw_version``, стоящее
в КАЖДОЙ записи, на вопрос «какой код это написал» не отвечало: два разных
среза дерева получали одно число. Второе число (``version = "0.1.0"`` в
``pyproject.toml``) версионирует несобираемый дистрибутив — ``[build-system]``
в проекте нет вовсе, — и выравнивание одной рукописной константы по другой
рукописной константе идентичности не добавило бы.

Идентичность даёт git: хеш отвечает на вопрос точно, и его нельзя забыть
поднять. Формат — локальная версия PEP 440::

    2.0.0+9950851b          # ровно этот коммит
    2.0.0+9950851b.dirty    # этот коммит ПЛЮС незакоммиченные правки
    2.0.0                   # git недоступен — идентичность неизвестна, и это видно

Суффикс ``.dirty`` обязателен: без него хеш врёт о том, какой код выполнялся,
а «правдоподобное неотличимо от проверенного» — ровно тот класс, ради которого
поле и заводилось. **Точность суффикса названа честно:** git отвечает про
грязь ВСЕГО репозитория, а не поддерева фреймворка — правка
``multiprocess_prototype/app.yaml`` пометит ``.dirty`` записи всех процессов
при нетронутом фреймворке. Ошибка направлена в безопасную сторону (грязное
никогда не назовётся чистым), и на этом основании принята.

**Известный предел (ревью Fable, 2026-08-05, не воспроизведён — нужен стенд с
вложенным репозиторием):** git ищет ``.git`` ВВЕРХ по дереву от ``cwd``.
Развёрнутая копия фреймворка внутри чужого git-репозитория получит хеш ЧУЖОГО
дерева — правдоподобный и ложный, то есть ровно тот дефект, против которого
поле и заводилось. Лечится сверкой ``git rev-parse --show-toplevel`` с
ожидаемым корнем либо ``GIT_CEILING_DIRECTORIES``; отложено до появления такого
развёртывания. Для frozen-сборок (PyInstaller) идентичность будет «неизвестна»
именно в проде — там версию надо запекать на этапе сборки.

Цена — один вызов ``git`` на процесс (замер: 35 мс), результат кэшируется на
время жизни процесса. Раздачи через env или конфиг сознательно нет: механизм
доставки стоил бы дороже, чем 35 мс однократно на старте, а форма доставки
конфига уже дважды была источником тихих дыр (5.12, Ф3 Б-7).
"""

from __future__ import annotations

import subprocess  # nosec B404 — единственный вызов ниже, argv литеральный, без shell
from pathlib import Path
from typing import Optional

__version__ = "2.0.0"

# Каталог пакета: git обязан спрашиваться про дерево ФРЕЙМВОРКА, а не про
# рабочий каталог процесса — он у воркера может быть любым.
_PACKAGE_DIR = Path(__file__).resolve().parent

_cached_code_version: Optional[str] = None


def _git_describe() -> str:
    """Сырой ответ git или пустая строка, если его нет.

    Ни одна ветка не вправе уронить процесс: отсутствие git, отсутствие
    ``.git`` (развёрнутая копия без истории), зависший вызов — всё это
    «идентичность неизвестна», а не сбой работы.
    """
    # ``nosec`` с названной причиной, а не молча:
    # B603 — argv литеральный, пользовательского ввода в нём нет ни одного байта,
    #        ``shell`` не включён, поэтому инъекции команды взяться неоткуда;
    # B607 — ``git`` ищется по PATH, и абсолютного пути тут не будет: он
    #        машинно-специфичен. Остаточный риск честно называется — подмена
    #        ``git`` в PATH даст выполнение чужого бинаря; но тот, кто управляет
    #        PATH процесса, уже управляет и самим процессом, так что этот вызов
    #        не расширяет поверхность атаки.
    try:
        result = subprocess.run(  # noqa: S603 — см. комментарий выше  # nosec B603 B607
            ["git", "describe", "--tags", "--always", "--dirty", "--abbrev=8"],
            cwd=str(_PACKAGE_DIR),
            capture_output=True,
            text=True,
            timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    if result.returncode != 0:
        return ""
    return result.stdout.strip()


def code_version() -> str:
    """Версия кода: семантическая часть плюс идентификатор коммита.

    Кэшируется на процесс — вызывается на инициализации каждого процесса, а
    ``Resource`` собирается один раз, так что второго вызова быть не должно
    даже теоретически; кэш стережёт от call-site'ов, которые появятся позже.
    """
    global _cached_code_version
    if _cached_code_version is None:
        raw = _git_describe()
        # Дефисы git'а → точки: локальный сегмент PEP 440 допускает только
        # буквы, цифры и точки.
        _cached_code_version = f"{__version__}+{raw.replace('-', '.')}" if raw else __version__
    return _cached_code_version

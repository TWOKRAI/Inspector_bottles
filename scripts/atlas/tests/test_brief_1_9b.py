_PIN_OUT: dict[str, list[str]] = {}


def _pin_lines(atlas: Any, pin_repo: GitRepo) -> list[str]:
    """Вывод `brief` на пине — один раз на модуль (холодный ≈ 40 с, дедлайн вызова 60 с)."""
    if "lines" not in _PIN_OUT:
        res = atlas(pin_repo, "brief", _TASK, *_PINNED)
        assert res.code == 0, f"brief на пине: код {res.code}, stderr: {res.err!r}"
        _PIN_OUT["lines"] = res.out.splitlines()
    return _PIN_OUT["lines"]


def test_pin_block_has_marker_and_grammar(pinned: GitRepo, atlas: Any) -> None:  # noqa: F811
    lines = _pin_lines(atlas, pinned)
    assert lines[0] == _LABEL_PIN
    opener = _OPEN_RE.match(lines[1])

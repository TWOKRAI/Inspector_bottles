def test_usage_errors(repo_factory: RepoFactory, atlas: Any, monkeypatch: pytest.MonkeyPatch) -> None:
    repo = brief_repo(repo_factory, monkeypatch)
    tasks = repo.path / _TASKS
    tasks.mkdir(parents=True)
    (tasks / "1.6.md").write_bytes(_hand("1.6", facts_label=True).encode("utf-8"))
    (tasks / "1.7.md").write_bytes(_hand("1.7", design=False).encode("utf-8"))
    (tasks / "1.8.md").write_bytes(_hand("1.8").encode("utf-8"))

    # контроль существования: корректный вызов без флагов работает; иначе 2 даёт и argparse на неизвестную подкоманду
    control = atlas(repo, "brief", "alpha#1.1")
    assert control.code == 0, f"контрольный вызов `brief alpha#1.1`: код {control.code}, stderr {control.err!r}"

    cases = {
        "--write вместе с --check": ("alpha#1.1", "--write", "--check"),
        "неизвестная задача": ("alpha#9.9",),
        "неизвестная задача с --write": ("alpha#9.9", "--write"),
        "--check на файле без маркеров": ("alpha#1.8", "--check"),
        "--check без файла": ("alpha#1.2", "--check"),
        "--write: метка FACTS без маркеров": ("alpha#1.6", "--write"),
        "--write: ни маркеров, ни DESIGN": ("alpha#1.7", "--write"),
    }
    for title, argv in cases.items():
        res = atlas(repo, "brief", *argv)
        assert res.code == 2, f"{title}: код {res.code}, stdout {res.out!r}, stderr {res.err!r}"
        assert res.err != "", f"{title}: причина не названа в stderr"
        assert "invalid choice" not in res.err, f"{title}: 2 дал argparse (подкоманды нет), а не brief"
    assert not (tasks / "1.1.md").exists(), "ошибка аргументов создала файл"



def test_pin_literals_replay(pinned: GitRepo, atlas: Any) -> None:  # noqa: F811
    """Каждая атлас-команда блока, повторённая как есть, даёт код 0 и литерал — подстрока stdout."""
    facts = _facts(_fact_lines(_pin_lines(atlas, pinned)))
    outputs: dict[str, Any] = {}
    replayed = 0
    for fact in facts:
        cmd = fact["cmd"]
        if not cmd.startswith("python -m scripts.atlas "):
            continue
        if cmd not in outputs:
            outputs[cmd] = atlas(pinned, *shlex.split(cmd)[3:])
        res = outputs[cmd]
        if fact["lit"] is not None:
            assert res.code == 0, f"{cmd}: код {res.code}, stderr {res.err!r}"
            assert fact["lit"] in res.out, f"литерал не подстрока вывода команды: {fact['lit']!r} <- {cmd}"
        else:
            assert res.code == int(fact["code"]), f"{cmd}: код {res.code}, ждали exit {fact['code']}"
        replayed += 1
    assert replayed >= 8, f"повторено строк {replayed}, нужно >= 8"
    assert len(outputs) >= 3, f"разных атлас-команд {len(outputs)}, нужно >= 3 (pack, ref, card)"



def _hand(task_id: str, *, facts_label: bool = False, design: bool = True) -> str:
    """Бриф, написанный руками: без маркеров; метка FACTS и DESIGN — по флагам."""
    text = f"# Task {task_id} — ручной бриф\n\nTASK: {task_id} — ручной бриф\nROLE: developer\n\n"
    if facts_label:
        text += "FACTS (написано руками):\n  - старая строка\n\n"
    if design:
        text += "DESIGN (decided by the lead):\n  1. первая строка\n  2. вторая строка\n\n"
    return text + "FILES:\n  1. m/widget.py\n"


def brief_repo(factory: RepoFactory, mp: pytest.MonkeyPatch, name: str = "b9") -> GitRepo:
    """Модуль m (класс Widget в m/widget.py, тесты), n вызывает класс в make_widget, p вызывает make_widget.

    Репозиторий построен так, что `pack alpha#1.1`, `ref m --symbol Widget`, `ref n --symbol make_widget` и
    `card m` уже работают: из недостающего остаётся только подкоманда `brief`.
    """
    mp.setenv("PYTHONDONTWRITEBYTECODE", "1")  # `pytest --collect-only` в репозитории не оставляет .pyc
    repo = new_repo(factory, name)
    exclude = repo.path / ".git" / "info" / "exclude"
    exclude.write_text(exclude.read_text(encoding="utf-8") + "__pycache__/\n*.pyc\n.pytest_cache/\n", encoding="utf-8")
    repo.write("modules.yaml", modules_yaml([("m", "scripts"), ("n", "scripts"), ("p", "scripts")]))
    put(repo, "plans/2026-10-01_alpha/plan.md", _PLAN)
    put(repo, "m/__init__.py", "")
    put(repo, "m/widget.py", _WIDGET)
    put(repo, "m/tests/test_x.py", _TEST_X)
    put(repo, "n/__init__.py", "")
    put(repo, "n/use.py", _USE)
    put(repo, "p/__init__.py", "")
    put(repo, "p/top.py", _TOP)
    put(repo, "misc/note.txt", "вне модулей\n")
    commit(repo, mp, "2026-10-01", "init")
    return repo


def test_write_skeleton_replace_insert(repo_factory: RepoFactory, atlas: Any, monkeypatch: pytest.MonkeyPatch) -> None:
    repo = brief_repo(repo_factory, monkeypatch)
    task = repo.path / _TASKS / "1.1.md"

    # 1. файла и каталога tasks/ нет -> каркас с метками по порядку, маркерами и литералами фикстуры
    assert not task.parent.exists()
    res = atlas(repo, "brief", "alpha#1.1", "--write")
    assert res.code == 0, res.err
    first = task.read_bytes()
    text = first.decode("utf-8")
    lines = text.splitlines()
    assert lines[0].startswith("# Task 1.1 — ")
    assert _labels(text) == _SKELETON_LABELS
    sha = repo.head[:7]
    assert [ln for ln in lines if _OPEN_RE.match(ln)] == [f"<!-- atlas:facts {sha} -->"]
    assert lines.count(_CLOSE) == 1
    open_at = next(i for i, ln in enumerate(lines) if _OPEN_RE.match(ln))
    assert _label_index(text, "FACTS") < open_at < lines.index(_CLOSE) < _label_index(text, "DESIGN")
    lits = _lits(_fact_lines(lines))
    for lit in ("m/widget.py", "m/tests/test_x.py:1  импорт, тестов 2", "n/use.py:5  вызов", "p/top.py:5  вызов"):
        assert lit in lits, f"в блоке нет литерала {lit!r}"

    # 2. повтор на том же HEAD -> файл прежний байт в байт
    assert atlas(repo, "brief", "alpha#1.1", "--write").code == 0
    assert task.read_bytes() == first

    # 3. текст вне блока, дописанный руками, цел; HEAD сменился -> блок заменён, а не продублирован
    edited = [lines[0], "Ручная заметка под заголовком.", *lines[1:], "Ручная строка в конце файла."]
    task.write_bytes(("\n".join(edited) + "\n").encode("utf-8"))
    put(repo, "m/widget.py", _WIDGET + "\n    def stop(self) -> int:\n        return 2\n")
    commit(repo, monkeypatch, "2026-10-02", "m: stop")
    assert repo.head[:7] != sha
    res = atlas(repo, "brief", "alpha#1.1", "--write")
    assert res.code == 0, res.err
    new_text = task.read_text(encoding="utf-8")
    new_lines = new_text.splitlines()
    before, block, after = _split(edited)
    new_before, new_block, new_after = _split(new_lines)
    assert (new_before, new_after) == (before, after), "текст вне блока изменён"
    assert new_block != block
    assert [ln for ln in new_lines if _OPEN_RE.match(ln)] == [f"<!-- atlas:facts {repo.head[:7]} -->"]
    assert new_lines.count(_CLOSE) == 1
    assert _labels(new_text).count("FACTS") == 1

    # 4. файл без маркеров, но с DESIGN -> блок встаёт перед DESIGN; повтор не множит метку
    hand = _hand("1.3")
    hand_path = repo.path / _TASKS / "1.3.md"
    hand_path.write_bytes(hand.encode("utf-8"))
    res = atlas(repo, "brief", "alpha#1.3", "--write")
    assert res.code == 0, res.err
    inserted = hand_path.read_bytes()
    text = inserted.decode("utf-8")
    lines = text.splitlines()
    assert _labels(text) == ["TASK", "ROLE", "FACTS", "DESIGN", "FILES"]
    open_at = next(i for i, ln in enumerate(lines) if _OPEN_RE.match(ln))
    assert _label_index(text, "FACTS") < open_at < lines.index(_CLOSE) < _label_index(text, "DESIGN")
    _, block, _ = _split(lines)
    assert [ln for ln in lines if ln.strip() and ln not in block] == [ln for ln in hand.splitlines() if ln.strip()]
    assert atlas(repo, "brief", "alpha#1.3", "--write").code == 0
    assert hand_path.read_bytes() == inserted
    assert _labels(hand_path.read_text(encoding="utf-8")).count("FACTS") == 1

    # 5. CRLF: с маркерами (sha устарел -> блок переписывается) и без маркеров -> ни одного голого LF
    atlas(repo, "brief", "alpha#1.4", "--write")
    crlf_marked = repo.path / _TASKS / "1.4.md"
    lf_text = crlf_marked.read_text(encoding="utf-8")
    old_marker = f"<!-- atlas:facts {repo.head[:7]} -->"
    assert old_marker in lf_text
    crlf_marked.write_bytes(lf_text.replace(old_marker, "<!-- atlas:facts 0000000 -->").replace("\n", "\r\n").encode())
    assert atlas(repo, "brief", "alpha#1.4", "--write").code == 0
    data = crlf_marked.read_bytes()
    assert data.count(b"\r\n") > 0
    assert data.count(b"\r\n") == data.count(b"\n"), "в файле с CRLF появился голый LF (маркеры есть)"
    assert b"0000000" not in data
    assert [ln for ln in data.decode().splitlines() if _OPEN_RE.match(ln)] == [old_marker]

    crlf_bare = repo.path / _TASKS / "1.5.md"
    crlf_bare.write_bytes(_hand("1.5").replace("\n", "\r\n").encode("utf-8"))
    assert atlas(repo, "brief", "alpha#1.5", "--write").code == 0
    data = crlf_bare.read_bytes()
    assert b"atlas:facts" in data
    assert data.count(b"\r\n") == data.count(b"\n"), "в файле с CRLF появился голый LF (маркеров не было)"


def test_check_fresh_then_stale(repo_factory: RepoFactory, atlas: Any, monkeypatch: pytest.MonkeyPatch) -> None:
    repo = brief_repo(repo_factory, monkeypatch)
    task = repo.path / _TASKS / "1.1.md"
    assert atlas(repo, "brief", "alpha#1.1", "--write").code == 0
    written = task.read_text(encoding="utf-8")
    for cited in ("m/widget.py", "n/use.py:5  вызов", "p/top.py:5  вызов"):
        assert cited in written, f"предусловие: в блоке нет {cited!r}"
    commit(repo, monkeypatch, "2026-10-02", "brief 1.1")  # HEAD ушёл от маркера, рабочее дерево чистое

    def check() -> Any:
        return atlas(repo, "brief", "alpha#1.1", "--check")

    def edited_check(rel: str) -> Any:
        """Дописать строку в файл (без коммита), проверить, вернуть исходные байты."""
        path = repo.path / rel
        original = path.read_bytes()
        path.write_bytes(original + b"# edit\n")
        try:
            return check()
        finally:
            path.write_bytes(original)

    fresh = check()
    assert fresh.code == 0, fresh.out + fresh.err

    # m/__init__.py не назван ни в одном литерале: вход только как файл модуля из аргумента `ref`/`card`/`pack --module`

    assert opener["sha"] == _PIN7
    assert lines[-1] == _CLOSE
    assert sum(1 for ln in lines if _OPEN_RE.match(ln)) == 1
    assert lines.count(_CLOSE) == 1

    block = lines[2:-1]
    assert len(block) >= 10, f"в блоке {len(block)} строк, нужно >= 10"
    facts = _facts(block)  # каждая строка по грамматике §2.5
    assert [ln for ln in block if re.match(r"^[ \t]*\d+\. ", ln)] == []
    assert _labels("\n".join(block)) == [], "строка блока открыла чужую метку (§2.4)"
    assert len(set(block)) == len(block), "в блоке есть точные дубли строк"

    bad_what = [m["what"] for m in facts if not _WHAT_RE.fullmatch(m["what"])]
    assert bad_what == [], f"«что» вне словаря DESIGN п. 4: {bad_what}"
    assert [m for m in facts if m["what"] in _LIVE_WHAT] == [], "живые строки на пине запрещены"
    live_cmds = [m["cmd"] for m in facts if m["cmd"].startswith(("python -m pytest", "git log --oneline --source"))]
    assert live_cmds == []
    # DESIGN п. 3: команда атлас-строки кончается `--ref <sha7> --main-ref <значение>` (main-ref задан явно)
    atlas_cmds = [m["cmd"] for m in facts if m["cmd"].startswith("python -m scripts.atlas ")]

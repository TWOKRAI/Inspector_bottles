# --- общие хелперы ------------------------------------------------------------------------------------------


def _labels(text: str) -> list[str]:
    from scripts.plans_ledger import _brief_label_positions

    return [name for _, name in _brief_label_positions(text)]


def _label_index(text: str, name: str) -> int:
    from scripts.plans_ledger import _brief_label_positions

    return next(idx for idx, label in _brief_label_positions(text) if label == name)


def _facts(block: list[str]) -> list[re.Match[str]]:
    """Каждая строка блока обязана лечь в грамматику §2.5; иначе — понятное сообщение."""
    found = []
    for line in block:
        match = _FACT_RE.match(line)
        assert match is not None, f"строка вне грамматики §2.5: {line!r}"
        found.append(match)
    return found


def _lits(block: list[str]) -> set[str]:
    return {m["lit"] for m in _facts(block) if m["lit"]}


def _pairs(block: list[str]) -> set[tuple[str, str]]:
    return {(m["what"], m["lit"]) for m in _facts(block) if m["lit"]}


def _split(lines: list[str]) -> tuple[list[str], list[str], list[str]]:
    """(до, блок, после): блок — от метки FACTS (если она прямо над маркером) до закрывающего маркера."""
    start = next(i for i, ln in enumerate(lines) if _OPEN_RE.match(ln))
    end = next(i for i, ln in enumerate(lines) if ln == _CLOSE and i > start)
    if start > 0 and lines[start - 1].startswith("FACTS ("):
        start -= 1
    return lines[:start], lines[start : end + 1], lines[end + 1 :]


def _fact_lines(lines: list[str]) -> list[str]:
    """Строки между маркерами."""
    start = next(i for i, ln in enumerate(lines) if _OPEN_RE.match(ln))
    end = next(i for i, ln in enumerate(lines) if ln == _CLOSE and i > start)
    return lines[start + 1 : end]



# -*- coding: utf-8 -*-
"""Публичные контракты плоскости документов.

Правило: внешние модули импортируют только отсюда и из ``__init__``.

**Почему это отдельная плоскость, а не kind в логах.** Диагностика отвечает на вопрос
«что происходило» и живёт дни: файлы ротируются, `ObservabilityStore` вообще не имеет
ретеншена и растёт, пока его не почистят руками. Документ отвечает на вопрос «что было
решено» — какая деталь признана браком, кто и когда сменил настройку наблюдаемости.
В промышленности такие записи хранят годами. Смешивать их с диагностикой нельзя в обе
стороны: чистка логов не должна уносить документ, а вечное хранение документов не должно
распространяться на диагностику.

**Почему сток, а не фильтр по уровню.** Допуск в долговечное хранилище фреймворка сегодня
гейтится severity (tap с ``min_level="ERROR"``), а документ — не severity: запись аудита
пишется на INFO/WARNING и потому не доезжает вообще (ADR-CRM-013, репро). Правило допуска
здесь выражено СТРУКТУРНО: у документа свой приёмник, и попадание в него не зависит от
уровня. Фильтра, который надо не забыть настроить, нет вовсе.

**Стык слоёв.** ``multiprocess_framework`` не имеет права импортировать ``Services``
(правило слоёв 9), поэтому фреймворк знает только :class:`IDocumentSink` — один вызов с
``dict``. Реализацию поверх SQL даёт этот пакет, сшивает композиционный корень
(``multiprocess_prototype``). Обратной зависимости не возникает.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Protocol, runtime_checkable

__all__ = [
    "KIND_AUDIT",
    "KIND_VERDICT",
    "IDocumentSink",
    "IDocumentStore",
]

#: Смена настройки наблюдаемости: кто, когда, чем, и что из этого не удалось.
KIND_AUDIT = "audit"
#: Решение о качестве изделия: «деталь N признана браком, уверенность 0.91».
KIND_VERDICT = "verdict"


@runtime_checkable
class IDocumentSink(Protocol):
    """Приёмник документов — ЕДИНСТВЕННОЕ, что видит фреймворк.

    Намеренно узкий: один метод, аргумент — ``dict`` (правило «Dict at Boundary»).
    Ни запросов, ни ретеншена здесь нет — читателю документов нужен
    :class:`IDocumentStore`, а фреймворк документы только пишет.
    """

    def append(self, document: Dict[str, Any]) -> bool:
        """Записать документ долговечно.

        Pre:
          - ``document["kind"]`` — непустая строка (род документа, напр. ``audit``)
          - ``document["ts"]`` — момент события, epoch-секунды (float)
          - остальные ключи произвольны и едут в ``payload`` как JSON

        Post:
          - при ``True`` документ доступен через :meth:`IDocumentStore.query`
          - при ``False`` документ НЕ записан, и отказ уже посчитан реализацией
          - исключение наружу не выходит: сбой хранилища не имеет права уронить
            того, кто породил документ (аудит зовётся из пути смены конфигурации)

        Invariants:
          - идемпотентности НЕТ: два одинаковых вызова дают две строки. Документ —
            это событие, а не состояние; дедупликация была бы потерей факта
        """
        ...


@runtime_checkable
class IDocumentStore(Protocol):
    """Хранилище документов: запись, чтение, срок хранения.

    Расширяет :class:`IDocumentSink` чтением и ретеншеном. Живёт в ``Services``,
    потому что документ — продуктовые данные (деталь, рецепт, оператор), а не
    механика фреймворка.
    """

    def append(self, document: Dict[str, Any]) -> bool:
        """См. :meth:`IDocumentSink.append`."""
        ...

    def query(
        self,
        kind: Optional[str] = None,
        since: Optional[float] = None,
        until: Optional[float] = None,
        limit: int = 100,
        offset: int = 0,
    ) -> List[Dict[str, Any]]:
        """Страница документов, свежие первыми.

        Pre:
          - ``limit > 0``
          - ``offset >= 0``
          - ``since``/``until`` — epoch-секунды либо ``None`` (граница не задана)

        Post:
          - результат отсортирован по ``ts`` убыванию
          - длина результата ``<= limit``
          - все элементы удовлетворяют заданным фильтрам одновременно (И, не ИЛИ)
        """
        ...

    def purge_expired(self, now: Optional[float] = None) -> int:
        """Удалить документы, чей срок хранения истёк. Вернуть число удалённых.

        Срок задаётся ПО ВРЕМЕНИ и per-kind, а не по количеству записей. Ротация по
        количеству (как у ``action_log``: 10 000 строк → архив) для документа не
        годится: срок хранения молча становится функцией загрузки линии, и на
        нагруженной смене месяц вердиктов уезжает за неделю.

        Pre:
          - ``now`` — момент отсчёта, epoch-секунды; ``None`` → текущее время

        Post:
          - удалены ровно те документы, у которых ``now - ts > retention(kind)``
          - документы рода, для которого срок НЕ задан, не удаляются никогда
            (неизвестный срок — не повод удалять: молчание конфига не является
            разрешением потерять документ о качестве)
          - возвращённое число равно количеству удалённых строк
        """
        ...

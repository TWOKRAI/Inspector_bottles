# -*- coding: utf-8 -*-
"""Режим «без присмотра»: живой GUI под автоматизацией, где кликать некому.

**Зачем.** Живой стенд наблюдаемости до сих пор поднимался с ``--headless``: без
презентационного overlay процесс ``gui`` остаётся ``HeadlessGuiProcess``, окон нет,
и нагрузка на плоскости беднее настоящей в разы (замер F1: строки 40–53 КБ с окнами
против ~1900 байт без них). Мерить фон по headless-стенду — значит подписывать число,
которого в бою не бывает. Мешало ровно одно: модальные окна. Приложение при закрытии
спрашивает «в редакторе топологии есть несохранённые правки, сохранить перед выходом?»
и **ждёт клика** — автоматический прогон вставал на shutdown (тот же класс, что
зависание 8+ минут на ``LoginDialog`` из Ф0.4).

**Два яруса, а не один.** Универсальный «закрывать все модалки» здесь неверен: у
вопроса «сохранить правки?» отказ по умолчанию (``reject``) означает «Отмена», то есть
окно НЕ закроется и приложение не выйдет — вместо ожидания клика получилось бы
молчаливое зависание на том же месте.

1. **Названные вопросы** отвечают явным решением ДО показа окна и пишут это решение
   в лог (:func:`auto_answer`). Единственный такой вопрос сегодня — несохранённые
   правки графа, и ответ ``discard``: автоматический прогон не имеет права писать
   рецепты (GUI-save переписывает yaml без комментариев).
2. **Всё остальное** — сторож (:func:`install_modal_watchdog`). В прогоне без
   присмотра любая другая модалка это дефект, а не сценарий: сторож её закрывает,
   называет классом и заголовком и считает. Прогон не встаёт и не притворяется
   чистым — след остаётся в логе.

**Выключено по умолчанию.** Ручка — env ``INSPECTOR_GUI_UNATTENDED=1``, снимок берётся
на импорте: ручка, читающая окружение на каждом обращении, прочитала бы и собственную
запись, сделанную позже, и режим менялся бы посреди прогона.

Живёт в прототипе, а не во фреймворке, намеренно: ярус 1 знает про конкретный вопрос
приложения. Если ярус 2 (сторож) понадобится второму приложению конструктора — переносить
его в ``frontend_module`` тогда, а не заранее.
"""

from __future__ import annotations

import os
from typing import Any, Callable, Optional

#: Имя ручки. Значение ``"1"`` — включено; всё остальное, включая отсутствие, — выключено.
ENV_UNATTENDED = "INSPECTOR_GUI_UNATTENDED"

#: Снимок на импорте — см. докстринг модуля.
_UNATTENDED: bool = os.environ.get(ENV_UNATTENDED) == "1"

#: Куда писать. Ставится один раз на старте GUI (``run_gui``) — это логгер процесса,
#: а не новый писатель: своих стоков модуль не заводит.
_log: Optional[Callable[..., None]] = None

#: Что ответили за оператора и что закрыл сторож. Наблюдаемость режима: живой прогон
#: обязан уметь показать, сколько раз система обошлась без человека.
_answers: list[tuple[str, str]] = []


def is_unattended() -> bool:
    """Включён ли режим без присмотра."""
    return _UNATTENDED


def set_logger(log: Callable[..., None] | None) -> None:
    """Отдать модулю логгер процесса (``process._log_warning``)."""
    global _log
    _log = log


def auto_answers() -> tuple[tuple[str, str], ...]:
    """Список пар «вопрос → ответ», данных без оператора (в порядке появления)."""
    return tuple(_answers)


def auto_answer(question: str, answer: str) -> None:
    """Записать ответ, данный за оператора, и сказать об этом вслух.

    Молчаливый автоответ хуже отсутствия режима: прогон выглядел бы так, будто вопроса
    не было, и потерянные правки объяснить было бы нечем.
    """
    _answers.append((question, answer))
    if _log is not None:
        _log(f"unattended.auto_answer: «{question}» → «{answer}» (оператора нет)", module="gui")


def install_modal_watchdog(app: Any, *, interval_ms: int = 250) -> Any:
    """Закрывать модалки, на которые никто не ответит. Возвращает таймер или ``None``.

    Таймер продолжает срабатывать внутри вложенного цикла событий, который открывает
    ``exec()``, — именно поэтому сторож работает там, где модалка уже висит.

    Владение — у ``app``: таймер без родителя пережил бы только ближайшую сборку мусора,
    и сторож умер бы молча, оставив прогон висеть на первой же модалке.
    """
    if not _UNATTENDED:
        return None

    from PySide6.QtCore import QTimer
    from PySide6.QtWidgets import QApplication, QDialog

    def _close_any_modal() -> None:
        widget = QApplication.activeModalWidget()
        if widget is None:
            return
        title = widget.windowTitle() or "<без заголовка>"
        name = type(widget).__name__
        _answers.append((f"{name}[{title}]", "closed-by-watchdog"))
        if _log is not None:
            _log(
                f"unattended.modal_closed: {name}[{title}] — модальное окно в прогоне без "
                "присмотра; закрыто сторожем. Это дефект сценария, а не штатный путь.",
                module="gui",
            )
        if isinstance(widget, QDialog):
            widget.reject()
        else:
            widget.close()

    timer = QTimer(app)
    timer.setInterval(interval_ms)
    timer.timeout.connect(_close_any_modal)
    timer.start()
    return timer


__all__ = [
    "ENV_UNATTENDED",
    "auto_answer",
    "auto_answers",
    "install_modal_watchdog",
    "is_unattended",
    "set_logger",
]
